def area_of(n):
    """목차에서 이 강의가 든 영역 이름."""
    for a, b, name in AREA_OF_LECTURE:
        if a <= n <= b:
            return name
    return None


def matches(n, q):
    """문항 q 가 n강에 맞는가. (맞으면 순위, 아니면 None)

    순위가 낮을수록 먼저 뽑힌다 — 강의의 한복판부터 준다.
      0…  concept 이 맞았다 (적어 둔 차례대로)
      50  area 만 맞았다 (종합 강의)
      90  지문이 맞았다 — 꼬리표가 못 말한 것이라 뒤로 민다
    """
    spec = LECTURE_MAP.get(n)
    if not spec:
        return None
    area, concept = q.get('area', ''), q.get('concept', '')
    areas = spec.get('area')
    if spec.get('wide'):
        return 50 if (areas and area in areas) else None
    if areas and area not in areas:
        return None
    for i, k in enumerate(spec.get('concept', [])):
        if k in concept:
            return i
    stem = spec.get('stem')
    if stem and re.search(stem, q.get('stem', '')):
        return 90
    return None
