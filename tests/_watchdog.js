/* ============================================================
   멈추는 검사는 실패하는 검사보다 나쁘다
   ------------------------------------------------------------
   브라우저 검사는 **영원히 기다릴 수 있는 자리**가 많다.
   `navigator.serviceWorker.ready` 에는 시간 제한이 없고, `waitForFunction`
   도 조건에 따라 안 끝난다. 하나가 멈추면 CI 는 30분 타임아웃까지 붙들려
   있다가 죽고, 통나무에는 "진행 중" 한 줄만 남는다 — **무엇이 잘못됐는지
   끝내 알 수 없다.**

   실제로 두 번 겪었다.
     · tests/offline.js — 세 번에 한 번 멈춰서 CI 를 40분 붙들었다
     · tests/hub-live.js — 통합 셸 검사에서 15분 넘게 안 끝났다

   그래서 브라우저를 띄우는 검사는 전부 파수꾼을 문다. 시간이 지나면
   **빨간불로** 끝나고, 마지막으로 찍힌 줄이 멈춘 자리를 가리킨다.

   쓰는 법 (파일 맨 위, require 바로 다음):
       require('./_watchdog.js')(240);   // 초. 기본 240

   환경 변수 TEST_MAX_SEC 로 한 번에 늘릴 수 있다.
   ============================================================ */
'use strict';

module.exports = function watchdog(seconds) {
  const max = Number(process.env.TEST_MAX_SEC || seconds || 240);
  const t = setTimeout(() => {
    console.log(`\n실패: ${max}초가 지나도 안 끝났다 — 위 마지막 줄이 멈춘 자리다.`);
    /* 브라우저가 살아 있어도 그냥 끊는다. 여기서 얌전히 닫으려 들면
       그 닫기가 또 안 끝날 수 있다. */
    process.exit(1);
  }, max * 1000);
  /* 검사가 제 시간에 끝나면 이 타이머가 프로세스를 붙들면 안 된다. */
  t.unref();
  return t;
};
