import re

P = 'build_t14_p5.py'
src = open(P, encoding='utf-8').read()

R = [
    # ── M02175 자가진단 — 3차에 본문에서 뺀 한정이 여기 남아 있었다 ─────────
    ("          '중성 원자라면 껍질이 하나 열리는 자리가 곧 값이 갑자기 크게 오르는 자리다.')",
     "          '껍질이 하나 열리는 자리가 곧 값이 갑자기 크게 오르는 자리다.')"),

    # ── M02177 ③ 논박 — '가장' 의 범위를 적는다 ─────────────────────────────
    ("          '이 표에서 가장 크지만 껍질 수도 둘과 넷으로 달라.",
     "          '네 선지 가운데 가장 크지만 껍질 수도 둘과 넷으로 달라."),
]

for a, b in R:
    n = src.count(a)
    assert n == 1, f'{n}곳: {a[:50]!r}'
    src = src.replace(a, b)

open(P, 'w', encoding='utf-8').write(src)

body = src[src.index('def build():'):]
body = '\n'.join(l for l in body.split('\n') if not l.strip().startswith('#'))

for w in ['중성 원자라면 껍질이 하나 열리는 자리가', '이 표에서 가장 크지만']:
    assert w not in body, f'물러난 문면이 남았다: {w}'

flat = re.sub(r"'\s*\n\s*'", '', body)
for w, k in [('껍질이 하나 열리는 자리가 곧 값이 갑자기 크게 오르는 자리다', 1),
             ('네 선지 가운데 가장 크지만', 1)]:
    n = flat.count(w)
    assert n == k, f'{w}: {n} ≠ {k}'

print('fix_t14_p5_r4 적용 완료 —', len(R), '곳')
