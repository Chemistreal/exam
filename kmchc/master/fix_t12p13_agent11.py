"""T12 P13 11차 조치 — 해설 문면 3 (선지·발문 변경 없음)

■ ★M01927 — 9차 조치가 만든 정면 충돌 (factchecker ✗)★
  "보어는 이 둘을 한 가정으로 막았어." 와
  "선스펙트럼 쪽은 여기에 한 걸음이 더 붙어." 가 ★같은 층위에서 '충분한가'를 두고
  서로 다른 답을 낸다.★ 9차에 '한 걸음이 더 붙는다'를 소리 내어 적어 8차의 어긋남을
  풀었는데, 정작 앞줄의 단언은 그대로 두었다. 앞줄을 '한 가정에서 출발해'로 낮춘다.
  ▸ 세 회차(8→9→11) 내리 같은 자리를 고치고 있다. 뒤에 오는 문장을 바꿀 때
    ★그 문장을 예고한 앞줄도 함께 보라★ 는 것이 이 자리의 교훈이다.

■ M01932 △ — 자가진단의 화살표가 문장과 반대 방향
  '도착 준위가 낮을수록(1 → 2 → 3) 에너지가 크다' — 괄호 안은 올라가는 방향인데
  앞 어절은 '낮을수록'이다. 요약 한 줄만 떼어 읽으면 뒤집힌다. (9차에 내가 넣은 자리다.)

■ M01934 △ — 배타 선언을 뒤 문장이 스스로 흐린다
  '빈 공간이라는 결론은 이 둘이 아니라 세 번째 결과에서 나와' 뒤에 10차가 넣은
  '되튐이 드물다는 것과 대부분이 지나갔다는 것은 같은 셈을 양쪽에서 읽은 거야' 가 온다.
  같은 셈이라면 '이 둘이 아니라'라는 배제가 무뎌진다. 앞줄을 '곧바로 말해 주는 것은
  아니고'로 완화한다(전면 모순은 아니므로 뒤 문장은 그대로 둔다).

■ solver 10차 '없습니다'(F1 0 · F5 0) · defender 8·9차 0건(입력 불변) · factchecker ✗ 1 △ 2
■ 반려 — M01936 '축은 값을 그대로 읽는 눈금이 아니라 자리를 읽는 눈금이거든'
  factchecker 가 '로그 축도 값을 읽는다'며 과장이라 했고 스스로 '판정을 낮출 정도는
  아니다'라고 닫았다. 이 문장은 ★10⁰ 칸을 '딱 1 eV'로 읽지 말라★ 는 경고이고 바로 뒤에
  실제 값(1.6 ~ 3.2 eV)을 밝혀 뜻이 흐려지지 않는다.
"""
import json, os

BANK = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'master_bank.json')


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:30]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


def main():
    bank = json.load(open(BANK, encoding='utf-8'))
    d = {x['id']: x for x in bank}

    sub(d['M01927'], '보어는 이 둘을 한 가정으로 막았어.', '보어는 이 둘을 한 가정에서 출발해 막았어.')
    sub(d['M01932'], '자가진단: 도착 준위가 낮을수록(1 → 2 → 3) 에너지가 크다.',
        '자가진단: 도착 준위가 1 · 2 · 3 으로 올라갈수록 에너지는 작아진다.')
    sub(d['M01934'], '원자가 대부분 비어 있다는 결론은 이 둘이 아니라 세 번째 결과,',
        '원자가 대부분 비어 있다는 결론은 이 둘이 곧바로 말해 주는 것이 아니고 세 번째 결과,')

    for x in bank:
        assert '**' not in x['stem'] and '**' not in x['solution'], x['id']
        assert '★' not in x['stem'] and '★' not in x['solution'], x['id']
    json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('P13 11차 조치 완료 — 해설 문면 3')


if __name__ == '__main__':
    main()
