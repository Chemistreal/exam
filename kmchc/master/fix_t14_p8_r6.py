"""T14 P8 6차 조치 — 오답의 겨냥은 그 오답이 어긴 것을 가리켜야 한다.

6차 보고. solver ★열 문항 정답 일치·전부 확실·차단 결함 0★ · defender ★[상] 0 ·
[중] 0 — 동결 권고★([중하] 셋 유지에 동의, 자기 대체안 하나 철회) ·
factchecker ★✗ 0 · △ 2★(1차 ✗1△5 → 2차 ✗2△8 → 3차 ✗1△4 → 4차 ✗0△3 →
5차 ✗1△4 → 6차 ✗0△2) · student-sim ★대체안 3/3 생존 · D 오답 0 ·
C/D 분리 3/10 회복★(4차 3 → 5차 1 → 6차 3).

★두 검증자가 스스로 자기 판정을 물렸다 — 되묻기가 값을 했다.★
  · defender 가 M02211 ① 대체안('같은 주기에서 왔는지')을 ★철회★ 했다. 발문의 경향이
    '같은 주기를 왼쪽에서 오른쪽으로' 인 이상 그 확인은 정답과 나란히 필요조건이 되어
    둘째 정답을 만든다는 내 반론을 그가 받았다.
  · student-sim 이 M02206 ①('65 pm')의 5차 사망 판정을 ★철회★ 했다. 네 프로필 어디에도
    부주의 채널이 없어 '묻는 대상을 잘못 읽는 오류' 를 겨냥한 선지는 이 모의로 판정할
    수 없다고 스스로 정리하고, 앞으로 그런 자리는 '죽음' 이 아니라 ★판정 보류(부주의
    표적)★ 로 적겠다고 했다. ▸ ★검증자의 판정도 그 검증자가 무엇을 잴 수 있는지에
    묶인다 — 잴 수 없는 것을 잰 판정은 되물어야 물러난다.★

5차에 갈아 끼운 넷은 세 검증자 모두 새 구멍이 없다고 확인했다. factchecker 는
M02208 새 ③ 이 ★교재 밖 사실에 비추어도 방향이 거꾸로★ 라고 검산했고(Goldschmidt
보정 CN12 = 1.00 · CN8 ≈ 0.97 · CN6 ≈ 0.96 · CN4 ≈ 0.88), defender 는 기하로도
확인했다. M02212 의 새 마디도 참이고 어긋난 마디는 여전히 ③ 하나뿐이다.

★① 오답의 겨냥은 그 오답이 어긴 것을 가리켜야 한다.★ (factchecker △1)
  M02208 ③ 의 겨냥과 해설 도입절을 '이웃의 촘촘함이 ★크기★ 를 정한다고 봄' 으로 적었다.
  그런데 이 문항이 묻는 것은 ★셈★ 이고, 배위수는 실제로 잰 반지름 값을 좌우한다
  (다만 방향이 반대다 — 이웃이 많은 쪽을 ★크게★ 잡는다). 그래서 이대로 두면 해설이
  '배위수는 크기와 무관하다' 로 읽혀 거짓을 함의한다.
  ▸ 겨냥과 도입절을 함께 '이웃의 촘촘함이 ★절반 내는 셈★ 을 바꾼다고 봄' 으로 되박는다.
    선지가 어긴 것은 크기에 대한 사실이 아니라 ★정의가 부르는 셈★ 이다.
  ▸ ★새로 얻는다 — 오답을 갈면 그 오답의 겨냥도 함께 간다. 문면만 갈고 겨냥을 두면
    해설이 선지가 어기지 않은 것을 어겼다고 말한다.★

★② 없던 것이 생긴 것을 '바뀌었다' 고 적지 않는다.★ (factchecker △2 · defender [하])
  M02212 ② 「전하의 부호가 바뀐다고 본 자리」 — 중성 원자의 전하는 0 이라 ★부호가
  없다.★ 바뀐 것이 아니라 플러스를 띠게 된 것이다. 해설 본문은 이미 '플러스를 띠는
  것은 실제로 일어난 일이야' 로 정확한데 선지와 단평만 헐거웠다.
  ▸ 「플러스를 띠게 되었다고 본 자리」 로 간다. 학생의 말('전하가 플러스로 바뀌었으니')
    을 그대로 짚으면서 표현만 정확해진다.
  ▸ 길이도 함께 센다 — factchecker 안('전하가 플러스가 되었다고 본 자리', 18자)을 쓰면
    산포가 0.26 이 되어 G3b 에 걸린다. 17자로 줄여 [14, 17, 15, 16] 로 맞춘다.
    ★검증자가 준 문면은 그 문항의 길이 판까지 보고 고른다.★

이월 하나 — defender 의 M02208 수치화 처방.
  세 검증자가 함께 짚었다 — 정답 ④ 가 발문 정의의 재진술이라 변별이 얕다. defender 가
  sim(발문에서 정의를 빼자)과 solver(그 정의 덕에 자족적이다)를 함께 만족시키는 길을
  냈다: 정의는 두고 발문에 이웃 거리 값을 넣어 ★정답을 재진술에서 적용 결과로★ 옮긴다.
  ▸ 옳은 진단이다. 다만 ★이것은 결함이 아니라 변별 개선★ 이고(defender 스스로 '반영하지
    않고 마감해도 결함으로 남지 않는다' 고 적었다), defender 가 준 선지 넷을 그대로 쓰면
    정답이 유일 최단이 되어 G3 에 걸린다(17자 대 31·33·45자). 길이 판을 다시 짜려면
    문항을 세 번째로 통째 다시 쓰는 셈이다.
  ▸ ★마감 기준은 결함 0 이다. 결함이 아닌 개선을 마감 조건으로 삼으면 배치는 닫히지
    않는다.★ P8 부채로 적고, 처방 자체는 ★P9 의 착수 지침★ 으로 옮긴다 — 정의를 발문에
    싣는 문항은 정답이 그 정의의 재진술이 되지 않도록 값을 하나 넣는다.

이월 여섯 — sim 의 죽은 선지 처방(M02205 ④ · M02207 ① · M02208 ② · M02209 ①③ ·
M02210 ④ · M02211 ② · M02213 ④).
  받지 않는 까닭을 셋으로 적는다.
  ㉠ ★죽은 선지를 갈면 다음 회차에 그 이웃이 죽는다 — 세 회차째 같은 무늬다.★ 4차에
    받은 다섯 가운데 셋이 5차에 죽었고, 5차에 받은 셋은 살았으나 6차에는 그 이웃 여섯이
    죽은 것으로 셌다. ★문면 교체는 죽는 자리를 옮길 뿐★ 이라는 것을 세 번 확인했다.
  ㉡ ★네 프로필 · 네 선지 · C=D 인 문항 일곱이면 죽는 자리는 산술적으로 일곱 언저리다.★
    sim 이 5차에 스스로 적은 셈이다. 여섯은 그 바닥보다 적다.
  ㉢ 개별 처방 가운데 하나는 ★그 자체로 참★ 이라 받을 수 없다 — M02210 ④ 안('안쪽 껍질
    전자까지 모두 더 세게 끌린다')은 한 주기를 훑는 동안 안쪽 전자도 실제로 더 세게
    끌리므로 참이다. ★F2 는 오답이 그 자체로 참인가로 잰다★ 에 정면으로 걸린다.
  ▸ 나머지는 P8 부채로 적고 ★P9 의 착수 지침★ 으로 옮긴다 — 오답을 쓸 때 그 오답을
    집을 프로필을 하나 지목하고, 지목할 프로필이 없으면 쓰지 않는다.
"""
import re

P = 'build_t14_p8.py'
src = open(P, encoding='utf-8').read()

CHOICES_RE = re.compile(r"\['(.+?)'\], (\d)", re.S)
BEFORE = CHOICES_RE.findall(src)
assert len(BEFORE) == 10
ANS_BEFORE = [a for _, a in BEFORE]


def sub(old, new, n=1):
    global src
    c = src.count(old)
    assert c == n, f'{c}곳(기대 {n}): {old[:56]!r}'
    src = src.replace(old, new)


# ══ M02208 ③ ── 겨냥과 도입절을 크기에서 셈으로 되박는다 ═══════════════════
sub("              ('이웃이 많은 쪽은 반지름을 작게 잡는다', '이웃의 촘촘함이 크기를 '\n"
    "               '정한다고 봄', 'causal')],",
    "              ('이웃이 많은 쪽은 반지름을 작게 잡는다', '이웃의 촘촘함이 절반 내는 '\n"
    "               '셈을 바꾼다고 봄', 'causal')],")
sub("          '③은 이웃의 촘촘함이 크기를 정한다고 보았어. 정의가 부르는 것은 이웃한 두 핵 '",
    "          '③은 이웃의 촘촘함이 절반 내는 셈을 바꾼다고 보았어. 정의가 부르는 것은 이웃한 '\n"
    "          '두 핵 '")

# ══ M02212 ② ── 없던 것이 생긴 것을 '바뀌었다' 고 적지 않는다 ═══════════════
sub("              '전하의 부호가 바뀐다고 본 자리',", "              '플러스를 띠게 되었다고 본 자리',")
sub("              ('전하의 부호가 바뀐다고 본 자리', '사실인 변화를 어긋난 자리로 봄',\n"
    "               'surface'),",
    "              ('플러스를 띠게 되었다고 본 자리', '사실인 변화를 어긋난 자리로 봄',\n"
    "               'surface'),")
sub("             '전하 = 두 수의 차이에서 생김 → 부호가 바뀐 것도 크기가 준 것도 전자가 '",
    "             '전하 = 두 수의 차이에서 생김 → 플러스를 띠게 된 것도 크기가 준 것도 전자가 '")
sub("           '전하의 부호가 바뀐다고 본 자리': '부호가 바뀐 것은 실제로 일어난 일이야.',",
    "           '플러스를 띠게 되었다고 본 자리': '전자를 잃으면 실제로 일어나는 '\n"
    "                                       '일이야.',")

open(P, 'w', encoding='utf-8').write(src)


# ── ★기계로 센다★ ─────────────────────────────────────────────────────────────
body = '\n'.join(l for l in src.split('\n') if not l.strip().startswith('#'))
body = body[body.index('def build('):]
flat = re.sub(r"'\s*\n\s*'", '', body)

BAN = ['이웃의 촘촘함이 크기를', '전하의 부호가 바뀐다고', '부호가 바뀐 것은 실제로',
       '부호가 바뀐 것도 크기가']
for w in BAN:
    assert w not in flat, f'옛 낱말이 남았다: {w!r}'
assert not re.search(r'[가-힣]★\s(를|을|은|의|으로|로|에서|에|과|보다|처럼|까지|부터'
                     r'|이고|이다|이야|이라|이지|인|야|다)(?=[\s,.·)?!\'"])', flat), \
    '★ 뒤에서 조사를 뗐다'
assert not re.search(r'[가-힣]\s(를|을|로)(?=[\s,.·)?!])', flat), '조사를 앞말에서 뗐다'

AFTER = CHOICES_RE.findall(src)
assert len(AFTER) == 10
assert [a for _, a in AFTER] == ANS_BEFORE, '정답 자리가 바뀌었다'
CH = [re.findall(r"'([^']+)'", f"'{blk}'") for blk, _ in AFTER]
assert all(len(c) == 4 for c in CH)

# ★겨냥이 선지가 어긴 것을 가리키는가★ — M02208 ③ 은 크기가 아니라 셈을 어겼다
s08 = flat[flat.index("T.mk('M02208'"):flat.index("T.mk('M02209'")]
assert s08.count('절반 내는 셈을 바꾼다고') == 2, 'M02208 겨냥과 해설 도입절이 어긋난다'

# ★길이 판을 다시 셌는가★ — M02212 의 정답은 유일 최장도 유일 최단도 아니어야 한다
c12 = CH[7]
L = [len(t) for t in c12]
assert L == [14, 17, 15, 16], f'M02212 길이 판이 어긋난다: {L} {c12}'
assert L[2] != max(L) and L[2] != min(L), 'M02212 정답이 길이의 끝에 섰다'

print('fix_t14_p8_r6 적용 완료 — 선지 하나 교체, 겨냥 둘·해설 넷 손질')
