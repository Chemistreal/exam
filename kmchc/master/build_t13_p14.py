def local_checks(items):
    import re
    bad = []

    # ① 관계식 3갈래 — 수치 선지 자리에서 '이상치가 정답' 도 '정답만 만족' 도 아닐 것
    REL = [('2의 거듭제곱', lambda v: v > 0 and (v & (v - 1)) == 0),
           ('4의 배수', lambda v: v % 4 == 0),
           ('홀수', lambda v: v % 2 == 1)]
    for x in items:
        vals = []
        for c in x['choices']:
            m = re.match(r'^(\d+)\s*(개|번째)?$', c.strip())
            if not m:
                vals = None
                break
            vals.append(int(m.group(1)))
        if not vals:
            continue
        av = vals[x['answer']]
        for name, f in REL:
            ok = [v for v in vals if f(v)]
            if len(ok) == 3 and av not in ok:
                bad.append(f"{x['id']} 관계식 '{name}' — 이상치가 정답({av})")
            if len(ok) == 1 and av in ok:
                bad.append(f"{x['id']} 관계식 '{name}' — 정답({av})만 만족")

    # ② 오답 유형이 한 문항 안에서 겹치지 않을 것
    for x in items:
        ts = [w['type'] for w in x['distractors']]
        if len(set(ts)) < len(ts):
            bad.append(f"{x['id']} 오답 유형 중복 — {ts}")

    # ③ 발문에 정답 문자열이 통째로 들어가 있지 않을 것
    for x in items:
        a = x['choices'][x['answer']]
        core = re.sub(r'[^0-9A-Za-z가-힣]', '', a)
        stem = re.sub(r'[^0-9A-Za-z가-힣]', '', x['stem'])
        if len(core) >= 6 and core in stem:
            bad.append(f"{x['id']} 발문에 정답이 통째로 들어 있음")

    # ④ ★오답끼리의 포함 관계★(P10 ㉯)
    for x in items:
        cs = [re.sub(r'\s+', '', c) for c in x['choices']]
        for i in range(4):
            for j in range(4):
                if i != j and len(cs[i]) >= 12 and cs[i] in cs[j]:
                    bad.append(f"{x['id']} 선지 포함 관계 — {i+1} 이 {j+1} 안에 들어 있음")

    # ⑤ ★선지에 적힌 수의 합 관계★(P10 ㉱)
    for x in items:
        nums = []
        for c in x['choices']:
            f = re.findall(r'\d+', c)
            nums.append(int(f[-1]) if f else None)
        if any(n is None for n in nums) or len(set(nums)) < 4:
            continue
        av = nums[x['answer']]
        pairs = [(i, j) for i in range(4) for j in range(i + 1, 4)
                 if i != x['answer'] and j != x['answer'] and nums[i] + nums[j] == av]
        if len(pairs) == 1:
            i, j = pairs[0]
            bad.append(f"{x['id']} 합 관계 — 정답 {av} = {nums[i]} + {nums[j]} (유일)")

    # ⑥ ★한 문항 안에서 정답만 홀로 다른 문말이 되지 않을 것★(P10 ㉮ · 형태 신호)
    for x in items:
        tails = [c.strip()[-4:] for c in x['choices']]
        at = tails[x['answer']]
        if tails.count(at) == 1 and len(set(tails)) == 2:
            bad.append(f"{x['id']} 문말 형태 — 정답만 '{at}' 로 끝남")

    # ⑦ 지시 대상표 — 이 배치가 쓰는 수치가 서로 어긋나지 않을 것
    REFERENT = {
        'N 껍질의 정원': 32, 'l=3 부껍질의 정원': 14, 'n=3 껍질의 오비탈 수': 9,
        '철의 원자 번호': 26, '크로뮴의 원자 번호': 24, '인의 원자 번호': 15,
        '알루미늄의 원자 번호': 13, '산소의 원자 번호': 8, '아르곤의 원자 번호': 18,
        '인의 홀전자 수': 3, 'Cr 의 3d 전자 수': 5, '탄소의 전자 수': 6,
    }
    for k, v in REFERENT.items():
        if v <= 0:
            bad.append(f'지시 대상표 오류 — {k}')

    # ⑧ 정답 길이 순위 (G3c 예고) — ★동률은 세지 않고, 표본이 넷 미만이면 비율을 재지 않는다★
    ranks = []
    for x in items:
        ls = [len(c) for c in x['choices']]
        a = x['answer']
        if ls.count(ls[a]) > 1:
            continue
        ranks.append(sum(1 for v in ls if v > ls[a]) + 1)
    if ranks:
        for r in (1, 4):
            if ranks.count(r):
                bad.append(f'정답이 최장 또는 최단인 문항 {ranks.count(r)}제 — G3 와 어긋남')
        if len(ranks) >= 4:
            for r in (2, 3):
                if ranks.count(r) / len(ranks) >= 0.80:
                    bad.append(f'정답 길이순위 rank{r} = {ranks.count(r)}/{len(ranks)} — 한쪽 쏠림')
    print(f'  정답 길이순위(동률 {len(items) - len(ranks)}제 제외): '
          f'{{2: {ranks.count(2)}, 3: {ranks.count(3)}}}')

    # ⑨ ★같은 규칙을 나눠 쓰는 자리는 배치 단위로 훑는다★(P13 ㉰)
    #    2n²·2(2l+1)·Σ(2l+1)=n²·l≤n−1 을 네 문항이 나눠 쓴다. 값이 겹치면 서로 답을 준다.
    RULE_VALUE = {'M02101': 32, 'M02105': 14, 'M02108': 9}
    seen = {}
    for mid, v in RULE_VALUE.items():
        if v in seen:
            bad.append(f'규칙 지도 — {seen[v]} 와 {mid} 가 같은 값 {v} 를 답으로 씀')
        seen[v] = mid
    d = {x['id']: x for x in items}
    if '14' in d['M02108'].get('solution', '') or '7 개' in d['M02108'].get('solution', ''):
        bad.append('M02108 해설이 M02105 의 값(l=3 → 7 → 14)을 끌어옴')
    if 'n²' in d['M02106'].get('solution', '') or '2l + 1' in d['M02106'].get('solution', ''):
        bad.append('M02106 해설이 근거를 l ≤ n−1 밖에서 끌어옴')
    if 'n²' in d['M02101'].get('solution', '').replace('2n²', ''):
        bad.append('M02101 해설이 M02108 의 결론(껍질의 오비탈 수 = n²)을 앞질러 말함')
    # ★같은 규칙을 쓰는 두 문항이 같은 (n, l) 대입값을 쓰지 않을 것★(factchecker 1차)
    for pair in [('M02106', 'M02109')]:
        a, bb = d[pair[0]], d[pair[1]]
        for combo in ['n 이 2 이고 l 이 2', 'n 이 2 이면 l 은']:
            if combo in a.get('solution', '') and combo in bb.get('solution', ''):
                bad.append(f'{pair[0]} 와 {pair[1]} 가 같은 대입값을 씀 — 앞엣것이 뒤엣것을 판정해 버린다')

    # ⑩ ★소재 제한은 표기 등장이 아니라 사용으로 좁힌다★(P13 ㉳ · 설계 §6)
    #    이온은 M02104 하나 · 크로뮴은 M02110 하나 · Z ≤ 30.
    for x in items:
        blob = x['stem'] + ''.join(x['choices']) + x.get('solution', '')
        if x['id'] != 'M02104' and ('이온이 될' in blob or '²⁺' in blob):
            bad.append(f"{x['id']} 이온 소재는 M02104 한 자리로 제한한다")
        if x['id'] != 'M02110' and '크로뮴' in blob:
            bad.append(f"{x['id']} 크로뮴은 M02110 한 자리로 제한한다")
        for z in re.findall(r'원자 번호 (\d+)', blob):
            if int(z) > 30:
                bad.append(f"{x['id']} 원자 번호 {z} — Z ≤ 30 을 넘음")

    if bad:
        print('\n  ❌ 저작 점검 실패')
        for b in bad:
            print(f'     · {b}')
        raise SystemExit(1)
    print('  ✅ 저작 점검 통과 (관계식·오답 유형·누설·포함·합·문말·길이순위·규칙 지도·소재 제한)')


