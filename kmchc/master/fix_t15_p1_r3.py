# -*- coding: utf-8 -*-
"""T15 P1 3차 조치 — 명세가 확정된 낮은 위험 넷.

㉠ M02305 발문의 셈법을 M02306 과 같은 강도로 통일한다(착수문서 §4 ㉢ — '크게 뛴다' 를
   낱말로 정의하는 것이 봉인의 목적이고, 두 셈법을 갈라 묻는 것이 아니다).
㉡ M02307 해설의 '마지막 두 자리' 괄호가 자리 하나만 적었다 → (O→F · F→Ne).
㉢ M02307 calc_check 의 '아흔 넘는 감소(99·88)' — 88 은 아흔을 넘지 않는다.
   solution·단평이 이미 '99 와 88 만큼' 이므로 세 필드를 한 문면으로 통일한다.
㉣ M02301 의 '제1 은 전자 하나를 떼는 값' — 이 문항의 정답 ①이 '전자 1몰' 이므로
   해설이 정답과 부딪힌다. calc_check·solution·단평 세 곳을 '전자 1몰만' 으로 통일한다.
㉤ M02303 발문이 떼는 순서를 정하지 않아 오답 ③('순서를 바꾸면 E₁ 이 E₂ 보다 커질 수 있다')이
   참이 될 길이 남았다 → 정의의 조건을 발문에 인쇄한다.
"""
import ast
import io
import pathlib
import re

SRC = pathlib.Path('build_t15_p1.py')
BEFORE = SRC.read_text(encoding='utf-8')
body = BEFORE


def rep(old, new, n=1):
    global body
    got = body.count(old)
    assert got == n, f'{got}곳(기대 {n}) — {old[:70]!r}'
    body = body.replace(old, new)


# ── ㉠ M02305 발문 — 셈법을 못 박고 개수 규칙을 함께 인쇄한다 ──
rep("'(단위 kJ/mol)이었다. 값이 크게 뛰는 자리 앞까지의 개수가 원자가전자 수일 때, 가의 '",
    "'(단위 kJ/mol)이었다. 이웃한 두 값의 비(뒤 ÷ 앞)로 재어 가장 크게 뛰는 자리를 급증 '\n"
    "             '자리라 하고, 그 자리 앞까지의 개수를 원자가전자 수라 할 때, 가의 '")

# 발문이 '가장' 을 못 박았으므로 해설도 발문의 낱말을 쓴다.
rep("'2745 → 11577 이 약 4.2배야. 가장 크게 뛰는 자리는 세 번째와 네 번째 사이지. 발문이 '\n"
    "          '그 자리 앞까지의 개수가 원자가전자 수라 했으니 셋이야 — ④가 옳아. '",
    "'2745 → 11577 이 약 4.2배야. 비가 가장 큰 자리는 세 번째와 네 번째 사이니 그 자리가 '\n"
    "          '급증 자리지. 발문이 그 앞까지의 개수가 원자가전자 수라 했으니 셋이야 — ④가 옳아. '")

# ── ㉡ M02307 해설 — '마지막 두 자리' 는 O→F 와 F→Ne 둘이다 ──
rep("'가운데이고 마지막 두 자리(F→Ne)에서는 오히려 커지지. '",
    "'가운데이고 마지막 두 자리(O→F · F→Ne)에서는 오히려 커지지. '")

# ── ㉢ M02307 calc_check — 88 은 아흔을 넘지 않는다 ──
rep("'안의 일 / ④ 어림의 오차로는 아흔 넘는 감소(99·88)를 설명하지 못함',",
    "'안의 일 / ④ 어림의 오차로는 99 와 88 만큼의 감소를 설명하지 못함',")

# ── ㉣ M02301 — 제1 은 '전자 하나' 가 아니라 '전자 1몰' 이다(정답 ①과 부딪혔다) ──
rep("'뒤집음 / ④ 는 전자 1몰을 모든 전자로 넓힘(제1 은 전자 하나를 떼는 값이다)',",
    "'뒤집음 / ④ 는 전자 1몰을 모든 전자로 넓힘(제1 은 원자 1몰에서 전자 1몰만 떼는 값이다)',")
rep("'④는 전자 1몰을 모든 전자로 넓혔어. 제1 이라는 이름이 말하듯 이 값은 전자 하나를 '\n"
    "          '떼는 값이고, 나머지 전자를 떼는 데 드는 에너지는 여기에 들어 있지 않아. '",
    "'④는 전자 1몰을 모든 전자로 넓혔어. 제1 이라는 이름이 말하듯 이 값은 원자 1몰에서 전자 '\n"
    "          '1몰만 떼는 값이고, 나머지 전자를 떼는 데 드는 에너지는 여기에 들어 있지 않아. '")
rep("'기체 원자 1몰에서 전자를 모두 떼는 데 496 kJ 이 든다': '제1 은 전자 하나의 '\n"
    "                                          '값이야.'},",
    "'기체 원자 1몰에서 전자를 모두 떼는 데 496 kJ 이 든다': '제1 은 전자 1몰만 '\n"
    "                                          '떼는 값이야.'},")

# ── ㉤ M02303 발문 — 떼는 순서를 정의의 조건으로 못 박는다 ──
rep("'어떤 원자에서 전자를 하나씩 떼어 갈 때 드는 에너지를 차례로 E₁, E₂, E₃ … 이라 하면 '\n"
    "             '어느 원소에서나 E₁ < E₂ < E₃ … 이다. 그 까닭으로 옳은 것은?',",
    "'어떤 원자에서 그때그때 가장 약하게 붙은 전자부터 하나씩 떼어 갈 때 드는 에너지를 차례로 '\n"
    "             'E₁, E₂, E₃ … 이라 하면 어느 원소에서나 E₁ < E₂ < E₃ … 이다. 그 까닭으로 '\n"
    "             '옳은 것은?',")

# ── 불변 검사 ──
GONE = ['값이 크게 뛰는 자리 앞까지의 개수가 원자가전자 수일 때',
        '마지막 두 자리(F→Ne)',
        '아흔 넘는 감소',
        '제1 은 전자 하나를 떼는 값이다',
        '이 값은 전자 하나를 ',
        '제1 은 전자 하나의 ']
WANT = ['이웃한 두 값의 비(뒤 ÷ 앞)로 재어 가장 크게 뛰는 자리를 급증 ',
        '그 자리 앞까지의 개수를 원자가전자 수라 할 때',
        '마지막 두 자리(O→F · F→Ne)',
        '99 와 88 만큼의 감소',
        '제1 은 원자 1몰에서 전자 1몰만 떼는 값이다',
        '원자 1몰에서 전자 ',
        '제1 은 전자 1몰만 ',
        '그때그때 가장 약하게 붙은 전자부터 하나씩 떼어 갈 때']
KEEP = ['578, 1817, 2745, 11577',
        'Be 900 에서 B 801 로',
        '496 kJ/mol',
        'E₁ < E₂ < E₃']

try:
    for g in GONE:
        assert g not in body, f'GONE 남음 — {g!r}'
    for w in WANT:
        assert w in body, f'WANT 없음 — {w!r}'
    for k in KEEP:
        assert k in body, f'KEEP 사라짐 — {k!r}'
    ast.parse(body)
except AssertionError:
    SRC.write_text(BEFORE, encoding='utf-8')
    raise

SRC.write_text(body, encoding='utf-8')
print('fix_t15_p1_r3 — 조치 여덟 곳(문항 넷) 적용')
