# -*- coding: utf-8 -*-
"""T13 P2 — 7차 조치 (M01988 한 문항 · 발문 한 절과 오답 하나).

5차 순회. **세 검증자가 두 회차 연달아 실체 0 건이다.**

    solver      10/10 · 자족성 전원 충분 · 6차에 닫은 두 우회로가 **실제로
                닫혔음을 확인**("M01988 소거 최대치 2 개, 최종 판별에는 4s/3d
                역전 지식이 필수" · "M01989 는 ①②③ 이 모두 주양자수 6 이라
                배치를 읽지 않으면 고를 수 없다"). 남긴 것은 M01988 확신도 '보통'.
    defender    ★진짜 F2 실패 후보 없음★ 정답 쪽이 조건부 참인 자리도 없다고
                따로 확인했다. 남긴 것은 M01988 ② 표현 하나.
    factchecker ★사실 오류 없음 · 번호 어긋남 없음 · 문항 사이 모순 없음★
                6차에 손댄 여섯 자리를 모두 재확인해 유효 판정. △ 둘은 스스로
                "수정 필수는 아님" 이라 적었다.

남은 지적이 **M01988 한 문항에 모여 있다.** 세 검증자가 각기 다른 각도에서
같은 자리를 짚었으므로 그것만 닫고 끝낸다.

────────────────────────────────────────────────────────────────
㉠ 발문의 초점이 정답과 반 칸 어긋난다 (solver 5차 · factchecker 4차 · defender 3차)
────────────────────────────────────────────────────────────────
발문은 **아르곤 자신의** M 껍질이 8 인 까닭을 묻는데, 정답 ③ 은
"**아르곤 다음 자리에서** 4s 가 3d 보다 낮아서" 라고 다음 원소를 말한다.
아르곤 자신만 보면 일차적 사유는 "전자가 18 개뿐이라 3p 에서 소진된다" 이다.

★두 회차의 요구가 서로 반대였던 자리다.★ 정답을 '3d 가 4s 보다 높아서' 로
되돌리면 초점은 맞지만 그 진술이 **Sc 이후에는 거짓인 조건부 참**이 되어
defender 가 3차에 F2 로 올렸다. 그래서 범위를 문장 안에 넣은 것인데, 이번에는
그 범위 때문에 발문과 어긋나 보인다.

→ **선지가 아니라 발문을 정답의 초점에 맞춘다.** 관찰에 다음 원소를 함께
  적으면 "왜 M 껍질이 8 에서 멈추고 더 차지 않는가" 라는 물음이 되고, 정답의
  범위 한정이 그대로 들어맞는다.
    "… M 껍질에 든 전자는 8 개뿐이고, **그다음 원소인 칼륨에서도 M 껍질은 더
    차지 않는다.** 그 직접적인 까닭으로 옳은 것은?"
  ▸ 누출 검사 — 새 절은 **현상**을 하나 더 적을 뿐 까닭을 말하지 않는다.
    ①(정원이 8 로 줄어서)은 여전히 발문의 '정원 18' 이 지우고, ②·④ 는
    화학 판단이 있어야 지워진다. 소거 최대치는 그대로 2 개다.

────────────────────────────────────────────────────────────────
㉡ ② 에 '전개 순서' 독법이 남아 있다 (defender 5차)
────────────────────────────────────────────────────────────────
6차에 '아직 없어서 → 아직 생겨나지 않아서' 로 고쳐 **'전자가 안 찼다'** 는 참인
독법은 닫았다. 그런데 **'아르곤 자리에는' + '아직'** 이 남아 "쌓음 순서에서
아르곤 지점까지는 3d 가 아직 등장하지 않는다" 는 전개 순서 독법을 부른다.
그렇게 읽으면 준-참이 되고, 게다가 **정답 ③ 과 같은 말**이 되어 버린다
("4s 가 먼저라 3d 차례가 아직 안 왔다").

→ defender 가 짚은 두 낱말을 걷고 **존재 부정으로 못 박는다** —
  '아르곤 원자에는 3d 오비탈 자체가 존재하지 않아서'. 오비탈은 전자가 들어가야
  생기는 것이 아니므로 어떤 독법으로도 거짓이고, ③ 과 뜻이 겹치지도 않는다.

  ★교훈 — 오답을 고칠 때 **부사와 장소말이 독법을 연다.** '아직' 은 시점을,
  '자리에는' 은 순서를 끌어들인다. 존재를 부정하려면 존재만 말할 것.★

────────────────────────────────────────────────────────────────
㉢ 곁들여: 마지막 항과 최외각 (factchecker △)
────────────────────────────────────────────────────────────────
M01989 가 "축약 배치는 안쪽부터 적는 관례라 마지막 항이 대개 가장 바깥" 이라
했는데, 같은 배치 M01985 ② 의 [Ar] 4s² 3d⁵ 는 마지막 항이 가장 바깥이 아닌
반례다. '대개' 로 완화되어 있어 오류는 아니지만 한 마디를 더 붙인다.

받아들이지 않은 것
· M01988 ④(팔전자)를 defender 가 심각도 1 위로 올렸으나 스스로 "조건문 자체는
  성립하되 인과 방향이 뒤집혀 까닭으로는 거짓 · 최선답 형식에서 허용 · 수정
  불필요 판정이 타당" 이라 적었다. 남긴다.
· M01983 ①(6 개)과 M01990 ①(9 개)이 같은 트릭이다(defender·sim) — 배치 구성의
  문제이고 P3 설계의 검사 6 번으로 옮겨 두었다.
"""
import json
from collections import Counter

BANK = 'master/master_bank.json'
MK = ['①', '②', '③', '④']

bank = json.load(open(BANK, encoding='utf-8'))
by = {x['id']: x for x in bank}
before = {i: (json.dumps(by[f'M0{i}']['choices'], ensure_ascii=False),
              by[f'M0{i}']['stem'], by[f'M0{i}']['answer']) for i in range(1981, 1991)}


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:40]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


it = by['M01988']

# ㉠ 발문을 정답의 초점에 맞춘다
old_stem = ('M 껍질(n = 3)의 정원은 18 이다. 그런데 아르곤 원자의 바닥상태에서 M 껍질에 든 '
            '전자는 8 개뿐이다. 그 직접적인 까닭으로 옳은 것은?')
new_stem = ('M 껍질(n = 3)의 정원은 18 이다. 그런데 아르곤 원자의 바닥상태에서 M 껍질에 든 '
            '전자는 8 개뿐이고, 그다음 원소인 칼륨에서도 M 껍질은 더 차지 않는다. '
            '그 직접적인 까닭으로 옳은 것은?')
assert it['stem'] == old_stem, it['stem']
it['stem'] = new_stem

# ㉡ ② 에서 부사와 장소말을 걷고 존재 부정으로 못 박는다
old2 = '아르곤 자리에는 3d 오비탈이 아직 생겨나지 않아서'
new2 = '아르곤 원자에는 3d 오비탈 자체가 존재하지 않아서'
assert it['choices'][1] == old2, it['choices'][1]
it['choices'][1] = new2
it['solution'] = it['solution'].replace(old2, new2)
sub(it, '② 아르곤 원자에는 3d 오비탈 자체가 존재하지 않아서: 오비탈은 전자가 들어가야 생기는 '
        '것이 아니야. 부양자수가 주양자수보다 작기만 하면 되니 n = 3 인 아르곤에도 l = 2, '
        '곧 3d 는 멀쩡히 있어. 다만 비어 있을 뿐이지. 채워지기 시작하는 시기와 오비탈이 '
        '있느냐 없느냐는 다른 이야기야.',
    '② 아르곤 원자에는 3d 오비탈 자체가 존재하지 않아서: 오비탈은 전자가 들어가야 생기는 것이 '
    '아니야. 부양자수가 주양자수보다 작기만 하면 되니 n = 3 인 아르곤에도 l = 2, 곧 3d 는 '
    '멀쩡히 있어. 다만 비어 있을 뿐이지. 아르곤이든 스칸듐이든 3d 오비탈이 있다는 것은 '
    '똑같고, 다른 것은 거기에 전자가 들었느냐뿐이야.')
for d in it['distractors']:
    if d['opt'] == 1:
        d['error'] = '오비탈이 전자가 들어가야 생긴다고 봄 — 3d 는 아르곤에도 있고 비어 있을 뿐'

# ㉢ M01989 : 마지막 항이 늘 가장 바깥은 아니다 (factchecker △)
sub(by['M01989'],
    '축약 배치는 안쪽부터 바깥으로 적는 것이 관례라 마지막 항이 대개 가장 바깥이지만, '
    '마지막 항 하나가 그 껍질의 전부는 아니야.',
    '축약 배치는 안쪽부터 바깥으로 적는 것이 관례라 마지막 항이 대개 가장 바깥이지만, '
    '마지막 항 하나가 그 껍질의 전부는 아니야. 게다가 채움 순서대로 적으면 [Ar] 4s² 3d⁵ '
    '처럼 마지막 항이 가장 바깥이 아닌 경우도 있어.')

# ── 검사 ────────────────────────────────────────────────────────────────
seq = [by[f'M0{i}']['answer'] for i in range(1981, 1991)]
assert Counter(seq) == Counter({0: 2, 1: 2, 2: 3, 3: 3}), dict(Counter(seq))
for i in range(1981, 1991):
    x = by[f'M0{i}']
    assert x['answer'] == before[i][2], f'M0{i}: 정답 자리 불변 위반'
    if i != 1988:
        assert (json.dumps(x['choices'], ensure_ascii=False), x['stem']) == before[i][:2], \
            f'M0{i}: 손대지 않기로 한 문항인데 발문·선지가 바뀌었다'
    assert len(x['solution']) >= 300, (i, len(x['solution']))
    assert '★' not in x['solution'] and '★' not in x['stem'], f'M0{i}: G10 강조 표기'
    L = [len(c) for c in x['choices']]
    a = x['answer']
    assert not (L[a] == max(L) and L.count(max(L)) == 1), (i, 'G3 유일최장', L)
    assert not (L[a] == min(L) and L.count(min(L)) == 1), (i, 'G3 유일최단', L)
    ss = sorted(L)
    if (ss[1] + ss[2]) / 2 >= 8:
        assert (ss[3] - ss[0]) / ((ss[1] + ss[2]) / 2) <= 0.25, (i, 'G3b', L)
    head = x['solution'].split('\n\n')[1]
    assert (MK[a] + '가 옳아' in head) or (MK[a] + '이 옳아' in head), x['id']
    for k in range(4):
        assert (MK[k] + ' ' + x['choices'][k]) in x['solution'], x['id']

json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('7차 조치 완료 — M01988 발문 초점 + ② 존재 부정 · M01989 표기 관례 한 마디.')
