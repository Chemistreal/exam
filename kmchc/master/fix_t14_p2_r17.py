    #
    #    ▸ ★오탐부터 세었다★ (P1 교훈 ④). 사정거리만으로 걸면 ★9건★ 이 울고 그중 ★3건이
    #      오탐★ 이다 — 풀이 순서 안내 한 줄, ③ 오답이 두 쌍을 맞바꾼 것을 서술하는 문장 둘.
    #      세 오탐은 모두 ★요인의 승패를 주장하지 않는★ 문장이었다. 사정거리에 ★승패어★ 를
