def main():
    cj = json.load(open(CJ, encoding='utf-8'))
    concepts = {c['id']: c for c in cj[THEME]}

    linked = 0
    for cid, idx, mid in LINK:
        c = concepts[cid]
        a = c['angles'][idx]
        if mid not in a['by']:
            a['by'].append(mid)
            linked += 1

    for cid, note in NOTES.items():
        c = concepts[cid]
        if note not in c['note']:
            c['note'] = c['note'].rstrip() + ' ' + note

    json.dump(cj, open(CJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

    tot = un = 0
    for c in cj[THEME]:
        for a in c['angles']:
            tot += 1
            if not a['by']:
                un += 1
    print(f'T13 P11 링크 {linked}건 · 저작 주의 {len(NOTES)}개념 '
          f'({sum(len(v) for v in NOTES.values()):,}자)')
    print(f'  대장 각도 {tot} · 소진 {tot - un} · 미소진 {un}')


if __name__ == '__main__':
    main()
