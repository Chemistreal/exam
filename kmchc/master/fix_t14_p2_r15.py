# -*- coding: utf-8 -*-
"""T14 P2 15차 조치 — 마지막 한정어. '다른 요인' 이라고만 적은 자리에 그 요인의 이름을 적는다.

■ 15차 순회 결과
    solver       ★0건★ (정답 10/10 · 확신도 전부 '확실' · 자족성 충분)
    defender     ★F2 실패 후보 없음 — 수정할 것이 없습니다★
                 M02146 ① 상관 읽기 닫힘 확인 (타동 사동사 '줄이다' 가 주어를 행위자로
                 고정 + 발문이 '까닭' 을 물음 + 지문의 '오히려' 가 먼저 막음, 근거 셋)
    factchecker  ★사실 오류 0건★ (세 회차 연속) · 과장 1건

  ★defender 가 처음으로 '없다' 고 판정했다.★ 남은 것은 factchecker 의 △ 하나뿐이다.

■ 고친 것 하나 — M02154 ④ 반박 (본문 + 압축 줄)

  '전자 수가 많으면 커지는 쪽으로 작용하는 것은 맞지만, 그것은 ★다른 요인이 묶여 있을 때★
  쓰는 말이야'

  ★어느 요인이 묶여야 하는지를 말하지 않았다.★ 학생이 '껍질 수가 묶였을 때' 로 읽으면
  이 배치 안에서 곧바로 틀린다 — M02146 의 Na·Cl 은 같은 3주기라 껍질 수가 묶인 쌍인데,
  전자 수가 더 많은 Cl 이 더 작다(99 pm < 186 pm).

  → '★양성자 수가 묶인 쌍★ — 같은 원소의 원자와 그 이온에서 쓰는 말이야' 로 이름을 적는다.
    양성자 수가 묶이면 전자 수가 많은 쪽이 실제로 크다 — F(9e, 64 pm) < F⁻(10e, 133 pm)
    이고 Na⁺(10e, 95 pm) < Na(11e, 186 pm) 이니 음이온·양이온 양쪽에서 성립한다.
    ▸ 어휘도 배치 안에서 맞춘다 — M02152 본문이 이미 '같은 원소의 원자와 그 이온처럼,
      양성자 수가 묶인 쌍' 이라고 쓰고 있다.
    ▸ ★'껍질 수가 묶인다' 고 쓰지 않은 것이 요점이다.★ 12차에 factchecker 가 지적한 대로
      양이온은 껍질이 통째로 비어 껍질 수가 묶이지 않는다(Na 셋 → Na⁺ 둘). 여기서 묶이는
      것은 양성자 수 하나이고, 그 하나만 적었다.

■ ★이 배치에서 같은 결함이 다섯 번 나왔다 — 늘 "무엇이" 를 빼먹은 자리였다.★

      9차  '껍질 수가 같으면 양성자 수가 이긴다'    → 무엇이 같은 쌍인지 안 적음(이온 반례)
     11차  '껍질 수가 갈리면 껍질 수가 이긴다'      → 열쇠 자체가 틀림(Li/Cl 반례)
     12차  '같은 원소의 원자와 그 이온이면 껍질·양성자가 모두 묶인다' → 양이온에서 거짓
     13차  '같은 주기라면'                          → 중성 원자인지 안 적음(Mg/Cl⁻ 반례)
     15차  '다른 요인이 묶여 있을 때'               → 어느 요인인지 안 적음(Na/Cl 반례)

  ★규칙 문장을 쓸 때 빠지는 것은 언제나 목적어다 — 무엇이 묶였는지, 누구끼리인지.★
  다음 배치부터는 규칙 문장을 적을 때마다 ★"무엇이" 와 "누구끼리" 두 칸을 채웠는지★ 를
  먼저 확인한다. 두 칸이 비면 그 문장은 반드시 이 배치 안에서 반례를 낸다 — 다섯 번 다 그랬다.

■ 받지 않은 것
    defender 의 잔여 자리 둘 (M02146 ④ '상쇄되는 셈이기' · M02150 ③ '어긋나 함께 설 수 없다')
      — 둘 다 전제('두 영향이 반대 방향') 는 참이고 결론에서 거짓이 되는 같은 구조인데,
      defender 가 "판정 대상 명제는 결론 쪽이므로 참 조각이 답으로 끌지 못한다 · 필수 수정
      아님" 으로 판정했다. 발문이 각각 '까닭' 과 '옳게 정리한 것' 이라 양립 부정은 곧 지문
      부정이 된다.
    solver 의 문투 지적 (M02146 ② '껍질 수까지 함께' 의 선행 대상 · ④ '셈이기' 의 리듬 ·
      M02147 발문의 방향) — ② 를 '껍질 수도 줄어들었기' 로 줄이면 14자가 되어 산포가
      0.44 로 튄다(문턱 0.25). ★문면을 다듬을 자리가 길이 게이트에 막혀 있다★ — watch 에
      올리고 P3 에서는 선지를 처음부터 길이 여유를 두고 짓는다.
    M02146 발문의 '오히려' — solver 는 ① 의 매력을 깎는다고 보았고 defender 는 상관 읽기를
      막는 장치로 세어 닫힘 근거 셋 가운데 하나로 들었다. ★두 검증자의 평가가 엇갈리는
      자리이고, 역설을 세우는 것이 이 문항의 틀★ 이므로 그대로 둔다.
"""
import os
import re

BASE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(BASE, 'build_t14_p2.py')

R = [
    # 본문
    ("'맞지만, 그것은 다른 요인이 묶여 있을 때 쓰는 말이야. 여기서는 전자 수가 같으니 '",
     "'맞지만, 그것은 양성자 수가 묶인 쌍 — 같은 원소의 원자와 그 이온에서 쓰는 말이야. '\n"
     "          '여기서는 전자 수가 같으니 '"),
    # 압축 줄
    ("'전자 수가 많은 쪽이 크다는 말은 늘 맞다': '그 말은 다른 요인이 묶여 있을 때 쓰는 '\n"
     "                                                      '거야. 여기서는 전자 수가 같으니 걸 '\n"
     "                                                      '자리조차 없지.'",
     "'전자 수가 많은 쪽이 크다는 말은 늘 맞다': '그 말은 양성자 수가 묶인 쌍 — 같은 '\n"
     "                                                      '원소의 원자와 그 이온에서 쓰는 거야. '\n"
     "                                                      '여기서는 전자 수가 같으니 걸 자리조차 '\n"
     "                                                      '없지.'"),
]

BAN_AFTER = ['다른 요인이 묶여 있을 때']


def main():
    src = open(SRC, encoding='utf-8').read()
    for i, (a, b) in enumerate(R, 1):
        n = src.count(a)
        assert n == 1, f'{i}번 문면이 {n}곳 — 손으로 볼 것\n---\n{a[:160]}'
        src = src.replace(a, b)
    for s in BAN_AFTER:
        assert s not in src, f'조치 뒤에도 남았다: {s}'
    # ★줄 끊김을 이어 붙인 뒤에 센다★ (14차에 이 함정에서 결함이 나왔다)
    flat = re.sub(r"'\s*\n\s*'", '', src)
    assert flat.count('양성자 수가 묶인 쌍') >= 2, '본문과 압축 줄 양쪽에 있어야 한다'
    # ★여기서 묶이는 것은 양성자 수 하나다 — 껍질 수라고 쓰면 양이온에서 거짓이 된다★
    assert '껍질 수가 묶인 쌍' not in flat, '양이온에서 거짓이 되는 문면이 들어왔다'
    open(SRC, 'w', encoding='utf-8').write(src)
    print(f'T14 P2 15차 조치 — {len(R)}곳 교체')
    print("  M02154 ④ 반박 '다른 요인' → '양성자 수가 묶인 쌍' (본문·압축 줄)")


if __name__ == '__main__':
    main()
