def main():
    d = json.load(open(BANK, encoding='utf-8'))
    items = d if isinstance(d, list) else d['items']
    x = {it['id']: it for it in items}
    n = 0

    for fid, st in STEM.items():
        assert x[fid]['stem'] != st, f'{fid}: stem 이 이미 같음'
        x[fid]['stem'] = st; n += 1
    for fid, pf in PROOF.items():
        assert x[fid]['answer_proof'] != pf, f'{fid}: proof 가 이미 같음'
        x[fid]['answer_proof'] = pf; n += 1

    assert x['M01913']['solution'] != M1913_SOL
    x['M01913']['solution'] = M1913_SOL; n += 1

    for fid, idx, txt, reb, err, typ in SWAP:
        swap_choice(x[fid], idx, txt, reb, err, typ); n += 1

    for fid, idx, txt in TIGHTEN:
        it = x[fid]
        old = it['choices'][idx]
        assert old != txt, f'{fid}[{idx}]: 이미 같음'
        mark = '①②③④'[idx]
        if idx != it['answer']:
            head = f'{mark} {old}:'
            assert head in it['solution'], f'{fid}: 해설 {mark} 줄 없음'
            it['solution'] = it['solution'].replace(head, f'{mark} {txt}:')
        else:
            head = f'[정답] {mark} {old} —'
            assert head in it['solution'], f'{fid}: 해설 [정답] 줄 없음'
            it['solution'] = it['solution'].replace(head, f'[정답] {mark} {txt} —')
        it['choices'][idx] = txt
        n += 1

    for fid, old, new in SUB:
        it = x[fid]
        assert old in it['solution'], f'{fid}: 대상 조각 없음 -> {old[:44]}'
        assert it['solution'].count(old) == 1, f'{fid}: 조각이 둘 이상'
        it['solution'] = it['solution'].replace(old, new)
        n += 1

    for fid, key, frag in STALE:
        assert frag not in x[fid][key], f'{fid}.{key}: 옛 문면 잔존 -> {frag}'

    # ── 자체 점검 ──────────────────────────────────────────────
    ids = [f'M0{i}' for i in range(1907, 1917)]
    for fid in ids:
        it = x[fid]
        sol = it['solution']
        # 해설의 오답 줄 머리가 지금 선지와 정확히 맞는가 (1차 버그 재발 방지)
        for k, c in enumerate(it['choices']):
            if k == it['answer']:
                assert f"[정답] {'①②③④'[k]} {c} —" in sol, f'{fid}: [정답] 줄 어긋남'
            else:
                assert f"{'①②③④'[k]} {c}:" in sol, f'{fid}: {k+1} 줄 어긋남'
        # 옛 선지 문면이 해설에 남아 있지 않은가
        assert len(sol) >= 300 and '★' not in sol and '**' not in sol
        opts = sorted(dd['opt'] for dd in it['distractors'])
        assert opts == sorted(set(range(4)) - {it['answer']}), f'{fid}: distractors 어긋남'
    assert x['M01908']['choices'][3].endswith('적외선이다')
    assert all(c.endswith('적외선이다') for c in x['M01908']['choices'])
    assert 'n = 1' not in x['M01907']['stem']

    json.dump(d, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

    print(f'P11 2차 조치 {n}곳 · 채택 8 · 반려 7')
    for fid in ids:
        it = x[fid]
        L = [len(c) for c in it['choices']]
        s = sorted(L)
        sp = (s[3] - s[0]) / ((s[1] + s[2]) / 2)
        rk = sorted(range(4), key=lambda i: -L[i]).index(it['answer']) + 1
        print(f"  {fid} 정답{'①②③④'[it['answer']]} 길이{L} 산포{sp:.2f} "
              f"길이순위{rk} 해설{len(it['solution'])}자")


if __name__ == '__main__':
    main()
