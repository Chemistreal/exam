# ㉡ 수치 선지 — 공유 관계식을 어기는 선지가 하나뿐이고 그것이 정답은 아닌가
import re
NUMW = {'여덟': 8, '열': 10, '열둘': 12, '열넷': 14, '열여섯': 16, '열여덟': 18, '서른둘': 32}


def vals(it):
    """선지가 나타내는 '값' — 순수 수치 선지이거나 한글 수사로 개수를 말할 때만 읽는다.
    ▸ 앞자리 숫자를 그냥 읽으면 '4s 와 4p 를 …' 이 4 로 잡혀 ★검사가 조용히 헛돈다.★
      실제로 1차 판에서 그렇게 되어 M02038 이 검사에서 통째로 빠져나갔다."""
    out = []
    for c in it['choices']:
        m = re.fullmatch(r'\s*(\d+)\s*개?\s*', c)
        if m:
            out.append(int(m.group(1)))
            continue
        hit = [v for w, v in NUMW.items() if w + ' 개' in c]
        out.append(max(hit) if hit else None)
    return out


# ▸ 관계식은 ★이 단원에서 눈에 띄는 것만★ 건다. '3의 배수' 같은 임의의 정수 성질까지
#   넣으면 2·7·8·9 에서 9 만 3의 배수라는 식의 거짓 양성이 난다 — 학생이 실제로 쓰는
#   무늬(거듭제곱·2n²·정원의 배수·홀짝)로 한정한다.
REL = [('2의 거듭제곱', lambda v: v > 0 and (v & (v - 1)) == 0),
       ('4의 배수', lambda v: v % 4 == 0),
       ('홀수', lambda v: v % 2 == 1)]
for it in items:
    v = vals(it)
    if any(x is None for x in v) or len(set(v)) < 4:
        continue
    for name, f in REL:
        ok = [i for i in range(4) if f(v[i])]
        if len(ok) == 3 and it['answer'] not in ok:
            raise AssertionError(f"{it['id']}: 관계식 「{name}」 을 어기는 선지가 정답 하나뿐 {v}")
        if len(ok) == 1 and it['answer'] in ok:
            raise AssertionError(f"{it['id']}: 관계식 「{name}」 을 만족하는 선지가 정답 하나뿐 {v}")

