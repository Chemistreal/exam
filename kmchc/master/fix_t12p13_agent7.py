import json, os

BANK = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'master_bank.json')
MK = '①②③④'


def swap_choice(it, idx, new_txt, new_rebut, err, typ):
    mark = MK[idx]
    old = it['choices'][idx]
    assert idx != it['answer'], f"{it['id']}: 정답 자리는 이 헬퍼로 바꾸지 않는다"
    lines = it['solution'].split('\n')
    hit = [i for i, L in enumerate(lines) if L.startswith(f'{mark} {old}:')]
    assert len(hit) == 1, f"{it['id']}: 해설 {mark} 줄을 못 찾음"
    lines[hit[0]] = f'{mark} {new_txt}: {new_rebut}'
    it['solution'] = '\n'.join(lines)
    it['choices'][idx] = new_txt
    for dd in it['distractors']:
        if dd['opt'] == idx:
            dd['error'], dd['type'] = err, typ
            break
    else:
        raise AssertionError(f"{it['id']}: distractor {idx} 없음")


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:26]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


def main():
    bank = json.load(open(BANK, encoding='utf-8'))
    d = {x['id']: x for x in bank}

    # ── 1. M01927 ② 교체 ───────────────────────────────────────────────
    swap_choice(d['M01927'], 1, '전자는 핵에서 멀어질수록 더 빠르게 돌아 떨어지지 않는다',
                '핵에서 멀어질수록 전자는 오히려 느리게 돌아. 그리고 보어가 막은 것은 '
                '빠르기가 아니라 빛을 내놓는 일이야 — 정해진 준위에서는 아예 내놓지 '
                '않는다고 못 박았지.',
                '준위가 높을수록 속력이 커진다고 봄 — 실제로는 v ∝ 1/n 으로 느려진다', 'sign')

    # ── 2. M01928 해설 손질 셋 ─────────────────────────────────────────
    it = d['M01928']
    sub(it, '전자가 양성자의 1/1836 쯤으로 아주 가벼워 그 어림이 통하지만',
        '전자는 양성자의 1/1836 밖에 되지 않을 만큼 가벼워서 그 어림이 통하지만')
    sub(it, '그리고 어긋난 몫인 두 배분이 곧 전하를 띠지 않는 입자 두 개분이라는 것이 '
            '이 논증이 끝내 다다른 곳이지.',
        '예상은 두 배였지만 실제로 재어 보니 네 배였어. 그 어긋난 두 배분이 곧 전하를 '
        '띠지 않는 입자 두 개분이었고, 논증은 그렇게 중성자를 불러냈지.')
    sub(it, '④ 중성자의 질량은 셈에 넣지 않아도 될 만큼 작다: 중성자의 질량은 양성자와 '
            '거의 같아. 무시할 수 없고, 오히려 두 개가 더해져 네 배가 된 거지.',
        '④ 중성자의 질량은 셈에 넣지 않아도 될 만큼 작다: 중성자의 질량은 양성자와 거의 '
        '같아 무시할 수 없어. 게다가 이 논증은 중성자를 작다고 본 것이 아니라 아예 셈에 '
        '두지 않았지 — 빠뜨린 두 개분이 곧 어긋남의 정체야.')

    # ── 3. M01929 계산 줄에 단위 ───────────────────────────────────────
    sub(d['M01929'], '1.6×10⁻¹⁹ 을 1.76×10⁸ 으로 나누면 9.1×10⁻²⁸ 이 돼',
        '1.6×10⁻¹⁹ C 를 1.76×10⁸ C/g 으로 나누면 9.1×10⁻²⁸ g 이 돼')

    # ── 4. M01931 반박·자가진단 ────────────────────────────────────────
    it = d['M01931']
    sub(it, '도착 준위가 1, 2, 1 로 서로 달라.', '도착 준위가 1 과 2 로 갈려.')
    sub(it, '더해지는 것은 에너지이지 파장이 아니다(파장은 1/λ 가 더해진다).',
        '더해지는 것은 에너지이지 파장이 아니다 — 파장 대신 파수 1/λ 가 더해진다.')
    for dd in it['distractors']:
        if dd['opt'] == 1:
            dd['error'] = '도착 준위가 1 과 2 로 갈림 — 라이먼과 발머가 섞여 있다'

    # ── 5. M01932 자가진단 ─────────────────────────────────────────────
    sub(d['M01932'], '자가진단: 도착 n = 1 > 2 > 3 순으로 에너지가 크다.',
        '자가진단: 도착 준위가 낮을수록(1 → 2 → 3) 에너지가 크다.')

    # ── 6. M01934 ② 반박의 지시 대상 ───────────────────────────────────
    sub(d['M01934'], '핵이 아주 작다는 것은 그런 일이 아주 드물다는 데서 나오지.',
        '핵이 아주 작다는 것은 되튐이 아주 드물다는 데서 나오지.')

    for x in bank:
        assert '**' not in x['stem'] and '**' not in x['solution'], x['id']
        assert '★' not in x['stem'] and '★' not in x['solution'], x['id']

    json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('P13 7차 조치 완료 — 오답 교체 1 · 해설 손질 6')
    for i in range(1927, 1937):
        x = d[f'M0{i}']
        L = [len(c) for c in x['choices']]
        s = sorted(L)
        sp = (s[3] - s[0]) / ((s[1] + s[2]) / 2)
        rk = sorted(range(4), key=lambda j: -L[j]).index(x['answer']) + 1
        flag = '' if (sp <= 0.25 or s[1] < 8) else '  ← G3b'
        if L[x['answer']] == s[3] and L.count(s[3]) == 1:
            flag += '  ← G3 최장'
        if L[x['answer']] == s[0] and L.count(s[0]) == 1:
            flag += '  ← G3 최단'
        print(f'  {x["id"]} {L} 산포{sp:.2f} 순위{rk}{flag}')


if __name__ == '__main__':
    main()
