    swap_choice(it, 2, '표의 값이 모두 양수이니 수소의 에너지 준위도 모두 양수다',
                '표에 적힌 것은 차의 크기야. 준위 값은 −1312/n² 로 모두 음수지.')
    swap_choice(it, 3, '값이 같으니 흡수와 방출 가운데 어느 쪽이 쉬운지 알 수 있다',
                '주고받는 양이 같다는 것뿐이야. 어느 쪽이 잘 일어나는지는 표에 없어.')

    # ══ M01950 ─ ④ 교체 + ② 반박 + 자가진단 ═════════════════════════════
