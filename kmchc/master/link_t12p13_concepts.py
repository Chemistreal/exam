    ('C12-N02', 1, 'M01929'),   # 단위가 C/g 임을 놓치면 10³ 배 어긋난다 [오개념]
    ('C12-018', 4, 'M01930'),   # 각 묶음의 왼쪽 끝이 그 계열의 최단 파장인 까닭
