def spread(ch):
    L = sorted(len(str(x)) for x in ch)
    return (L[3] - L[0]) / ((L[1] + L[2]) / 2) if L[1] + L[2] else 0.0


def len_rank(it):
    L = [len(str(x)) for x in it['choices']]
    order = sorted(range(4), key=lambda i: (-L[i], i))
    return order.index(it['answer']) + 1


