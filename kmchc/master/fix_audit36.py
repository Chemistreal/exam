# ── 2. ★ 유출 ────────────────────────────────────────────────
STAR = [('M01812',
         "자가진단: 퍼진 쪽이 (+), 박힌 쪽이 전자 = 푸딩 모형. ★핵이 아직 없다★",
         "자가진단: 퍼진 쪽이 (+), 박힌 쪽이 전자 = 푸딩 모형. 핵은 아직 없다.")]


def main():
    bank = json.load(open(BANK, encoding='utf-8'))
    d = {x['id']: x for x in bank}
    n = 0

    # 1. objective
    for fid, obj in OBJ.items():
        assert 'objective' not in d[fid] or not d[fid]['objective'], f'{fid}: 이미 있음'
        d[fid]['objective'] = obj
        n += 1

    # 2. ★
    for fid, old, new in STAR:
        s = d[fid]['solution']
        assert old in s, f'{fid}: 대상 문구 없음'
        d[fid]['solution'] = s.replace(old, new, 1)
        n += 1

    # 3. 해설의 오답 인용을 선지 문면과 글자 그대로 맞춘다
    fixed = []
    for i in range(1807, 1887):
        fid = f'M0{i}'
        x = d[fid]
        ch, a, sol = x['choices'], x['answer'], x['solution']
        for w in x['distractors']:
            opt = ch[w['opt']]
            if opt in sol:
                continue
            # 해설의 해당 반박 줄을 찾아 앞부분을 선지 문면으로 갈아 끼운다
            cir = '①②③④'[w['opt']]
            lines = sol.split('\n')
            tgt = [k for k, ln in enumerate(lines) if ln.startswith(cir + ' ')]
            assert len(tgt) == 1, f'{fid} {cir}: 반박 줄 {len(tgt)}개'
            k = tgt[0]
            body = lines[k].split(': ', 1)
            assert len(body) == 2, f'{fid} {cir}: 콜론 분리 실패 -> {lines[k][:60]}'
            lines[k] = f'{cir} {opt}: {body[1]}'
            sol = '\n'.join(lines)
            fixed.append(f'{fid}{cir}')
        x['solution'] = sol
    n += len(fixed)
    print(f'해설 인용 정합 {len(fixed)}건: {" ".join(fixed)}')

    # ── 검증 ────────────────────────────────────────────────
    for i in range(1807, 1887):
        fid = f'M0{i}'
        x = d[fid]
        assert x.get('objective'), f'{fid}: objective 결손'
        for f in ('stem', 'solution'):
            for badtok in ('**', '★'):
                assert badtok not in x[f], f'{fid}: {f} 에 {badtok}'
        assert len(x['solution']) >= 300, f'{fid}: 해설 {len(x["solution"])}자'
        for w in x['distractors']:
            assert x['choices'][w['opt']] in x['solution'], f'{fid}: 해설에 오답 문면 없음'
    # ★감사36 에서 드러난 별개의 부채★ M00001~M01806 은 objective 키만 있고 값이 빈 문자열이다.
    #   RESUME 의 "기존 1,816제에 자리 부여 완료" 는 ★슬롯만 만든 것★ 이었고 내용은 없다.
    #   T12 밖이라 이번 감사의 조치 범위가 아니다 — 리포트에 부채로 올린다.
    empty = [x['id'] for x in bank if 'objective' in x and not x['objective']]
    missing = [x['id'] for x in bank if 'objective' not in x]
    assert not missing, f'objective 키 결손 잔존: {missing[:5]}'
    print(f'★부채★ objective 가 빈 문자열인 문항 {len(empty)}제 '
          f'({empty[0]}~{empty[-1]}) — T12 밖이라 이번 조치 범위 아님')

    json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'조치 {n}곳 적용 · T12 80제 objective 충족 · ★ 0')


if __name__ == '__main__':
    main()
