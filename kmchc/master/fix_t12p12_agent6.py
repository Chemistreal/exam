import json, os

BJ = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'master_bank.json')
MK = '①②③④'

REPL = [
    # △1 — 출발 n=∞ 만으로는 91 nm 가 정해지지 않는다. 도착 n=1 을 넣는다.
    ('M01923', 'solution',
     '출발이 n = ∞ 인 전이는 라이먼 계열의 한계로 약 91 nm 라 122 nm 보다 더 짧아. '
     '이 다섯 선에는 없지.',
     '출발이 n = ∞ 이고 도착이 n = 1 인 전이가 라이먼 계열의 한계인데, 그 파장은 약 91 nm 라 '
     '122 nm 보다 짧아. 이 다섯 선에는 없지.'),

    # △2 — 최대에서 평균으로 건너뛴 자리를 잇는다
    ('M01921', 'solution',
     '가장 큰 운동에너지야. 그러니 진동수를 올리면 평균도 함께 커지지 — ①이 옳아.',
     '가장 큰 운동에너지야. 가장 큰 값이 올라가면 그 아래 분포가 통째로 올라가니 '
     '평균도 함께 커지지 — ①이 옳아.'),

    # △3 — 자가진단의 기호를 본문과 맞춘다((E/k)×λ 가 91.11 이고 E×λ 는 91.11k 다)
    ('M01926', 'solution',
     '자가진단: 네 줄의 E×λ 를 견줘',
     '자가진단: 네 줄의 (E/k)×λ 를 견줘'),

    # △4 — 금박 두께를 인용값에 맞춘다
    ('M01917', 'solution',
     '그런데 금박은 원자가 수천 겹으로 쌓인 덩어리라, 원자를 죄다 비켜 가는 길이 있을 수 없어.',
     '그런데 금박은 원자가 천 겹 넘게 쌓인 덩어리라, 원자를 죄다 비켜 가는 길이 있을 수 없어.'),
    ('M01917', 'solution',
     '하지만 수천 겹을 지나면서 그 틈만 골라 빠져나갈 수는 없지.',
     '하지만 천 겹 넘는 층을 지나면서 그 틈만 골라 빠져나갈 수는 없지.'),
]


def main():
    bank = json.load(open(BJ, encoding='utf-8'))
    x = {i['id']: i for i in bank}
    ids = [f'M0{i}' for i in range(1917, 1927)]

    miss = [(f, k, a[:30]) for f, k, a, _ in REPL if a not in x[f][k]]
    assert not miss, f'치환 대상 없음: {miss}'
    for f, k, a, b in REPL:
        x[f][k] = x[f][k].replace(a, b, 1)

    from collections import Counter
    for fid in ids:
        it = x[fid]
        sol = it['solution']
        for k, c in enumerate(it['choices']):
            if k == it['answer']:
                assert f'[정답] {MK[k]} {c} —' in sol, f'{fid}: [정답] 줄 어긋남'
            else:
                assert f'{MK[k]} {c}:' in sol, f'{fid}: {k + 1} 번 줄 어긋남'
        assert sorted(d['opt'] for d in it['distractors']) == \
            sorted(k for k in range(4) if k != it['answer']), f'{fid}: 오답 자리 어긋남'
        assert '★' not in it['stem'] and '★' not in sol, f'{fid}: 강조 기호 잔존'
        assert '**' not in sol, f'{fid}: 굵게 기호 잔존'
        assert len(sol) >= 300, f'{fid}: 해설이 300자 미만'
    assert Counter(x[f]['answer'] + 1 for f in ids) == Counter({1: 3, 2: 2, 3: 3, 4: 2})
    assert '수천 겹' not in x['M01917']['solution'], 'M01917: 수천 겹 잔존'
    assert '네 줄의 E×λ' not in x['M01926']['solution'], 'M01926: 옛 기호 잔존'

    json.dump(bank, open(BJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('P12 6차 조치 완료 — 본문 치환 5 (선지 변경 없음)')


if __name__ == '__main__':
    main()
