# -*- coding: utf-8 -*-
"""T13 P2 — 8차 조치 (서술만 · 선지·정답 불변, 발문은 한 절의 표현만).

마감 확인 순회. **세 검증자가 세 회차 연달아 실체 0 건이다.**

    solver      10/10 · 확신 전원 '확실' · 자족성 전원 '충족'.
                7차의 두 손질이 "새 정답을 만들거나 정답을 흔들지 않았다" 고 확인.
    factchecker ★사실 오류 없음★ 오답 서른의 값 검산 전부 일치 · 번호 어긋남 없음 ·
                문항 사이 모순 없음. 7차 수정분도 "정확합니다" 로 확인.
                △ 넷은 스스로 "수정 필수 아님".

★그런데 7차도 되튀었다 — M01988 ② 는 이번이 다섯 번째 개정이다★

    초판  아르곤에는 3d 라는 오비탈이 처음부터 없어서   → sim: 죽음
    2차   3d 는 4주기부터 채워져 아르곤에는 아직 없어서 → defender: 무조건 참(F2)
    3차   M 껍질이 다 차야 다음 껍질로 넘어가기 때문에   → sim: 죽음(발문과 모순)
    6차   아르곤 자리에는 3d 오비탈이 아직 생겨나지 않아서 → defender: 순서 독법 준-참
    7차   아르곤 원자에는 3d 오비탈 자체가 존재하지 않아서 → solver: 정원 18 이 존재를 함축

★이 자리는 구조적으로 좁다.★ 발문이 '정원 18' 을 적는 순간 18 = 2 + 6 + 10 이라
**3d 의 존재가 전제에 함축**되므로 존재를 부정하는 오답은 약해지고, 반대로 시점·
순서로 비켜 쓰면 '아직 안 찼다' 라는 **참인 독법**이 열린다. 다섯 번의 개정이
그 두 벽 사이를 오갔다.

  ▸ **여기서 멈춘다.** 판단 근거 — ㉮ 진리값의 최종 심판인 factchecker 가 현재
    ② 를 "정확하다" 고 확인했고, ㉯ defender 의 순서 독법 지적은 닫혔으며,
    ㉰ sim 은 A 가 이 계열 오답에 실제로 착지하는 것을 보았고, ㉱ solver 가 말한
    소거는 'M 껍질이 s·p·d 로 이루어진다' 는 **화학 지식을 쓰는 소거**다.
    ㉲ 무엇보다 **다섯 회차가 각각 한 검증자를 만족시키고 다른 검증자를 깨웠다** —
    이것이 멈춤 규칙이 말하는 되풀이 신호다.
  ▸ 대신 **선택지가 좁은 까닭을 개념 대장에 적어** 다음 배치가 같은 벽에 부딪히지
    않게 한다(link 스크립트 C13-014 주).

────────────────────────────────────────────────────────────────
이번에 손대는 것 — 모두 서술
────────────────────────────────────────────────────────────────
㉠ **7차가 만든 어휘 반향** (solver) — 발문에 넣은 "**그다음** 원소인 칼륨에서도"
   가 정답 ③ 의 "아르곤 **다음** 자리에서" 와 낱말로 울린다. 아르곤 이후를
   말하는 선지가 ③ 하나뿐이라 그 울림이 정답을 지목한다.
   → "칼륨의 마지막 전자도 M 껍질로 들어가지 않는다" 로. 관찰의 내용은 그대로고
     '다음' 이라는 낱말만 사라진다.
   ★교훈: 발문에 절을 더할 때 **그 절의 낱말이 어느 선지와 겹치는지** 볼 것.
   범위를 맞추려 넣은 말이 형태 단서가 된다.★
㉡ M01988 반박의 "n = 3 인 아르곤" 은 원자 자체에 주양자수가 있는 듯 읽힌다
   (factchecker) → "n = 3 껍질을 가진 아르곤".
㉢ M01987 본문의 "같은 부껍질끼리는 어느 원자에서나 에너지가 같아" 에 한정어가
   없다(factchecker). ③ 반박에는 "홀로 있는 원자라면" 이 있는데 본문에는 빠져
   착물·분자로 잘못 일반화될 소지가 있다 → 본문에도 넣는다.
㉣ M01981 은 2s·2p 가 갈라진다고만 하고 **어느 쪽이 낮은지를 끝내 말하지
   않는다**(factchecker) → "2s 쪽이 낮아진다" 를 한 마디 덧붙인다.

남기는 것: M01984 "준위 자체는 달라지지 않지"(고교 범위 이상화 · factchecker 가
"허용 가능" 판정) · M01986 ①('−1')이 죽은 선지라는 점(sim) — 전자 넷의 스핀 합은
**패리티상 정수**라 반정수 대안은 지식 없이 소거되고, 규약을 못 박은 뒤 경로가
남는 정수 값은 0 과 +2 뿐이라 이미 다 쓰였다. 구조적 비용으로 기록한다.
"""
import json
from collections import Counter

BANK = 'master/master_bank.json'
MK = ['①', '②', '③', '④']

bank = json.load(open(BANK, encoding='utf-8'))
by = {x['id']: x for x in bank}
before = {i: (json.dumps(by[f'M0{i}']['choices'], ensure_ascii=False), by[f'M0{i}']['answer'])
          for i in range(1981, 1991)}


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:40]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


# ── ㉠ M01988 발문 : '다음' 반향을 끊는다 (solver) ───────────────────────
it = by['M01988']
old_stem = ('M 껍질(n = 3)의 정원은 18 이다. 그런데 아르곤 원자의 바닥상태에서 M 껍질에 든 '
            '전자는 8 개뿐이고, 그다음 원소인 칼륨에서도 M 껍질은 더 차지 않는다. '
            '그 직접적인 까닭으로 옳은 것은?')
new_stem = ('M 껍질(n = 3)의 정원은 18 이다. 그런데 아르곤 원자의 바닥상태에서 M 껍질에 든 '
            '전자는 8 개뿐이고, 칼륨의 마지막 전자도 M 껍질로 들어가지 않는다. '
            '그 직접적인 까닭으로 옳은 것은?')
assert it['stem'] == old_stem, it['stem']
it['stem'] = new_stem

# ── ㉡ M01988 : 주양자수의 주어 (factchecker) ────────────────────────────
sub(it, 'n = 3 인 아르곤에도 l = 2, 곧 3d 는 멀쩡히 있어',
    'n = 3 껍질을 가진 아르곤에도 l = 2, 곧 3d 는 멀쩡히 있어')

# ── ㉢ M01987 : 본문에도 '홀로 있는 원자' 한정 (factchecker) ─────────────
sub(by['M01987'],
    '첫째, 같은 부껍질에 속한 오비탈끼리는 주양자수도 부양자수도 같고 자기양자수만 다르니 '
    '어느 원자에서나 에너지가 같아.',
    '첫째, 같은 부껍질에 속한 오비탈끼리는 주양자수도 부양자수도 같고 자기양자수만 다르니 '
    '홀로 있는 원자라면 어느 원자에서나 에너지가 같아.')

# ── ㉣ M01981 : 갈라지는 방향을 밝힌다 (factchecker) ─────────────────────
sub(by['M01981'],
    '두 오비탈은 주양자수가 같지만 전자가 여럿 있으면 서로 밀어내는 정도가 달라져 에너지가 '
    '벌어져.',
    '두 오비탈은 주양자수가 같지만 전자가 여럿 있으면 서로 밀어내는 정도가 달라져 에너지가 '
    '벌어져. 2s 쪽이 핵 가까이 머무는 몫이 있어 덜 밀리고, 그래서 2s 가 2p 보다 낮아지지.')

# ── 검사 ────────────────────────────────────────────────────────────────
seq = [by[f'M0{i}']['answer'] for i in range(1981, 1991)]
assert Counter(seq) == Counter({0: 2, 1: 2, 2: 3, 3: 3}), dict(Counter(seq))
for i in range(1981, 1991):
    x = by[f'M0{i}']
    assert (json.dumps(x['choices'], ensure_ascii=False), x['answer']) == before[i], \
        f'M0{i}: 선지·정답 불변 위반'
    assert len(x['solution']) >= 300, (i, len(x['solution']))
    assert '★' not in x['solution'] and '★' not in x['stem'], f'M0{i}: G10 강조 표기'
    L = [len(c) for c in x['choices']]
    a = x['answer']
    assert not (L[a] == max(L) and L.count(max(L)) == 1), (i, 'G3 유일최장', L)
    assert not (L[a] == min(L) and L.count(min(L)) == 1), (i, 'G3 유일최단', L)
    ss = sorted(L)
    if (ss[1] + ss[2]) / 2 >= 8:
        assert (ss[3] - ss[0]) / ((ss[1] + ss[2]) / 2) <= 0.25, (i, 'G3b', L)
    head = x['solution'].split('\n\n')[1]
    assert (MK[a] + '가 옳아' in head) or (MK[a] + '이 옳아' in head), x['id']
    for k in range(4):
        assert (MK[k] + ' ' + x['choices'][k]) in x['solution'], x['id']
assert '다음' not in by['M01988']['stem'], '발문에 다음 반향이 남았다'

json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('8차 조치 완료 — 발문 어휘 반향 1 · 서술 3. 선지·정답 불변 확인.')
