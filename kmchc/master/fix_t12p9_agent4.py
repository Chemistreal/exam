def spread(ch):
    L = sorted(len(str(c)) for c in ch)
    return (L[3] - L[0]) / ((L[1] + L[2]) / 2)


def rank(it):
    L = [len(str(c)) for c in it['choices']]
    return sorted(range(4), key=lambda i: -L[i]).index(it['answer']) + 1


def main():
    bank = json.load(open(BANK, encoding='utf-8'))
    d = {x['id']: x for x in bank}
    n = 0
    for fid, r in REPL.items():
        x = d[fid]
        for key in ('stem', 'answer_proof', 'solution', 'choices'):
            if key in r:
                assert x[key] != r[key], f'{fid}: {key} 가 이미 같음'
                x[key] = r[key]; n += 1
        for w in x['distractors']:
            for k, fld in (('errors', 'error'), ('types', 'type')):
                if k in r and w['opt'] in r[k]:
                    w[fld] = r[k][w['opt']]; n += 1
    for fid, field, old, new in SUB:
        x = d[fid]
        assert old in x[field], f'{fid}.{field}: 대상 문면 없음 -> {old}'
        x[field] = x[field].replace(old, new, 1); n += 1
    for fid, opt, old, new in ERR_SUB:
        w = [y for y in d[fid]['distractors'] if y['opt'] == opt][0]
        assert w['error'] == old, f'{fid} opt{opt}: error 어긋남 -> {w["error"]}'
        w['error'] = new; n += 1

    touched = set(REPL) | {s[0] for s in SUB} | {e[0] for e in ERR_SUB}
    for fid in touched:
        x = d[fid]
        ch, a, sol = x['choices'], x['answer'], x['solution']
        L = [len(str(c)) for c in ch]
        assert not (L[a] == max(L) and L.count(max(L)) == 1), f'{fid}: 정답=유일 최장 {L}'
        assert not (L[a] == min(L) and L.count(min(L)) == 1), f'{fid}: 정답=유일 최단 {L}'
        if sorted(L)[1] >= 8:
            assert spread(ch) <= 0.25, f'{fid}: 산포 {spread(ch):.3f} {L}'
        assert len(set(ch)) == 4, f'{fid}: 선지 중복'
        assert len(sol) >= 300, f'{fid}: 해설 {len(sol)}자'
        for w in x['distractors']:
            assert ch[w['opt']] in sol, f'{fid} {CIR[w["opt"]]}: 해설에 오답 문면 없음 -> {ch[w["opt"]]}'
        assert ch[a] in sol, f'{fid}: 해설에 정답 문면 없음'
        for f in ('stem', 'solution'):
            for bad in ('**', '★'):
                assert bad not in x[f], f'{fid}: {f} 에 {bad}'

    # ── 형식 요령 기계 검사 ──
    x = d['M01887']
    st = Counter(c.split(' → ')[0] for c in x['choices'])
    en = Counter(c.split(' → ')[-1] for c in x['choices'])
    ans = x['choices'][x['answer']]
    # 시작: 최빈값이 정답의 시작과 같더라도 동수여야 단서가 되지 않는다
    assert st.most_common(1)[0][1] <= 2, f'M01887: 시작 다수결 {dict(st)}'
    assert len(st) == 2 and set(st.values()) == {2}, f'M01887: 시작이 2:2 가 아님 {dict(st)}'
    assert len(en) == 1, f'M01887: 끝이 균일하지 않음 {dict(en)}'
    assert '(가) → (나) → (다) → (라)' not in x['choices'], 'M01887: 발문 나열 순서가 선지에 있다'
    print(f'  M01887 시작 {dict(st)} · 끝 {dict(en)} · 정답 {ans}')
    # M01891 어미 통일
    assert all(c.endswith('므로') for c in d['M01891']['choices']), 'M01891: 선지 어미 불일치'
    # M01891 결론 2○ 2× 유지
    assert sum(c.startswith('○') for c in d['M01891']['choices']) == 2, 'M01891: ○ 가 둘이 아님'

    STALE = {
        'M01887': ['(다) → (가) → (나) → (라)'],
        'M01888': ['보았다. 만약'],
        'M01891': ['무엇이든', 'hν 의 합도 ×', '남는다. × 인 것은'],
        'M01893': ['여섯 자리쯤'],
        'M01894': ['원자 속에서 나왔으니'],
        'M01896': ['정밀한 값으로'],
    }
    for fid, pats in STALE.items():
        blob = json.dumps(d[fid], ensure_ascii=False)
        for p in pats:
            assert p not in blob, f'{fid}: 걷어낸 문면 잔존 -> {p}'

