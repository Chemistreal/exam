for a, b in R:
    n = src.count(a)
    assert n == 1, f'{n}곳: {a[:50]!r}'
    src = src.replace(a, b)

open(P, 'w', encoding='utf-8').write(src)

# ── ★기계로 센다★ — 문항 블록 안에서 옛 낱말이 0 인지 확인한다 ─────────────
#   사람이 '다섯 자리' 목록을 적었다가 겨냥 줄을 빠뜨린 것이 5차의 구멍이었다.
#   블록을 통째로 잘라 세면 목록을 적을 필요가 없다.
def block(mid):
    i = src.index(f"    # ── M{mid} ──")
    nxt = [j for j in (src.find('    # ── M02', i + 10), src.find('    return it', i))
           if j != -1]
    b = src[i:min(nxt)]
    return '\n'.join(l for l in b.split('\n') if not l.strip().startswith('#'))


#   ▸ ★M02175 의 '급상승' 은 여기서 세지 않는다★ — 검사를 돌려 보니 skill · calc ·
#     objective 에도 그 낱말이 있었는데, 셋은 ★내부 표기★ 이고 학생이 읽는 자리가 아니다
#     (calc 는 '=' 와 '→' 를 쓴다). factchecker 가 짚은 것은 학생이 읽는 겨냥·도입 줄이다.
#     ★요건을 적는 낱말은 모든 자리에서 같아야 하지만, 문체는 내부와 학생 문면이 달라도
#     된다★ — 이 검사는 요건 낱말에만 건다.
for mid, words in [('02179', ['달라지는지', '달라진 것이', '달라지는 자리', '홀로 달라지']),
                   ('02184', ['핵간 거리'])]:
    b = block(mid)
    for w in words:
        assert w not in b, f'M{mid} 에 옛 낱말이 남았다: {w}'

# ── M02179 블록에서 '늘어' 계열이 요건 자리마다 있는지 ──────────────────────
b79 = block('02179')
for w, k in [('늘어난 자리', 2), ('늘어나는지 적어', 2), ('늘어나는 비교 자리', 1),
             ('늘어나는 자리', 2), ('늘어난 짝', 3)]:
    n = re.sub(r"'\s*\n\s*'", '', b79).count(w)
    assert n == k, f'M02179 {w}: {n} ≠ {k}'

b84 = block('02184')
assert re.sub(r"'\s*\n\s*'", '', b84).count('반지름과 핵 사이 거리가 같아진다') == 3

print('fix_t14_p5_r6 적용 완료 —', len(R), '곳')
