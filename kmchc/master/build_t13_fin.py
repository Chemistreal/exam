def local_checks(items):
    import re
    from collections import Counter
    bad = []

    # ① 오답 유형이 한 문항 안에서 겹치지 않을 것
    for x in items:
        ts = [w['type'] for w in x['distractors']]
        if len(set(ts)) < len(ts):
            bad.append(f"{x['id']} 오답 유형 중복 — {ts}")

    # ② 발문에 정답 문자열이 통째로 들어가 있지 않을 것
    for x in items:
        core = re.sub(r'[^0-9A-Za-z가-힣]', '', x['choices'][x['answer']])
        stem = re.sub(r'[^0-9A-Za-z가-힣]', '', x['stem'])
        if len(core) >= 6 and core in stem:
            bad.append(f"{x['id']} 발문에 정답이 통째로 들어 있음")

    # ③ 정답 길이 순위 — 유일 최장·최단이 없을 것
    for x in items:
        ls = [len(c) for c in x['choices']]
        a = x['answer']
        if ls.count(ls[a]) == 1 and (ls[a] == max(ls) or ls[a] == min(ls)):
            bad.append(f"{x['id']} 정답이 유일 최장·최단 {ls} (정답 {a+1})")

    # ④ ★G6 예고 — 머리 낱말 한 마디를 허용한 새 폭으로 본다★(T13 P16 이 넓혔다)
    for x in items:
        hs = [re.match(r'^(?:[가-힣a-zA-Z]{1,4}\s+)?(\d+)', c.strip()) for c in x['choices']]
        if all(hs):
            v = [int(h.group(1)) for h in hs]
            if any(v[i] > v[i + 1] for i in range(len(v) - 1)):
                bad.append(f"{x['id']} G6 — 수치 보기가 오름차순이 아님 {v}")

    d = {x['id']: x for x in items}

