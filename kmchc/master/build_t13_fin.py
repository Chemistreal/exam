    #    이 배치 1차에서 셋(M02132·M02133·M02134)이 걸렸다. 게이트는 ★병합한 뒤★ 짚어
    #    주므로 은행을 되돌리고 다시 빌드해야 했다. 저작 단계에서 먼저 막는다.
    #    (설계 주석과 이 검사 코드는 은행에 들어가지 않으므로 ★를 써도 된다.)
