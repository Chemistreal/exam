def local_checks(items):
    import re
    bad = []

    # ① 오답 유형이 한 문항 안에서 겹치지 않을 것
    for x in items:
        ts = [w['type'] for w in x['distractors']]
        if len(set(ts)) < len(ts):
            bad.append(f"{x['id']} 오답 유형 중복 — {ts}")

    # ② 발문에 정답 문자열이 통째로 들어가 있지 않을 것
    for x in items:
        core = re.sub(r'[^0-9A-Za-z가-힣]', '', x['choices'][x['answer']])
        stem = re.sub(r'[^0-9A-Za-z가-힣]', '', x['stem'])
        if len(core) >= 6 and core in stem:
            bad.append(f"{x['id']} 발문에 정답이 통째로 들어 있음")

    # ③ 정답 길이 순위 — 유일 최장·최단이 없을 것
    for x in items:
        ls = [len(c) for c in x['choices']]
        a = x['answer']
        if ls.count(ls[a]) == 1 and (ls[a] == max(ls) or ls[a] == min(ls)):
            bad.append(f"{x['id']} 정답이 유일 최장·최단 {ls} (정답 {a+1})")

    # ④ ★G6 예고 — 머리 낱말 한 마디를 허용한 새 폭으로 본다★(T13 P16 이 넓혔다)
    for x in items:
        hs = [re.match(r'^(?:[가-힣a-zA-Z]{1,4}\s+)?(\d+)', c.strip()) for c in x['choices']]
        if all(hs):
            v = [int(h.group(1)) for h in hs]
            if any(v[i] > v[i + 1] for i in range(len(v) - 1)):
                bad.append(f"{x['id']} G6 — 수치 보기가 오름차순이 아님 {v}")

    d = {x['id']: x for x in items}

    # ⑤ ★소재 제한★ — M02134 가 P15 M02117(구리 이온)과 겹치지 않게
    s134 = d['M02134']['stem'] + ''.join(d['M02134']['choices']) + d['M02134'].get('solution', '')
    for tok in ('구리', 'Cu', '크로뮴', 'Cr'):
        if tok in s134:
            bad.append(f"M02134 가 '{tok}' 를 적음 — P15 M02117 과 겹친다")

    # ⑥ ★M02131 이 채움 차례 규칙의 내용을 말하지 않을 것★ — P16 M02129 의 정답 근거다
    s131 = d['M02131'].get('solution', '')
    if '작은 것부터' in s131 or '먼저 채워' in s131:
        bad.append('M02131 이 채움 차례 규칙의 내용을 말함 — n + l 은 잣대 이름으로만 쓸 것')

    # ⑦ 지시 대상표
    REF = {'황의 원자 번호': 16, '네온의 원자 번호': 10, '철의 원자 번호': 26,
           'd 오비탈 수': 5, 'Fe²⁺ 의 홀전자': 4, 'Fe³⁺ 의 홀전자': 5}
    if REF['d 오비탈 수'] * 2 - 6 != REF['Fe²⁺ 의 홀전자']:
        bad.append('지시 대상표 오류 — 3d⁶ 의 홀전자 계산이 어긋남')
    if REF['d 오비탈 수'] != REF['Fe³⁺ 의 홀전자']:
        bad.append('지시 대상표 오류 — 3d⁵ 는 다섯 칸이 모두 홀전자다')

    # ⑧ ★G10 예고 — 은행 문면에 강조 표기를 남기지 말 것★
    #    이 배치 1차에서 셋(M02132·M02133·M02134)이 걸렸다. 게이트는 ★병합한 뒤★ 짚어
    #    주므로 은행을 되돌리고 다시 빌드해야 했다. 저작 단계에서 먼저 막는다.
    #    (설계 주석과 이 검사 코드는 은행에 들어가지 않으므로 ★를 써도 된다.)
    for x in items:
        for fld in ('stem', 'solution'):
            if '★' in x.get(fld, ''):
                bad.append(f"{x['id']} {fld} 에 강조 표기(★) — 은행은 평문")

    # ⑨ ★G3d 예고 — 자리 열이 주기 2 로 되풀이되지 않을 것★
    #    넷에 두 값을 둘씩 담으면 번갈아 놓기가 가장 자연스러운데 그것이 곧 주기 2 다.
    #    1차에서 ③④③④ 로 짰다가 걸렸다.
    seq = [x['answer'] for x in items]
    for p in (2, 3):
        if len(seq) >= 2 * p and all(seq[k] == seq[k % p] for k in range(len(seq))):
            bad.append(f"자리 열이 주기 {p} 로 되풀이됨 "
                       f"{'-'.join(str(a + 1) for a in seq)}")

    if bad:
        print('\n  ❌ 저작 점검 실패')
        for b in bad:
            print(f'     · {b}')
        raise SystemExit(1)
    print('  ✅ 저작 점검 통과 (유형·누설·길이순위·G6(확장)·소재·규칙 봉인·대상표'
          '·G10 평문·G3d 주기)')


