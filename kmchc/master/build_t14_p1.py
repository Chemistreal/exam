def local_checks(items):
    import re
    from collections import Counter
    bad = []

    # ① 오답 유형이 한 문항 안에서 겹치지 않을 것
    for x in items:
        ts = [w['type'] for w in x['distractors']]
        if len(set(ts)) < len(ts):
            bad.append(f"{x['id']} 오답 유형 중복 — {ts}")

    # ② 발문에 정답 문자열이 통째로 들어가 있지 않을 것
    for x in items:
        core = re.sub(r'[^0-9A-Za-z가-힣]', '', x['choices'][x['answer']])
        stem = re.sub(r'[^0-9A-Za-z가-힣]', '', x['stem'])
        if len(core) >= 6 and core in stem:
            bad.append(f"{x['id']} 발문에 정답이 통째로 들어 있음")

    # ③ 정답 길이 순위 — 유일 최장·최단이 없을 것
    for x in items:
        ls = [len(c) for c in x['choices']]
        a = x['answer']
        if ls.count(ls[a]) == 1 and (ls[a] == max(ls) or ls[a] == min(ls)):
            bad.append(f"{x['id']} 정답이 유일 최장·최단 {ls} (정답 {a+1})")

    # ④ ★교재가 준 다섯 수치 밖의 반지름 값을 지어내지 않았는가★
    #    198 · 99 · 176 · 77 · 154 와, 명시된 오개념의 산술 결과만 쓴다.
    OK = {'198', '99', '176', '77', '154', '88', '44', '22', '275', '286', '143', '200', '100'}
    for x in items:
        for m in re.finditer(r'(\d+)\s*pm', x['stem'] + ' '.join(x['choices'])):
            if m.group(1) not in OK:
                bad.append(f"{x['id']} 근거 없는 수치 {m.group(1)} pm")

    # ⑤ ★테마2 봉인 — 규칙을 발문 괄호에 인쇄하지 않았는가★
    #    테마2 는 "(결합 거리 = 두 반지름의 합)" 을 주고 대입시킨다. 이 배치는 그것이
    #    ★재는 것★ 이므로 발문에 적으면 문항이 통째로 죽는다.
    for x in items:
        if re.search(r'(결합 거리|핵 사이 거리)\s*=\s*', x['stem']) or '두 반지름의 합' in x['stem']:
            bad.append(f"{x['id']} 발문에 관계식을 인쇄함 — 이 배치가 재는 것을 준 셈")

    # ⑥ ★G3g 예고★ — 칸별 최빈값 조합이 정답을 유일하게 짚지 않을 것
    for x in items:
        toks = [c.split() for c in x['choices']]
        if len(toks[0]) >= 2 and all(len(t) == len(toks[0]) for t in toks):
            picks = []
            for col in zip(*toks):
                cc = Counter(col).most_common()
                win = [v for v, k in cc if k == cc[0][1]]
                picks.append(win[0] if len(win) == 1 else None)
            if any(p is not None for p in picks):
                surv = [i for i, t in enumerate(toks)
                        if all(p is None or t[k] == p for k, p in enumerate(picks))]
                if surv == [x['answer']]:
                    bad.append(f"{x['id']} 칸별 최빈값 조합이 정답을 유일하게 짚음")

    # ⑦ ★선지 사이 포함관계★ — 한 선지가 다른 선지를 통째로 품지 않을 것
    for x in items:
        for i, c in enumerate(x['choices']):
            for j, d in enumerate(x['choices']):
                if i != j and len(c) >= 6 and c in d:
                    bad.append(f"{x['id']} {i+1} 이 {j+1} 안에 통째로 들어 있음")

    # ⑧ ★G10 평문★
    for x in items:
        for fld in ('stem', 'solution'):
            if '★' in x.get(fld, ''):
                bad.append(f"{x['id']} {fld} 에 강조 표기(★) — 은행은 평문")

    # ⑨ ★난이도 상한★ — 쉬움 2 를 넘기지 않는다(T13 부채)
    ec = sum(1 for x in items if x['difficulty'] == '쉬움')
    if ec > 2:
        bad.append(f'쉬움 {ec}제 — 착수 규약의 상한 2 를 넘김')

    if bad:
        print('\n  ❌ 저작 점검 실패')
        for b in bad:
            print(f'     · {b}')
        raise SystemExit(1)
    print('  ✅ 저작 점검 통과 (유형·누설·길이순위·수치 근거·관계식 봉인'
          '·G3g·포함관계·G10 평문·쉬움 상한)')


