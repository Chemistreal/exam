sub(by['M01984'],
    '실제로는 여기에 교환에너지 몫도 함께 들어가는데, 두 몫을 합치면 언제나 짝짓는 쪽이 '
    '손해라 결과는 달라지지 않아.',
    '실제로는 여기에 교환에너지 몫도 함께 들어가는데, 지금처럼 에너지가 같은 오비탈끼리라면 '
    '두 몫을 합쳐도 짝짓는 쪽이 손해라 결과는 달라지지 않아. 부껍질이 다른 자리에서는 이야기가 '
    '달라지니 이 결론을 아무 데나 옮기지는 말자.')

