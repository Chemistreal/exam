for i in range(1981, 1991):
    x = by[f'M0{i}']
    now = (json.dumps(x['choices'], ensure_ascii=False), x['stem'], x['answer'])
    if i not in (1988, 1989):
        assert now == before[i], f'M0{i}: 손대지 않기로 한 문항인데 구조가 바뀌었다'
    assert x['stem'] == before[i][1] and x['answer'] == before[i][2], f'M0{i}: 발문·정답 불변 위반'
    L = [len(c) for c in x['choices']]
