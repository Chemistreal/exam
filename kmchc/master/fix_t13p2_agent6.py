# ── sim : (ㄴ) 우회로를 닫는 오답 둘 ─────────────────────────────────────
def retext(it, idx, new):
    old = it['choices'][idx]
    assert new not in it['choices'], (it['id'], new)
    it['choices'][idx] = new
    if old in it['solution']:
        it['solution'] = it['solution'].replace(old, new)


it = by['M01988']
