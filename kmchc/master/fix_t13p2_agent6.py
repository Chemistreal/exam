"""T13 P2 — 6차 조치 (서술 넷 + (ㄴ) 우회로를 닫는 오답 둘).

4차 순회에서 **세 검증자가 모두 실체 0 건**이 되었다.

    solver      10/10 확실 · 자족성 전원 충족 · **지적 사항 없음**
                배치 편향도 해소 확인 — 수치 문항 셋의 정답이 2·3·4 번으로 흩어져
                "수치 정답은 늘 최댓값" 식 소거가 통하지 않는다.
    defender    ★F2 실패 후보 없음★ 27 개 오답 전부 어느 경로로도 변호 불가.
                5차에 갈아 넣은 네 오답이 **그 자체로 참인 진술**이 되지 않았는지
                따로 짚어 확인해 주었다 — 모두 독립 진술로도 거짓.
    factchecker ★사실 오류 없음 · 경로 뒤바뀜 없음 · 번호 어긋남 없음 ·
                문항 사이 모순 없음★ 오답 서른의 경로를 값으로 전수 검산했고,
                4차에 잡았던 '두 선지 경로 교차' 유형을 겨눈 네 쌍도 모두 정합.

남은 것은 factchecker 의 △ 넷이고 모두 **화학 주장을 건드리지 않는 서술**이다.

────────────────────────────────────────────────────────────────
△1 M01984 — "언제나" 의 범위가 열려 있다
────────────────────────────────────────────────────────────────
"두 몫을 합치면 **언제나** 짝짓는 쪽이 손해라" 는 **축퇴된 같은 부껍질 안에서만**
참이다. 부껍질이 다르면(4s 와 3d 처럼) 짝짓는 쪽이 이기는 경우가 있다. 범위를
열어 두면 "원자는 짝을 짓기 전에 반드시 다른 오비탈로 간다" 로 굳는다.

────────────────────────────────────────────────────────────────
△2 M01989 — 적힌 항만 보고 껍질 전체를 말하게 된다
────────────────────────────────────────────────────────────────
"4f 에 열넷, 5d 에 열이 있어" 는 적힌 항 기준으로는 맞지만, 비스무트의
n = 4 껍질은 실제로 32 개, n = 5 껍질은 18 개(5s² 5p⁶ 5d¹⁰)이고 나머지는
[Xe] 안에 숨어 있다. 학생이 "n = 4 껍질에는 전자가 14 개" 로 굳힐 소지가 있다.

★이 문항은 '가장 바깥 껍질' 을 묻고 있어 값에는 영향이 없지만, 같은 배치의
M01983·M01990 이 '껍질과 부껍질을 갈라 세기' 를 재고 있어 어긋나 보인다.★

────────────────────────────────────────────────────────────────
△3 M01982 — 두 오답의 경로가 값에 비해 모호하다
────────────────────────────────────────────────────────────────
② 는 5차에 경로를 또렷이 적었는데 ③ 과 ④ 는 그렇지 않다. ③('3·3·3')의 경로는
'이온이 되어도 홀전자 수는 변하지 않는다' 는 가정이고, ④('3·4·5')는 '이온화할
때마다 짝이 하나씩 풀린다' 는 가정이다. 적어 두지 않으면 학생이 자기 오류를
특정하지 못한다.

────────────────────────────────────────────────────────────────
△4 M01988 — 이온 배치를 오비탈 순서로만 설명하는 단정
────────────────────────────────────────────────────────────────
"3d 가 4s 아래로 내려가는데, 전이금속 이온에서 4s 가 먼저 빠지는 것이 **그**
**때문이야**" — 고교 교육과정에서 널리 쓰는 설명이지만 엄밀히는 이온의 배치가
오비탈 순서 역전이 아니라 이온 전체의 에너지 최소화로 정해진다. 단정형이라
절대 규칙으로 받아들여진다. '그렇게 설명한다' 는 층위로 낮춘다.

────────────────────────────────────────────────────────────────
그리고 sim 이 남긴 두 자리 — ★소거만으로 답이 남는 우회로★
────────────────────────────────────────────────────────────────
sim 은 A 0 / B 0 / C 7 / D 10(D 전원 정답)을 내면서 죽은 선지 일곱을 짚었다.
그 가운데 **둘은 죽었을 뿐 아니라 (ㄴ) 우회로를 열어 두고 있었다.**

· **M01988** — ①("정원이 8 로 줄어서")과 ②("M 껍질이 다 차야 넘어가서")가 둘 다
  ★발문의 서술과 정면으로 어긋나 화학 없이 소거된다.★ 4s/3d 역전을 몰라도
  ④(팔전자)만 걸러 내면 ③ 이 남는다.
  → ② 를 **'아르곤 자리에는 3d 오비탈이 아직 생겨나지 않아서'** 로. 오비탈은
    채워지든 말든 있으므로 명백히 거짓이고, ★발문만으로는 소거되지 않는다.★
    2차의 '아직 없어서' 는 '아직 안 찼다' 로 읽혀 참이 될 수 있었는데(defender),
    '생겨나지 않는다' 는 그 독법이 닫힌다.
· **M01989** — "가장 바깥 = 주양자수가 큰 쪽" 한 줄로 ③(n=5)·④(n=4)가 날아가
  5 대 3 이지선다가 된다.
  → ③ 을 **'주양자수 6 · 전자 15 개'**(6s²6p³ 에 5d¹⁰ 까지 원자가로 묶은 값)로.
    ★세 선지가 모두 n = 6 이 되어 주양자수만으로는 갈리지 않는다.★ 죽은 선지가
    살아나면서 C 의 붕괴 착지점도 새로 생긴다.

★멈춤 규칙(P1 7차)의 예외 조건에 맞는 자리만 손댔다★ — 둘 다 이미 아는 사실만
쓰고 길이·G3b 를 깨지 않는다. 나머지 다섯은 남긴다.

받아들이지 않은 것
· M01986 ① → '+1/2' — 2차에 패리티로 죽어 뺀 값을 도로 넣자는 것(세 번째).
· M01985 ① → '[Ne] 3s² 3p⁷' — defender·factchecker 가 복수정답 시비를 경고했다.
· M01987 ① → '2s 와 3s' — ④(2pz·3pz)가 이미 'l 이 같고 n 이 다른' 자리라 겹친다.
  ④ → '3dxy 와 3dz²' 는 ③(2px·2py)과 **같은 까닭으로 함께 지워져** (ㄱ) 형제 조항 위반.
· M01981 ② → 'Li 가 Li⁺ 로' — 15 자라 정답(17 자)이 유일최장이 된다. 경로는 좋다.
· M01983 ③ → '10 개' — 12 아래 자리가 하나뿐이라 살아 있는 6 을 빼야 넣을 수 있다.
"""
import json
from collections import Counter

BANK = 'master/master_bank.json'
MK = ['①', '②', '③', '④']

bank = json.load(open(BANK, encoding='utf-8'))
by = {x['id']: x for x in bank}
before = {i: (json.dumps(by[f'M0{i}']['choices'], ensure_ascii=False),
              by[f'M0{i}']['stem'], by[f'M0{i}']['answer']) for i in range(1981, 1991)}


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:40]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


