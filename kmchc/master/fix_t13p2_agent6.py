    '④ 차례로 3 · 4 · 5: 이온화할 때마다 짝이 하나씩 풀린다고 본 값이야. 방향은 맞게 보았지만 '
    '한 걸음 이르지. Co²⁺ 까지는 4s 만 빠져 3d⁷ 이 그대로라 홀전자가 변하지 않고, 짝이 풀리는 '
