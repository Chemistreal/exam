def main():
    d = json.load(open(BANK, encoding='utf-8'))
    items = d if isinstance(d, list) else d['items']
    x = {it['id']: it for it in items}

    ids = [f'M0{i}' for i in range(1907, 1917)]
    assert set(WATCH) == set(ids), f'watch 대상 어긋남: {set(WATCH) ^ set(ids)}'

    tot = 0
    for fid in ids:
        it = x[fid]
        v = it.get('verified') or {}
        assert 'layer5' not in v, f'{fid}: 이미 층5 기록됨'
        v.update({'layer5': LAYER5, 'at': AT, 'by': '독립 에이전트 패스',
                  'watch': WATCH[fid]})
        it['verified'] = v
        tot += len(WATCH[fid])

    for fid in ids:
        w = x[fid]['verified']['watch']
        assert len(w) >= 200, f'{fid}: watch 가 너무 짧다 ({len(w)}자)'
