#   ★완전 병렬로 만들면 자카드가 터진다★ — 병렬성과 어휘 겹침은 맞바꿈이라 한정어를 남긴다.
rep('어느 그래프에서나 알칼리 금속 자리가 그 주기의 봉우리가 된다',
    '어느 그래프에서나 알칼리 금속이 그 주기의 봉우리에 놓인다')

# ════ 권고 2·5·6 — M02325 ① 의 머리·반박, 그리고 반박 차례 ════
rep('넷 — 급증을 빼고 적힌 값 열둘을 껍질마다 셋씩 잡아 넷이다',
    '넷 — 급증 자리가 둘이지만 적힌 값 열둘을 셋씩 잡아 넷이다')
rep("          '②는 하나 — 급증 자리가 둘이므로 그 사이의 껍질 하나만 센다 라고 했어. 경계 사이만 '\n"
    "          '세면 양쪽 끝의 껍질을 빠뜨리지. '\n"
    "          '③은 둘 — 급증 자리가 둘이므로 껍질의 수도 그대로 둘이다 라고 했어. 경계의 수와 덩어리의 수는 하나 '\n"
    "          '차이야. '\n"
    "          '①은 넷 — 급증 자리가 둘이지만 적힌 값 열둘을 셋씩 잡아 넷이다 라고 했어. 값을 더 적거나 덜 적으면 '\n"
    "          '답이 달라지니 셈의 근거가 되지 못해. '",
    "          '①은 넷 — 급증 자리가 둘이지만 적힌 값 열둘을 셋씩 잡아 넷이다 라고 했어. 금 두 개가 '\n"
    "          '나눈 덩어리는 둘·여덟·둘이라 셋씩이 아니야. '\n"
    "          '②는 하나 — 급증 자리가 둘이므로 그 사이의 껍질 하나만 센다 라고 했어. 경계 사이만 '\n"
    "          '세면 양쪽 끝의 껍질을 빠뜨리지. '\n"
    "          '③은 둘 — 급증 자리가 둘이므로 껍질의 수도 그대로 둘이다 라고 했어. 경계의 수와 덩어리의 수는 하나 '\n"
    "          '차이야. '")
rep("'넷 — 급증 자리가 둘이지만 적힌 값 열둘을 셋씩 잡아 넷이다': '값을 더 적으면 답이 달라져.'",
    "'넷 — 급증 자리가 둘이지만 적힌 값 열둘을 셋씩 잡아 넷이다': '덩어리는 둘·여덟·둘이야.'")
rep("① 은 급증을 버리고 값의 개수를 나눔(값을 더 적으면 답이 달라짐)'",
    "① 은 값의 개수를 나눔(덩어리는 둘·여덟·둘이라 셋씩이 아님)'")

try:
    ast.parse(body)
except SyntaxError as e:
    sys.stderr.write('문법 오류 %s — 원본 복구\n' % e)
    io.open(SRC, 'w', encoding='utf-8').write(BEFORE)
    raise

GONE = ['화합물을 만들지 않기 때문이라고', '같은 주기에 있는 다른 원소보다',
        '전자가 둘 짝지어 들어가기 때문이라고', '봉우리가 된다',
        '급증을 빼고 적힌 값 열둘']
for g in GONE:
    assert g not in body, 'GONE 남음: %r' % g

