MK = '①②③④'


def parts(it):
    lines = it['solution'].split('\n')
    lead = lines[0]
    diag = [L for L in lines if L.startswith('자가진단:')][0]
    a = it['answer']
    head = f'[정답] {MK[a]} {it["choices"][a]} — '
    hit = [L for L in lines if L.startswith('[정답] ')]
    assert len(hit) == 1 and hit[0].startswith(head), it['id']
    return lead, hit[0][len(head):], diag


def rebuild(it, choices, ans, reb, wrongs, cor=None):
    """선지·정답 자리·반박·오답 메타를 통째로 다시 세운다."""
    lead, cur, diag = parts(it)
    it['choices'] = list(choices)
    it['answer'] = ans
    it['distractors'] = [{'opt': choices.index(t), 'error': e, 'type': ty} for t, e, ty in wrongs]
    it['distractors'].sort(key=lambda d: d['opt'])
    body = [lead, '', f'[정답] {MK[ans]} {choices[ans]} — {cor if cor else cur}', '']
    body += [f'{MK[k]} {choices[k]}: {reb[choices[k]]}' for k in range(4) if k != ans]
    body += ['', diag]
    it['solution'] = '\n'.join(body)


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:36]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


def stem(it, old, new):
    assert it['stem'].count(old) == 1, it['id']
    it['stem'] = it['stem'].replace(old, new)


def field(it, key, old, new):
    assert it[key].count(old) == 1, (it['id'], key)
    it[key] = it[key].replace(old, new)


