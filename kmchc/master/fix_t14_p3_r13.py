"""T14 P3 13차 조치 — 압축 줄을 기계로 잡으려다 오탐 6:1 을 재고 손으로 돌아왔다.

13차 순회의 자리
────────────────────────────────────────────────────────────────────
▸ solver: ★0건★ (두 회차 연속). 인용 의무를 넣은 뒤 근거가 자료로 못 박혀 나왔다 —
  M02162 를 두고 '발문 안에 반례가 실려 있음 — ①은 Sr²⁺(껍질 4, 118) < K⁺(껍질 3, 138),
  ④는 Sr²⁺(2가, 118) > Li⁺(1가, 76)' 이라 값을 그대로 인용했다.
  ★12차에 defender 가 최우선으로 올린 지적을 독립 검증자가 자료로 반박한 셈이다.★
▸ student-sim: ★문항 결함 없음★ (다섯 회차 연속 F2 0건). 죽은 선지 하나를 대안 없음으로
  닫으며 후보 셋을 스스로 기각했다.
▸ factchecker: ★12차에 고친 다섯 문면을 모두 참으로 확인★ 하고 새 지적 둘을 냈다.
▸ defender: 지적 여섯 중 넷은 스스로 '결함까지는 아니다' 로 닫았고, 하나는 구조적
  한계라며 교체안을 내지 못했다. 받을 것은 하나다.

★기계화를 시도했다가 접었다★ — 이 회차의 가장 큰 배움
────────────────────────────────────────────────────────────────────
압축 줄에서 한정어가 빠지는 병이 다섯 회차째라 국소검사로 세우려 했다. 해설을
'[정답] 본문' 과 '압축 블록' 으로 갈라, 오답별 본문 문단에 있는 한정어가 그 오답의 압축
줄에 없으면 걸도록 짰다. ★실측: 7건이 울었고 그중 진짜는 1건(M02163 ④) — 오탐 6:1.★
  · M02161 ④ 본문 '같은 족이면' → 압축 '모두 1족이라' (같은 뜻을 다른 낱말로 적었다)
  · M02160 ① 본문 '이 방법으로' → 압축 '못 얻는 것과 없는 것은 달라' (뜻이 살아 있다)
★압축은 본디 덜어내는 것이라, 한정어가 빠졌다는 사실만으로는 결함이 아니다.★
결함은 빠진 한정어가 ★판정을 뒤집을 때★ 뿐이고 그것은 낱말로 셀 수 없다.
→ 게이트로 세우지 않는다. 대신 저작 지침에 적는다: ★오답 문면을 고칠 때 압축 줄을 같은
  붓으로 고치고, 압축 줄만 따로 읽어 참인지 본다.★ (P2 17차의 교훈과 같은 결론이다 —
  ★오탐부터 세면 세우지 말아야 할 검사가 보인다.★)

13차 조치 넷
────────────────────────────────────────────────────────────────────
① M02164 ④ 반박 논거 교체 (factchecker 중상)
   '이 그래프에는 양성자 수 축이 아예 없어서 견줄 상대도 없지' 는 같은 해설 앞부분과
   어긋난다 — 앞에서 가로축이 원자 번호임을 전제했고 ★원자 번호가 곧 양성자 수★ 이므로
   양성자 수는 이미 그래프에 있다. ④ 를 무너뜨리는 진짜 논거는 ★유효 핵전하 축에 숫자가
   없어 값을 읽을 수 없다★ 는 것이고, 이는 이 문항의 중심 논지와도 같다.
② M02163 ④ 압축 줄에 '알려진 값' 을 되살림 (factchecker 중)
   본문은 '주기율표 안의 자리와 알려진 값을 쓰면' 이라 적고 곧이어 '주기 번호만으로는
   정해지지 않아' 로 반례를 들었는데, 압축 줄은 '주기율표 안의 자리를 쓰면' 만 남아
   본문이 부정한 것을 압축 줄이 주장하는 꼴이 됐다. ★이것이 위 실측에서 유일한 진짜다.★
③ M02155 ① 압축 줄에 '중성 원자끼리' (factchecker 낮음)
   본문은 '같은 족의 중성 원자끼리' 로 한정했는데 압축 줄은 '같은 족에서' 만 남았다.
   이온까지 덮으면 참이 아니고, 바로 이 배치가 이온을 다룬다.
④ M02161 발문에 '원자 번호는 차례로 3, 11, 19 이다' (defender 보통)
   ② '껍질 수가 같아 양성자 수가 순서를 정했다' 를 깨려면 리튬·나트륨·칼륨이 서로 다른
   주기라는 ★발문 밖 지식★ 이 필요했다. 같은 배치의 M02162 는 껍질 수를 발문에 명시했는데
   M02161 만 빠져 ★비대칭★ 이었다. 원자 번호는 반지름이 아니므로 척도 부채를 키우지 않고,
   정답 ①('전하가 같으므로 껍질 수가 순서를 정했다')을 발문이 대신 말해 주지도 않는다.
   ▸ 11·12차에 두 번 기각한 것은 ★원자 반지름 값★ 을 실으라는 처방이었다. 그것은 두
     척도를 한 발문에 나란히 놓는 일이라 다르다. ★기각한 것과 받는 것을 가려 적는다.★

기각
────────────────────────────────────────────────────────────────────
▸ ★기각★ M02160 ③ 이 F2 위험이라는 지적(defender 보통) — ★같은 검증자가 12차에는
  '결함까지는 아니고 의도된 한정어 변별로 읽힌다. 수정 제안 없음' 이라 적었다.★ 다른
  검증자는 이번 회차에 아무도 지지하지 않는다: solver 는 ①③ 이 발문 한 줄로 명시적으로
  반박된다며 0건, student-sim 은 B 프로필이 실제로 고르는 살아 있는 선지로 보았고,
  factchecker 는 그 반박 문면을 참으로 확인했다. 게다가 '이 방법으로 못 잰다' 와 '크기가
  없다' 를 가르는 것은 ★C14-005 가 못 박은 이 문항의 구인 그 자체★ 다.
▸ ★기각★ M02163 ③④ 겨냥 중복(defender 보통, 네 번째) — defender 자신이 '발문을 손대지
  않으면 해소되지 않으며 교체안이 전부 같은 유형으로 되돌아가 제안하지 않는다' 고 적었다.
  세트 조립 부채로 남긴다.
▸ ★기각★ M02164 ②④ 반박 근거 절반 겹침(defender 낮음) · M02157 ④ 와 M02156 ② 의 한 절
  참(defender 낮음, 스스로 '결함까지는 아니다') · M02164 ③ 의 확장 추론 여지(solver·
  defender 낮음, 발문이 '이 그래프로' 를 두 번 못 박는다).
▸ ★기각★ 죽은 선지 M02160 ① · M02157 ③ — 두 검증자가 ★손대지 말 것★ 을 권했다.
  student-sim 은 후보 셋을 스스로 기각했고 defender 는 '매력적으로 고치려다 참인 절을
  끌어들이는 게 더 나쁘다' 고 적었다.
"""
import re

P = 'build_t14_p3.py'
src = open(P, encoding='utf-8').read()
orig = src

R = [
    # ── ① M02164 ④ 반박 논거 ────────────────────────────────────────
    ("          '핵을 가려 유효 핵전하가 핵전하보다 작아. 게다가 이 그래프에는 양성자 수 축이 아예 없어서 견줄 상대도 없지. '\n"
     "          '이 그래프에 없는 것을 이 그래프로 확인할 수는 없어.',\n",
     "          '핵을 가려 유효 핵전하가 핵전하보다 작아. 게다가 유효 핵전하 축에는 숫자가 없으니, '\n"
     "          '원자 번호로 알 수 있는 양성자 수와 견주어 같다 다르다를 말할 수가 없지. '\n"
     "          '숫자로 적히지 않은 것을 숫자로 확인할 수는 없어.',\n"),
    ("           '유효 핵전하가 양성자 수와 같음을 확인할 수 있다': '전자가 둘 이상이면 가림이 있어 '\n"
     "                                                            '유효 핵전하가 더 작고, 이 '\n"
     "                                                            '그래프에는 양성자 수 축이 없어.'},\n",
     "           '유효 핵전하가 양성자 수와 같음을 확인할 수 있다': '전자가 둘 이상이면 가림이 있어 '\n"
     "                                                            '유효 핵전하가 더 작고, 축에 숫자가 '\n"
     "                                                            '없어 견줄 수도 없어.'},\n"),
    # ── ② M02163 ④ 압축 줄에 '알려진 값' ────────────────────────────
    ("           '플루오린 F, 칼슘 Ca': '주기율표 안의 자리를 쓰면 답이 나오지만 물음은 이 두 줄로 '\n",
     "           '플루오린 F, 칼슘 Ca': '주기율표 안의 자리와 알려진 값을 쓰면 답이 나오지만 물음은 '\n"
     "                                  '이 두 줄로 '\n"),
    # ── ③ M02155 ① 압축 줄에 '중성 원자끼리' ────────────────────────
    ("                                                       '아래로 내려가면 커지니 봉우리도 골도 '\n",
     "                                                       '중성 원자끼리 아래로 내려가면 커지니 '\n"
     "                                                       '봉우리도 골도 '\n"),
    # ── ④ M02161 발문에 원자 번호 ───────────────────────────────────
    ("             '리튬·나트륨·칼륨은 모두 1족이고, 그 이온의 반지름은 차례로 76 pm, 102 pm, '\n",
     "             '리튬·나트륨·칼륨은 모두 1족이고 원자 번호는 차례로 3, 11, 19 이다. '\n"
     "             '그 이온의 반지름은 차례로 76 pm, 102 pm, '\n"),
]

for a, b in R:
    n = src.count(a)
    assert n == 1, f'{n}곳 — {a[:56]!r}'
    src = src.replace(a, b)

body = '\n'.join(l for l in src.split('\n') if not l.lstrip().startswith('#'))
body = body[body.index('def build('):]
BAN_AFTER = [
    '양성자 수 축이 아예 없어서',          # M02164 옛 논거
    '이 그래프에 없는 것을 이 그래프로',    # M02164 옛 마무리
    '그래프에는 양성자 수 축이 없어',       # M02164 옛 압축 줄
]
for b in BAN_AFTER:
    assert b not in body, f'금지 문면 잔존 — {b}'

flat = re.sub(r"'\s*\n\s*'", '', body)
COUNTS = [
    ('유효 핵전하 축에는 숫자가 없으니', 1),
    ('축에 숫자가 없어 견줄 수도 없어', 1),
    ('주기율표 안의 자리와 알려진 값을 쓰면 답이 나오지만 물음은 이 두 줄로', 1),
    ('같은 족에서 중성 원자끼리 아래로 내려가면 커지니', 1),
    ('모두 1족이고 원자 번호는 차례로 3, 11, 19 이다', 1),
]
for s, k in COUNTS:
    n = flat.count(s)
    assert n == k, f'{s[:34]!r} — {n}곳 (기대 {k})'

assert src != orig
open(P, 'w', encoding='utf-8').write(src)
print('✅ 13차 조치 적용 — M02164 ④ 논거·압축 줄 · M02163 ④ 압축 줄 · '
      'M02155 ① 압축 줄 · M02161 발문 원자 번호')
