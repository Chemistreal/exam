import json, os

BJ = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'master_bank.json')
MK = '①②③④'


def swap_choice(it, idx, new_txt, new_rebut, err, typ):
    mark = MK[idx]
    old = it['choices'][idx]
    assert idx != it['answer'], f"{it['id']}: 정답 자리는 이 헬퍼로 바꾸지 않는다"
    lines = it['solution'].split('\n')
    hit = [i for i, L in enumerate(lines) if L.startswith(f'{mark} {old}:')]
    assert len(hit) == 1, f"{it['id']}: 해설 {mark} 줄을 못 찾음"
    lines[hit[0]] = f'{mark} {new_txt}: {new_rebut}'
    it['solution'] = '\n'.join(lines)
    it['choices'][idx] = new_txt
    for dd in it['distractors']:
        if dd['opt'] == idx:
            dd['error'], dd['type'] = err, typ
            break
    else:
        raise AssertionError(f"{it['id']}: distractor {idx} 없음")


def set_answer(it, new_txt):
    idx = it['answer']
    head = f'[정답] {MK[idx]} {it["choices"][idx]} —'
    assert head in it['solution'], f"{it['id']}: [정답] 줄 머리를 못 찾음"
    it['solution'] = it['solution'].replace(head, f'[정답] {MK[idx]} {new_txt} —', 1)
    it['choices'][idx] = new_txt


REPL = [
    # ★factchecker ✗★ — 조성 진술이 되어 버린 자리를 개수 진술로 되돌린다
    ('M01928', 'solution',
     '수소 원자핵은 양성자 하나, 헬륨 원자핵은 양성자 둘이야.',
     '수소 원자핵에는 양성자가 하나, 헬륨 원자핵에는 양성자가 둘 있어.'),
    # factchecker △ — '휘어짐은 질량과 완전히 무관' 으로 일반화되지 않게 완화
    ('M01934', 'solution',
     '그리고 휘어짐이 말해 주는 것은 질량이 아니라 전하의 부호야.',
     '그리고 휘어짐이 곧바로 말해 주는 것은 질량이 아니라 전하의 부호야.'),
]


def main():
    bank = json.load(open(BJ, encoding='utf-8'))
    x = {i['id']: i for i in bank}
    ids = [f'M0{i}' for i in range(1927, 1937)]

    # ── M01927 ② 교체 (세 회차 죽음 + 겉도는 선지) ─────────────────
    swap_choice(x['M01927'], 1, '전자는 어느 반지름의 궤도에서나 돌 수 있다',
                '그것은 보어가 버린 그림이야. 어느 자리에나 있을 수 있으면 나오는 빛도 '
                '이어진 띠가 되어 선스펙트럼이 설명되지 않지.',
                '보어가 버린 연속 궤도를 새 가정으로 봄', 'surface')

    # ── M01928 쌍둥이 깨기 + 길이 재배치 ─────────────────────────
    set_answer(x['M01928'], '전자의 질량은 양성자에 견주어 아주 작다')
    swap_choice(x['M01928'], 0, '수소와 헬륨이 지닌 전자의 개수가 서로 같다',
                '수소는 하나, 헬륨은 둘이야. 수가 같아서 무시된 것이 아니라 가벼워서 무시된 거지.',
                '전자 수가 같아야 논증이 선다고 봄 — 수가 달라도 가벼워서 무시된다', 'conserv')
    swap_choice(x['M01928'], 2, '헬륨 원자핵이 띤 전하는 수소의 네 배다',
                '전하는 양성자 수가 정하니 두 배야. 네 배가 된 것은 질량이지 전하가 아니지.',
                '질량이 네 배인 것을 전하가 네 배인 것으로 옮겨 읽음', 'surface')

    # ── M01934 되튐 축 다수결 차단 ───────────────────────────────
    swap_choice(x['M01934'], 2,
                '휘어짐 — 원자가 대부분 비어 있다 · 되튐 — 핵이 알파를 끌어당겼다',
                '알파 입자도 핵도 (+)전하라 서로 밀어내지 끌어당기지 않아. '
                '그리고 빈 공간을 말해 주는 것은 통과야.',
                '같은 부호끼리 끌어당긴다고 보고 휘어짐에 통과의 결론을 붙임', 'sign')

    miss = [(f, k, a[:26]) for f, k, a, _ in REPL if a not in x[f][k]]
    assert not miss, f'치환 대상 없음: {miss}'
    for f, k, a, b in REPL:
        x[f][k] = x[f][k].replace(a, b, 1)

    # ── 자기 검사 ────────────────────────────────────────────────
    from collections import Counter
    for fid in ids:
        it = x[fid]
        sol = it['solution']
        for k, c in enumerate(it['choices']):
            if k == it['answer']:
                assert f'[정답] {MK[k]} {c} —' in sol, f'{fid}: [정답] 줄 어긋남'
            else:
                assert f'{MK[k]} {c}:' in sol, f'{fid}: {k + 1} 번 줄 어긋남'
        assert sorted(d['opt'] for d in it['distractors']) == \
            sorted(k for k in range(4) if k != it['answer']), f'{fid}: 오답 자리 어긋남'
        assert '★' not in it['stem'] and '★' not in sol, f'{fid}: 강조 기호 잔존'
        assert len(sol) >= 300, f'{fid}: 해설이 300자 미만 ({len(sol)})'
    assert Counter(x[f]['answer'] + 1 for f in ids) == Counter({1: 2, 2: 3, 3: 2, 4: 3})
    # 조성 진술이 남지 않았는가
    assert '헬륨 원자핵은 양성자 둘' not in x['M01928']['solution'], 'M01928: 조성 진술 잔존'
    # M01928 쌍둥이가 깨졌는가 — '만큼 작다' 는 ④ 하나뿐
    assert sum('셈에 넣지 않아도 될 만큼' in c for c in x['M01928']['choices']) == 1
    # M01934 되튐 축 네 값이 모두 다른가
    tails = [c.split('되튐 — ')[1] for c in x['M01934']['choices']]
    assert len(set(tails)) == 4 and sum('무겁다' in t for t in tails) == 1, f'M01934 되튐 축: {tails}'

    json.dump(bank, open(BJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('P13 3차 조치 완료 — 정답 문면 1 · 오답 교체 4 · 본문 치환 2')
    for fid in ids:
        L = [len(c) for c in x[fid]['choices']]
        s = sorted(L)
        sp = (s[3] - s[0]) / ((s[1] + s[2]) / 2)
        r = sorted(range(4), key=lambda i: -L[i]).index(x[fid]['answer']) + 1
        flag = ''
        if L[x[fid]['answer']] == max(L) and L.count(max(L)) == 1:
            flag = ' G3-최장'
        if L[x[fid]['answer']] == min(L) and L.count(min(L)) == 1:
            flag = ' G3-최단'
        if sp > 0.25 and s[1] >= 8:
            flag += ' G3b'
        print(f'  {fid} {L} 산포{sp:.2f} 순위{r}{flag}')


if __name__ == '__main__':
    main()
