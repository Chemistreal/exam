"""T14 P5 7차 조치 — 앞 배치의 겨냥 문구가 뒤 배치에 남는다.

solver ★0건★ · defender ★F2 0건 · 마감 진행 가능★ · factchecker 1건(마감 보류).
두 자리만 고친다.

★① 겨냥 줄이 다른 계열의 문구를 그대로 쓰고 있었다.★
  M02180 의 겨냥·도입 줄만 '★두 원소 사이에서★ 무엇이 같고 무엇이 달라졌는지
  먼저 적어 봐' 였다. 그런데 이 문항이 다루는 것은 처음부터 끝까지 ★두 사실★
  (양성자가 많으면 작아진다 / 칼륨이 가장 크다)의 충돌과 우선순위이고, 본문은
  ★칼륨 대 다른 원소들(복수)★ 을 견주므로 수도 맞지 않는다.
  ▸ '무엇이 같고 무엇이 달라졌는지' 는 ★통제 비교 계열(M02177·M02179)의 겨냥
    문구★ 다. 그 문구가 우선순위 문항에 남았다 — ★한 배치 안에서 계열이 다른
    문항에 같은 겨냥 문구를 쓰면, 절차가 그 문항의 것이 아니게 된다.★
  ▸ factchecker 가 "본문만 읽으면 눈에 띄지 않는 유형" 이라 적었고 실제로 ★여섯
    회차를 살아남았다★. 겨냥 줄과 본문을 ★나란히 놓고★ 읽어야 보인다.
  ▸ 이 배치에서 겨냥 줄이 걸린 것이 세 번째다(6차 M02179 의 요건 낱말 · 6차
    M02175 의 문체 · 7차 M02180 의 계열). ★겨냥 줄은 저작할 때 마지막에 적고
    나중에 아무도 읽지 않는 자리다★ — 순회 프롬프트에 겨냥·본문 대조를 상설로
    넣는다.

★② 낱말을 맞추다 새 갈래를 열었다.★
  6차에 M02184 ④ 를 '반지름이 핵간 거리와 같아진다' → '반지름과 핵 사이 거리가
  같아진다' 로 바꿨는데, defender 가 ★'(반지름과 핵) 사이 거리' 로 읽히는 갈래★
  가 생겼다고 짚었다. 참이 되는 쪽이 아니라 ★문장이 성립하지 않는 쪽★ 이라 F2 는
  아니지만, 갈래는 없는 편이 낫다. '반지름이 핵 사이 거리와 같아진다' 로 어순만
  되돌리면 ★길이가 같은 채로 갈래가 닫힌다★(defender 가 권한 '두 핵 사이 거리'
  는 스물여덟 자가 되어 산포가 0.27 로 벌어진다).
  ▸ ★조사 하나를 바꾸면 묶이는 짝이 바뀐다★ — '반지름과 … 거리가' 는 두 항을
    묶고 '반지름이 … 거리와' 는 앞뒤를 가른다.

기각한 것 하나.
  factchecker: M02175 의 '완만하게 내려가는 ★구간★'(겨냥·본문)과 '완만하게
  내려가는 ★자리★'(선지 ②·압축 줄)가 갈린다 — 확신도 25%로 ★제안자가 스스로
  보류 의견★ 을 냈고, 맞추려면 선지 원문을 건드려야 한다. 본문이 결을 둘로
  가르는 자리라 '구간' 이 값을 하고, 선지는 넷이 모두 '자리' 로 대구를 이룬다.
  ★대구를 깨면서까지 낱말을 맞추지 않는다.★
"""
import re

P = 'build_t14_p5.py'
src = open(P, encoding='utf-8').read()

R = [
    # ── M02180 겨냥·도입 줄 — 통제 비교 계열의 문구가 남아 있었다 ───────────
    ("             '두 원소 사이에서 무엇이 같고 무엇이 달라졌는지 먼저 적기',",
     "             '칼륨과 다른 원소들 사이에서 무엇이 같고 무엇이 달라졌는지 먼저 적기',"),
    ("    T.sol(x, '두 원소 사이에서 무엇이 같고 무엇이 달라졌는지 먼저 적어 봐.',",
     "    T.sol(x, '칼륨과 다른 원소들 사이에서 무엇이 같고 무엇이 달라졌는지 먼저 적어 봐.',"),

    # ── M02184 ④ — 조사를 되돌려 읽는 갈래를 닫는다(길이는 그대로) ─────────
    ("              '끌림이 세지면 반지름과 핵 사이 거리가 같아진다'], 0,",
     "              '끌림이 세지면 반지름이 핵 사이 거리와 같아진다'], 0,"),
    ("              ('끌림이 세지면 반지름과 핵 사이 거리가 같아진다', '반지름을 절반이 아니라 거리 '",
     "              ('끌림이 세지면 반지름이 핵 사이 거리와 같아진다', '반지름을 절반이 아니라 거리 '"),
    ("           '끌림이 세지면 반지름과 핵 사이 거리가 같아진다': '정의에서 절반은 셈 그 자체야. '",
     "           '끌림이 세지면 반지름이 핵 사이 거리와 같아진다': '정의에서 절반은 셈 그 자체야. '"),
]

for a, b in R:
    n = src.count(a)
    assert n == 1, f'{n}곳: {a[:50]!r}'
    src = src.replace(a, b)

open(P, 'w', encoding='utf-8').write(src)


# ── ★기계로 센다★ — 문항 블록을 통째로 잘라 옛 낱말이 0 인지 확인한다 ──────
def block(mid):
    i = src.index(f"    # ── M{mid} ──")
    nxt = [j for j in (src.find('    # ── M02', i + 10), src.find('    return it', i))
           if j != -1]
    b = src[i:min(nxt)]
    return '\n'.join(l for l in b.split('\n') if not l.strip().startswith('#'))


for mid, words in [('02180', ['두 원소 사이에서']),
                   ('02184', ['반지름과 핵 사이 거리', '핵간 거리'])]:
    b = block(mid)
    for w in words:
        assert w not in b, f'M{mid} 에 옛 낱말이 남았다: {w}'

flat80 = re.sub(r"'\s*\n\s*'", '', block('02180'))
assert flat80.count('칼륨과 다른 원소들 사이에서') == 2, flat80.count('칼륨과 다른 원소들 사이에서')
flat84 = re.sub(r"'\s*\n\s*'", '', block('02184'))
assert flat84.count('반지름이 핵 사이 거리와 같아진다') == 3

print('fix_t14_p5_r7 적용 완료 —', len(R), '곳')
