def main():
    bank = json.load(open(BANK, encoding='utf-8'))
    d = {x['id']: x for x in bank}
    n = 0

    for fid, ch in CH_SET.items():
        assert len(ch) == 4, fid
        d[fid]['choices'] = ch
        n += 1
    for fid, st in STEM_SET.items():
        d[fid]['stem'] = st
        n += 1
    for fid, pf in PROOF_SET.items():
        d[fid]['answer_proof'] = pf
        n += 1

    for (fid, opt), (err, typ) in DIST_SET.items():
        hit = [w for w in d[fid]['distractors'] if w['opt'] == opt]
        assert len(hit) == 1, f'{fid} opt{opt}: distractor {len(hit)}개'
        hit[0]['error'], hit[0]['type'] = err, typ
        n += 1

    for fid, sol in SOL_FULL.items():
        d[fid]['solution'] = sol
        n += 1

    for fid, old, new in SOL_REPL:
        s = d[fid]['solution']
        assert old in s, f'{fid}: 대상 문구 없음 -> {old[:45]}'
        d[fid]['solution'] = s.replace(old, new, 1)
        n += 1

    for fid, pat in STALE:
        assert pat not in d[fid]['solution'], f'{fid}: 옛 문구 잔존 -> {pat}'
        assert pat not in d[fid]['stem'], f'{fid}: stem 에 옛 문구 잔존 -> {pat}'

    for fid, w in WATCH.items():
        v = d[fid].setdefault('verified', {})
        prev = v.get('watch', '')
        v['watch'] = (prev + ' / ' + w) if prev else w
        n += 1

    # ── 검증 ────────────────────────────────────────────────
    def rank(ch, a):
        order = sorted(range(4), key=lambda i: (-len(ch[i]), i))
        return order.index(a) + 1

    ranks = {}
    for i in range(1867, 1877):
        fid = f'M0{i}'
        x = d[fid]
        ch, a = x['choices'], x['answer']
        L = [len(c) for c in ch]
        sl = sorted(L)
        sp = 0.0 if sl[1] < 8 else (sl[3] - sl[0]) / ((sl[1] + sl[2]) / 2)
        r = rank(ch, a)
        ranks[r] = ranks.get(r, 0) + 1
        assert sp <= 0.25, f'{fid}: G3b 산포 {sp:.3f}'
        assert not (L[a] == max(L) and L.count(max(L)) == 1), f'{fid}: G3 유일최장'
        assert not (L[a] == min(L) and L.count(min(L)) == 1), f'{fid}: G3 유일최단'
        assert len(x['solution']) >= 300, f'{fid}: 해설 {len(x["solution"])}자'
        for bad in ('**', '★'):
            assert bad not in x['stem'] and bad not in x['solution'], f'{fid}: G10 {bad}'
        # 오답 셋이 모두 해설에 언급되는가 (G9)
        for w in x['distractors']:
            o = ch[w['opt']]
            assert o in x['solution'], f'{fid}: 해설에 {CIR[w["opt"]]} 문면 없음'
        print(f'{fid} {x["track"]} 답{CIR[a]} 길이{L} 순위{r} 산포{sp:.2f} 해설{len(x["solution"])}자')

    print('길이순위', dict(sorted(ranks.items())))
    for r, c in ranks.items():
        assert c <= 4, f'G3c 위반: 순위{r} {c}/10'

    json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'조치 {n}곳 적용 · 규칙 위반 없음')


