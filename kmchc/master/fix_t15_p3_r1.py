# -*- coding: utf-8 -*-
"""T15 P3 1차 조치 — 길이 게이트 열다섯(G3·G3b·G3c)과 M02327 의 부정형 쏠림.

저작 점검은 통과했으나 verify 가 열다섯을 냈다: 열 문항 가운데 ★일곱★ 에서 정답이 유일
최장이었고 그 가운데 여섯은 산포도 0.25 를 넘었다. ★내가 정답을 가장 공들여 쓰기 때문에
생기는 쏠림★ 이고, 저작 점검에는 길이 검사가 없어 걸리지 않았다(P4 에 넣는다).

선지 문면은 choices·distractors·wmap·해설 산문 네 곳에 같은 문자열로 있으므로 한 번에
바꾼다. 정답 문면은 choices 한 곳뿐이다.
"""
import ast, io, sys

SRC = 'build_t15_p3.py'
BEFORE = io.open(SRC, encoding='utf-8').read()
body = BEFORE
log = []


def rep(old, new, expect=None):
    global body
    c = body.count(old)
    assert c > 0, '0곳: %r' % old[:50]
    if expect is not None:
        assert c == expect, '%d곳 (기대 %d): %r' % (c, expect, old[:50])
    body = body.replace(old, new)
    log.append('%d곳 %s' % (c, old[:22]))


# ── M02319 ── 정답 35 가 유일 최장 → ④ 를 늘린다
rep('헬륨은 같은 주기의 수소보다 양성자가 하나 더 많기 때문이다',
    '헬륨은 같은 주기의 수소보다 핵 속 양성자가 하나 더 많기 때문이다')

# ── M02321 ── 정답 45 → 줄이고 ④ 를 늘린다
rep('질소는 2p 세 방에 전자가 하나씩 홀로 들어 반만 채운 안정한 배치이기 때문이다',
    '질소는 2p 세 방에 전자가 하나씩 홀로 들어간 반만 채운 배치이기 때문이다')
rep('질소는 탄소보다 반지름이 커서 전자를 더 세게 붙잡기 때문이다',
    '질소는 탄소보다 원자 반지름이 커서 전자를 더 세게 붙잡고 있기 때문이다')

# ── M02323 ── 정답 40 → 줄이고 ①④ 를 늘린다
rep('2족에서 13족으로 갈 때 값이 작아지는 일이 두 주기에서 모두 일어난다',
    '2족에서 13족으로 갈 때 값이 작아지는 일이 두 주기에 모두 있다')
rep('2주기에서만 값이 작아지고 3주기에서는 경향대로 커진다',
    '2주기에서만 값이 작아지고 3주기에서는 경향대로 값이 커진다')
rep('3주기에서만 값이 작아지므로 주기가 커질수록 예외가 뚜렷해진다',
    '3주기에서만 값이 작아지므로 주기가 커질수록 예외가 뚜렷하게 나타난다')

# ── M02324 ── 정답 47 → 줄이고 ③④ 를 늘린다
rep('앞 자리는 떼는 전자의 오비탈이 바뀌고 뒤 자리는 같은 오비탈에 짝지은 전자가 생긴다',
    '앞 자리는 떼는 오비탈이 바뀌고 뒤 자리는 같은 오비탈에 짝지은 전자가 생긴다')
rep('두 자리 모두 같은 오비탈에 전자가 둘 짝지어 들어가기 때문이다',
    '두 자리 모두 같은 오비탈에 전자가 둘씩 짝지어 들어가기 때문이다')
rep('앞 자리는 짝지은 전자가 생기고 뒤 자리는 오비탈이 s 에서 p 로 바뀐다',
    '앞 자리는 짝지은 전자가 새로 생기고 뒤 자리는 오비탈이 s 에서 p 로 바뀐다')

# ── M02325 ── 정답 34 → 줄이고 ②③ 을 늘린다
rep('셋 — 급증이 두 번이므로 껍질은 두 번에 하나를 더한 셋이다',
    '셋 — 급증이 두 번이므로 그 수에 하나를 더한 셋이다')
rep('둘 — 급증 자리가 둘이므로 껍질도 둘이다',
    '둘 — 급증 자리가 둘이므로 껍질의 수도 그대로 둘이다')
rep('넷 — 적힌 값이 열둘이므로 껍질마다 셋씩 넷이다',
    '넷 — 적힌 값이 열둘이므로 껍질마다 셋씩 잡아 넷이다')

# ── M02327 ── ★정답만 부정형★ + 정답 35 가 유일 최장
#   ④ 를 같은 주장 그대로 부정형으로 적어 '않' 이 정답에만 있는 상태를 깬다.
rep('두 경향의 크기가 늘 같으므로 가와 나의 값은 서로 같다',
    '두 경향의 크기가 언제나 같으므로 가와 나의 값은 서로 다르지 않다')
rep('오른쪽으로 갈수록 커지므로 나가 가보다 크다',
    '같은 주기에서 오른쪽으로 갈수록 커지므로 나가 가보다 크다')
rep('아래로 갈수록 작아지므로 가가 나보다 크다',
    '같은 족에서 아래로 갈수록 작아지므로 가가 나보다 크다')

# ── M02328 ── 정답 41 → 줄이고 ③④ 를 늘린다
rep('적힌 값들의 경향으로 보아 붕소보다 클 것으로 보이나 값은 정해지지 않는다',
    '경향으로 보아 붕소보다 클 것으로 보이나 값은 정해지지 않는다')
rep('표에 없으므로 탄소에 대해서는 아무것도 말할 수 없다',
    '표에 적혀 있지 않으므로 탄소에 대해서는 아무것도 말할 수 없다')
rep('리튬과 플루오린의 사이이므로 520 과 1681 의 한가운데다',
    '리튬과 플루오린의 사이에 있으므로 520 과 1681 의 한가운데다')

try:
    ast.parse(body)
except SyntaxError as e:
    sys.stderr.write('문법 오류 %s — 원본 복구\n' % e)
    io.open(SRC, 'w', encoding='utf-8').write(BEFORE)
    raise

io.open(SRC, 'w', encoding='utf-8').write(body)
print('조치 %d건' % len(log))
for l in log:
    print('  ·', l)
