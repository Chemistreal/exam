"""T12 마감 14제 2차 조치 — 1차 조치가 해설 안에 자기모순 둘을 심어 놓았다

★2차 성적표★ defender ★중·고 심각도 0건★(낮음 1) · solver 지금 고쳐야 1 · 두고 볼 것 1 ·
factchecker ★✗ 2 · △ 2 · 참고 2★. 정답을 흔드는 자리는 없고, ★내가 1차에 만든 흠★ 이 남았다.

■ ★M01958 — 본문과 반박이 정면으로 부딪힌다 (factchecker ✗)★
  1차에 ④ 를 '아무 반지름에서나 돌 수 있다'(보어가 오히려 부정한 것)로 갈아 놓고
  ★본문 첫머리의 "네 선지가 모두 보어의 가정이라는 점부터 붙잡자" 는 그대로 두었다.★
  ④ 반박은 "이건 보어의 가정이 아니야" 라고 적혀 있으니 한 해설 안에서 서로를 부정한다.
  게다가 거기서 끌어낸 "참·거짓을 따져서는 갈리지 않는다" 도 ★헛도는 근거★ 가 된다 —
  ④ 는 참·거짓만으로 곧바로 탈락하기 때문이다.
  ◆규칙: 선지를 갈면 ★본문이 그 선지 집합을 두고 한 일반화★ 도 함께 볼 것.
    '네 선지가 모두 ~이다' 같은 문장은 선지 하나만 바뀌어도 거짓이 된다.◆
  ▸ factchecker 가 ★"앞 회차에 ○ 로 넘어간 것은 달라져서가 아니라 놓쳐서이므로 근거를 밝혀
    뒤집는다" 고 스스로 적었다.★ 규율이 지켜진 뒤집기라 받아들인다.

■ ★M01957 — 반박끼리 어긋난다 (factchecker ✗)★
  ① 반박은 "질량이 몰려 있다는 것은 ★되튐★ 쪽이 말해 주지" 라 해 놓고,
  ③ 반박은 "★크게 휘었다★ 는 것은 질량과 전하가 한곳에 몰려 있다는 뜻" 이라 적었다.
  본문도 되튐을 무거운 상대의 증거로, 휘어짐을 (+)전하 집중의 증거로 갈라 두었으니
  ★③ 반박만 궤도를 벗어났다.★ 정답 ④ 의 근거도 전하 집중이다.
  ▸ 아울러 본문의 "★이 셋 가운데 어느 하나가 아니라★ 그런 일이 드물었는가에서 나와" 는
    자가진단('드묾 = 작다')과 어긋나고 교과 서술('대부분 통과 → 핵은 매우 작다')과도 부딪힌다.
    드묾은 셋 바깥의 별개 정보가 아니라 ★세 결과에 이미 담긴 양적 측면★ 이다.

■ ★M01960 — 정의만 하고 쓰이지 않는 기호 k (defender·solver 둘 다)★
  발문이 '이온화 에너지를 k 라 할 때' 로 k 를 들이는데 물음도 선지도 k 를 쓰지 않는다 —
  답이 무차원 배수이기 때문이다. ★1차에 발문을 손보며 남은 잔여물★ 이다.
  ▸ solver 가 하나 더 짚었다 — 표는 (n, m) 과 (m, n) 칸이 다 차 있으므로 ★값에 부호가 붙는다고
    읽으면 가장 작은 것이 −k 가 되어 답이 없어진다.★ '값의 크기' 로 못 박는다.
  ▸ defender 의 '활용안'(가장 큰 것이 k 와 같다고 발문에 적기)은 ★반려★ 한다 —
    최댓값을 발문이 건네주면 이 문항이 요구하는 두 걸음 가운데 한 걸음이 사라진다.
    ★삭제안★ 을 택한다. 해설 쪽에서 k 를 도입해 쓰면 된다.

■ ★M01967 ① 반박 — 1차 수정이 절반만 닫혔다 (factchecker △)★
  본문의 '91.1 × 4 = 364.6' 은 반올림 때문임을 밝혔는데 ★① 반박에는 옛 문장이 그대로 남았다.★
  91.1 × 4 = 364.4 다. 반박은 따로 읽히는 자리라 같은 오독을 다시 심는다.
  ▸ 같은 문단의 '91.1 × 9 = 820' 도 실제 819.9 이므로 근사 기호를 붙인다(참고).

■ ★M01959 — 좌·우 반복 요소의 교집합이 곧 정답 (solver 두고 볼 것)★
  좌변 '질량이 같다' 가 ②④ 에, 우변 '동위원소의 발견' 이 ①④ 에 되풀이되어
  ★화학 없이 교집합만 짚어도 ④ 가 나온다.★ ① 의 우변을 '원자량 측정법의 확립' 으로 바꾸면
  네 우변이 모두 달라져 교차가 사라진다.
  ▸ ★solver 가 붙인 경고를 지킨다★ — ① 의 우변을 '전자의 발견'이나 '원자핵의 발견' 으로
    바꾸면 ★참이 되어 복수정답★ 이다. 그 둘은 쓰지 않는다.
  ▸ sim 이 1차에 낸 안(③ 의 우변도 동위원소로)은 ★교집합을 없애지 못해★ 이미 반려했다.

■ ★반려 — 근거와 함께★
  ▸ solver 'M01957 ③④ 가 좌변을 공유해 정답 자리가 좁혀진다'(참고) — 관찰이 셋뿐이라
    ★네 선지 가운데 하나는 반드시 좌변을 나눠 가진다.★ 자리를 옮겨도 쏠림이 이동할 뿐이다.
    solver 스스로 '급하지 않다' 고 적었다.
  ▸ solver 'M01967 이 ①②④ 스펙트럼 영역 대 ③ 에너지로 3 : 1'(참고) — ★1차에 극단어 3 : 1 을
    고쳤더니 축이 옮겨 왔다.★ 이 각도(상수 하나의 정체)는 정답이 '이 값이 무엇인가' 를 말하고
    오답은 모두 '어느 자리인가' 를 말할 수밖에 없다. P15 의 C12-028 에서 겪은 것과 같은
    ★각도에 붙박인 3 : 1★ 로 보고 기록한다.
  ▸ solver 'M01964 요소 다수결 · M01968 최대 메아리'(참고) — 둘 다 solver 가 '지금 손댈 필요
    없다' 고 적었고, 내용상 정답이 확실하며 오답 유도값도 살아 있다.
"""
import json
import os

BANK = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'master_bank.json')


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:40]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


def stem(it, old, new):
    assert it['stem'].count(old) == 1, it['id']
    it['stem'] = it['stem'].replace(old, new)


def swap_text(it, idx, old, new):
    assert it['choices'][idx] == old, (it['id'], it['choices'][idx])
    it['choices'][idx] = new
    mark = '①②③④'[idx]
    if idx != it['answer']:
        assert it['solution'].count(f'{mark} {old}: ') == 1, it['id']
        it['solution'] = it['solution'].replace(f'{mark} {old}: ', f'{mark} {new}: ')
    else:
        assert it['solution'].count(f'[정답] {mark} {old} — ') == 1, it['id']
        it['solution'] = it['solution'].replace(f'[정답] {mark} {old} — ', f'[정답] {mark} {new} — ')


def main():
    bank = json.load(open(BANK, encoding='utf-8'))
    d = {x['id']: x for x in bank}

    # ══ M01957 ─ ③ 반박을 전하 쪽으로 · 본문의 '셋 가운데' 손질 ═══════════════
    it = d['M01957']
    sub(it, '앞짝은 맞는 관찰이지만 뒷짝이 거꾸로야. 크게 휘었다는 것은 질량과 전하가 한곳에 '
            '몰려 있다는 뜻이지 고르게 퍼져 있다는 뜻이 아니거든.',
        '앞짝은 맞는 관찰이지만 뒷짝이 거꾸로야. 크게 휘었다는 것이 곧바로 말해 주는 것은 '
        '(+)전하가 좁은 곳에 몰려 있다는 것이고, 질량이 고르게 퍼져 있지 않다는 것은 되튐이 '
        '반박하지 — 가벼운 것에 부딪혔다면 되튀지 못하거든.')
    sub(it, '하나 더 붙여 두자. 원자핵이 아주 작다는 결론은 이 셋 가운데 어느 하나가 아니라 '
            '그런 일이 몇 번에 한 번꼴로 드물었는가에서 나와.',
        '하나 더 붙여 두자. 원자핵이 아주 작다는 결론은 셋 가운데 어느 하나를 말로만 읽어서가 '
        '아니라, 크게 휘거나 되튄 일이 몇 번에 한 번꼴로 드물었는지를 양으로 따져야 나와.')

    # ══ M01958 ─ 본문의 '네 선지가 모두 보어의 가정' 을 바로잡음 ═══════════════
    sub(d['M01958'],
        '네 선지가 모두 보어의 가정이라는 점부터 붙잡자. 그러니 참·거짓을 따져서는 갈리지 '
        '않고, 그 가운데 어느 것이 러더퍼드에게 이미 있던 그림인지를 물어야 해.',
        '선지 가운데 ①②③ 은 모두 보어의 가정이야. 이 셋은 참·거짓으로는 갈리지 않으니 그 '
        '가운데 어느 것이 러더퍼드에게 이미 있던 그림인지를 물어야 하지. ④ 는 보어가 오히려 '
        '부정한 것이라 가정 목록에서부터 빠져.')

    # ══ M01959 ─ ① 의 우변을 바꿔 좌·우 교집합을 없앰 ═══════════════════════
    it = d['M01959']
    swap_text(it, 0, '원자는 더 쪼갤 수 없다 — 동위원소의 발견',
              '원자는 더 쪼갤 수 없다 — 원자량 측정법의 확립')
    sub(it, '왼쪽은 손질된 가정이 맞지만 그것을 뒤집은 것은 전자와 같은 구성 입자의 발견이야.',
        '왼쪽은 손질된 가정이 맞아. 그런데 원자량을 재는 법이 자리를 잡았다고 원자를 쪼갤 수 '
        '있게 된 것은 아니지 — 이 가정을 뒤집은 것은 전자와 같은 구성 입자의 발견이야.')
    for dd in it['distractors']:
        if dd['opt'] == 0:
            dd['error'] = '가정은 맞게 짚었으나 그것을 뒤집지 못한 발견을 붙임'

    # ══ M01960 ─ 유휴 기호 k 삭제 + '값의 크기' 로 부호 시비 차단 ═══════════════
    it = d['M01960']
    stem(it, '수소 원자의 이온화 에너지를 k 라 할 때, 표에 실린 값 가운데 가장 큰 것과 '
             '가장 작은 것의 비에 가장 가까운 것은?',
         '표에 실린 값의 크기 가운데 가장 큰 것과 가장 작은 것의 비에 가장 가까운 것은?')
    sub(it, '전이 에너지가 어떻게 생겼는지부터 적어 보자. 두 준위 m 과 n 사이의 값은 '
            'k(1/m² − 1/n²) 이야.',
        '전이 에너지가 어떻게 생겼는지부터 적어 보자. 수소의 이온화 에너지를 k 라 하면 두 '
        '준위 m 과 n 사이의 값은 k(1/m² − 1/n²) 이야.')

    # ══ M01967 ─ ① 반박에 남은 364.6 · 820 근사 표기 ═══════════════════════
    it = d['M01967']
    sub(it, '발머 계열이 모여드는 끝은 91.1 에 4 를 곱한 자리, 곧 364.6 nm 야.',
        '발머 계열이 모여드는 끝은 91.1 에 4 를 곱한 자리, 곧 364 nm 언저리야'
        '(정확한 값은 364.6 nm).')
    sub(it, '파셴 한계는 괄호가 1/9 이라 91.1 × 9 = 820 nm 이고.',
        '파셴 한계는 괄호가 1/9 이라 91.1 × 9, 곧 820 nm 언저리이고.')

    # ══ M01968 ─ 띄어쓰기 ═══════════════════════════════════════════════════
    sub(d['M01968'], '에너지가 작아질 수록 파장은 길어지지', '에너지가 작아질수록 파장은 길어지지')

    for x in bank:
        assert '**' not in x['stem'] and '**' not in x['solution'], x['id']
        assert '★' not in x['stem'] and '★' not in x['solution'], x['id']

    json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    from collections import Counter
    print('T12 마감 14제 2차 조치 완료 — 발문 1 · 선지 1 · 해설 7')
    ranks = []
    for i in range(1957, 1971):
        x = d[f'M0{i}']
        L = [len(c) for c in x['choices']]
        s = sorted(L)
        sp = (s[3] - s[0]) / ((s[1] + s[2]) / 2)
        rk = sorted(range(4), key=lambda j: -L[j]).index(x['answer']) + 1
        ranks.append(rk)
        flag = '' if (sp <= 0.25 or s[1] < 8) else '  ← G3b'
        if L[x['answer']] == s[3] and L.count(s[3]) == 1:
            flag += '  ← G3 최장'
        if L[x['answer']] == s[0] and L.count(s[0]) == 1:
            flag += '  ← G3 최단'
        print(f'  {x["id"]} {L} 산포{sp:.2f} 순위{rk}{flag}')
    print('  길이순위', dict(sorted(Counter(ranks).items())))


if __name__ == '__main__':
    main()
