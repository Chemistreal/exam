# ── 저작 점검 ── 게이트가 보지 않는 이 배치만의 검사 ────────────────────────
def local_checks(items):
    import re
    from collections import Counter
    bad = []

    # ① 관계식 3갈래 — 수치 선지 자리에서 '이상치가 정답' 도 '정답만 만족' 도 아닐 것
    REL = [('2의 거듭제곱', lambda v: v > 0 and (v & (v - 1)) == 0),
           ('4의 배수', lambda v: v % 4 == 0),
           ('홀수', lambda v: v % 2 == 1)]
    for x in items:
        vals = []
        for c in x['choices']:
            m = re.match(r'^(\d+)\s*(개|번째)$', c.strip())
            if not m:
                vals = None
                break
            vals.append(int(m.group(1)))
        if not vals:
            continue
        av = vals[x['answer']]
        for name, f in REL:
            ok = [v for v in vals if f(v)]
            if len(ok) == 3 and av not in ok:
                bad.append(f"{x['id']} 관계식 '{name}' — 이상치가 정답({av})")
            if len(ok) == 1 and av in ok:
                bad.append(f"{x['id']} 관계식 '{name}' — 정답({av})만 만족")

    # ② 오답 유형이 한 문항 안에서 겹치지 않을 것
    for x in items:
        ts = [w['type'] for w in x['distractors']]
        if len(set(ts)) < len(ts):
            bad.append(f"{x['id']} 오답 유형 중복 — {ts}")

    # ③ 발문에 정답 문자열이 통째로 들어가 있지 않을 것
    for x in items:
        a = x['choices'][x['answer']]
        core = re.sub(r'[^0-9A-Za-z가-힣]', '', a)
        stem = re.sub(r'[^0-9A-Za-z가-힣]', '', x['stem'])
        if len(core) >= 6 and core in stem:
            bad.append(f"{x['id']} 발문에 정답이 통째로 들어 있음")

    # ④ ★오답끼리의 포함 관계★(P10 ㉯) — 한 선지가 다른 선지를 통째로 품으면 동반 탈락
    for x in items:
        cs = [re.sub(r'\s+', '', c) for c in x['choices']]
        for i in range(4):
            for j in range(4):
                if i != j and len(cs[i]) >= 12 and cs[i] in cs[j]:
                    bad.append(f"{x['id']} 선지 포함 관계 — {i+1} 이 {j+1} 안에 들어 있음")

    # ⑤ ★선지에 적힌 수의 합 관계★(P10 ㉱) — 정답이 다른 두 선지의 합으로만 유일하게 얻어지면 신호
    for x in items:
        nums = []
        for c in x['choices']:
            f = re.findall(r'\d+', c)
            nums.append(int(f[-1]) if f else None)
        if any(n is None for n in nums) or len(set(nums)) < 4:
            continue
        av = nums[x['answer']]
        pairs = [(i, j) for i in range(4) for j in range(i + 1, 4)
                 if i != x['answer'] and j != x['answer'] and nums[i] + nums[j] == av]
        if len(pairs) == 1:
            i, j = pairs[0]
            bad.append(f"{x['id']} 합 관계 — 정답 {av} = {nums[i]} + {nums[j]} (유일)")

    # ⑥ 지시 대상표 — 이 배치가 쓰는 수치가 서로 어긋나지 않을 것
    REFERENT = {
        'n=3 껍질의 오비탈 수': 9, 'n=3 껍질의 정원': 18,
        'n=2 껍질의 오비탈 수': 4, 'n=2 껍질의 정원': 8,
        '2p 부껍질의 오비탈 수': 3, '3d 부껍질의 오비탈 수': 5,
        '[Ne] 의 전자 수': 10, '[Ar] 의 전자 수': 18,
        '염소의 원자 번호': 17, '칼륨의 원자 번호': 19, '칼슘의 원자 번호': 20,
        '4s 의 채움 순번': 6, '3d 의 채움 순번': 7,
    }
    for k, v in REFERENT.items():
        if v <= 0:
            bad.append(f'지시 대상표 오류 — {k}')

    # ⑦ 정답 길이 순위가 한쪽으로 쏠리지 않을 것 (G3c 예고)
    ranks = []
    for x in items:
        L = [len(c) for c in x['choices']]
        ranks.append(sorted(range(4), key=lambda i: -L[i]).index(x['answer']) + 1)
    cnt = Counter(ranks)
    lim = max(4, int(len(items) * 0.4))
    for r, n in cnt.items():
        if n > lim:
            bad.append(f'정답 길이순위 {r} 이 {n} 회 — 한도 {lim}')
    print('  정답 길이순위:', dict(sorted(cnt.items())))

    if bad:
        print('\n❌ 저작 점검 실패')
        for b in bad:
            print('  -', b)
        raise SystemExit(1)
    print('  ✅ 저작 점검 통과 (관계식·오답 유형·누설·포함 관계·합 관계·지시 대상표·길이순위)')


