"""T15 P5 1차 조치 셋째 손질 — ★조치가 이번엔 극성 검사를 울렸다★

  r1b 로 길이를 맞추자 verify 가 다른 자리를 잡았다:
    · M02344 정답만 부정형('두 배에 못 미친다')
    · M02346 정답만 부정형('정할 수 없다')
  ▸ ★한 조치가 세 검사를 차례로 울렸다★ — 내용(게이팅) → 길이 → 극성. 셋은 같은 문면을
    서로 다른 축에서 재므로, ★선지를 갈 때는 뜻·길이·어미·극성을 한 묶음으로 함께 잡아야
    한다★(P9 가 얻은 '길이·어미·발문 겹침은 한 묶음' 에 ★극성★ 이 하나 더 붙는다).
  ▸ M02346 은 원래 '정할 수 없다' 가 이 문항의 논지였다. ★부정을 지우는 것이 아니라 같은 뜻을
    조건문으로 옮긴다★ — '주기를 알아야 비로소 … 정할 수 있다'. 뜻은 그대로고 극성만 뒤집힌다.
"""
import io

P = 'build_t15_p5.py'
src = io.open(P, encoding='utf-8').read()


def rep(old, new, n=1):
    global src
    c = src.count(old)
    if c != n:
        raise SystemExit('앵커 %d곳(기대 %d): %r' % (c, n, old[:70]))
    src = src.replace(old, new)


# ── M02344 ★정답★ ② — 부정을 범위 표현으로(33자 그대로) ───────────────
rep("              '다섯 값은 차례로 커지되 이웃한 비가 모두 두 배에 못 미친다',",
    "              '다섯 값은 차례로 커지되 이웃한 비가 모두 두 배 안쪽에 든다',")
rep("             '모두 두 배에 못 미치는 데 견주어 다섯째에서 여섯째로 가는 비는 3.4 이므로, 앞의 '",
    "             '모두 두 배 안쪽에 드는 데 견주어 다섯째에서 여섯째로 가는 비는 3.4 이므로, 앞의 '")
rep("          '마지막만 유독 크지. 그러니 앞의 다섯 값은 차례로 커지기는 해도 이웃한 비가 모두 '\n"
    "          '두 배에 못 미쳐 — ②가 옳아. '",
    "          '마지막만 유독 크지. 그러니 앞의 다섯 값은 차례로 커지기는 해도 이웃한 비가 모두 '\n"
    "          '두 배 안쪽에 들어 — ②가 옳아. '")

# ── M02346 ★정답★ ④ — 같은 뜻을 조건문으로 옮긴다(27자 그대로) ────────
rep("              '같은 주기인지 모르는 채로는 대소를 정할 수 없다'], 3,",
    "              '주기를 알아야 비로소 두 값의 대소를 정할 수 있다'], 3,")

io.open(P, 'w', encoding='utf-8').write(src)
print('✅ fix_t15_p5_r1c — 극성 둘(M02344 ② · M02346 ④)')
