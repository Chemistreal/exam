def apply_edits(bank):
    idx = {x['id']: x for x in bank}
    miss = []
    for fid, kind, old, new in EDITS:
        it = idx[fid]
        if kind == "choice":
            if old in it['choices']:
                it['choices'][it['choices'].index(old)] = new
            else:
                miss.append((fid, kind, old[:28]))
            # 오답 메타·해설의 라벨도 함께
            for d in it['distractors']:
                pass
            it['solution'] = it['solution'].replace(old, new)
            it['answer_proof'] = it['answer_proof'].replace(old, new)
        else:
            hit = False
            for f in ('solution', 'answer_proof', 'device', 'calc_check'):
                if old in it.get(f, ''):
                    it[f] = it[f].replace(old, new); hit = True
            for d in it['distractors']:
                if old in d.get('error', ''):
                    d['error'] = d['error'].replace(old, new); hit = True
            if not hit:
                miss.append((fid, kind, old[:28]))
    return bank, miss


