def main():
    cj = json.load(open(CJ, encoding='utf-8'))
    concepts = {c['id']: c for c in cj[THEME]}
    linked = 0
    for cid, idx, mid in LINK:
        a = concepts[cid]['angles'][idx]
        a.setdefault('by', [])
        if mid not in a['by']:
            a['by'].append(mid)
            linked += 1
    noted = 0
    for cid, note in NOTES.items():
        c = concepts[cid]
        if note not in c['note']:
            c['note'] = c['note'].rstrip() + ' ' + note
            noted += 1
    json.dump(cj, open(CJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    tot = sum(len(c['angles']) for c in cj[THEME])
    used = sum(1 for c in cj[THEME] for a in c['angles'] if a.get('by'))
    nc = sum(len(v) for v in NOTES.values())
    print(f'T15 P3 링크 — 각도 {linked} · 개념 주의 {noted}건 {nc:,}자')
    print(f'  각도 {tot} · 소진 {used} · 미소진 {tot - used}')
    done = [c['id'] for c in cj[THEME] if all(a.get('by') for a in c['angles'])]
    print(f'  소진 완료 개념 {len(done)}')


if __name__ == '__main__':
    main()
