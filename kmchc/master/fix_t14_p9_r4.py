# -*- coding: utf-8 -*-
"""T14 P9 4차 조치 — 한 문항 안의 두 단평이 같은 쌍을 반대로 부르지 않게 한다.

4차 보고. factchecker ★✗ 0 · △ 1★(1차 ✗4△12 → 2차 ✗0△5 → 3차 ✗1△3 → 4차 ✗0△1).
다른 셋은 이미 0 이다 — solver ★차단 0, 세 회차 연속 열 문항 정답 전부 일치★ ·
defender ★[상] 0 · [중] 0, 열 문항 모두 동결 권고★ · student-sim ★D 오답 0, 마감 가능★.

이번 조치도 ★선지 문면을 하나도 건드리지 않는다★ — M02220 의 해설과 단평 한 자리뿐이다.
그래서 solver·defender·sim 의 입력은 바뀌지 않고, 5차는 factchecker 만 돌린다.

★① 한 문항 안의 두 단평이 같은 쌍을 반대로 부르지 않게 한다.★ (factchecker △)
  3차에 M02220 ② 의 예시를 '질소와 황' 으로 옮기면서 뒤 절은 '가로로 ★멀리★ 건너뛴
  쌍에서는' 으로 두었다. 그런데 껍질 쪽이 지기 시작하는 최소 간격은 ★두 칸★ 이고
  (리튬–알루미늄), ★그 쌍이 바로 같은 문항 ③ 이 반례로 든 쌍★ 이다. 지금 문면은
  '한 칸은 안전 / 멀리는 위험' 으로 읽혀 ★두 칸을 안전지대로 넘겨준다.★ 학생이 ②의
  단평과 ③의 단평을 맞물릴 수 없다.
  ▸ '두 칸만 벌어져도' 로 적어 두 단평이 ★같은 쌍을 같은 이름으로 부르게★ 한다.
  ▸ 함께: '오른쪽으로 한 칸만 건너뛴' 은 세로 이동을 적지 않아 ★같은 주기의 이웃 칸★
    (엇갈릴 수 없는 쌍)으로 오독될 여지가 있다. '한 주기 내려가면서 오른쪽으로 한 칸만
    간' 으로 두 방향을 함께 적는다.

★② 검증자가 준 문면도 다시 센다.★
  factchecker 가 해설 쪽에는 '두 칸 ★넘게★ 벌어진 쌍' 을, 단평 쪽에는 '두 칸★만★
  벌어져도' 를 냈다. 둘이 어긋난다 — 리튬–알루미늄은 ★정확히 두 칸★ 이므로 '넘게' 로
  적으면 그 쌍이 다시 범위 밖으로 나간다(그가 든 반례가 그 자신의 문면에 걸린다).
  ▸ 양쪽 다 '두 칸만 벌어져도' 로 적는다. ★P7 에서 얻은 '대체안은 문면만이 아니라 그
    문항의 판까지 보고 고른다' 가 여기서는 '검증자가 준 두 문면이 서로 맞는지 센다' 로
    나타났다.★
  ▸ 그의 검산 자체는 값으로 확인된다 — 오른쪽 한 칸 쌍은 예외 없이 껍질 쪽이 이기고
    (Li<Mg · Be<Al · B<Si · C<P · N<S · O<Cl · Na<Ca), 두 칸은 갈린다
    (Be 112 < Si 117 은 이기고 Li 152 > Al 143 은 진다). ★'기도 해' 라는 헤지가
    두 칸의 갈림을 정확히 담는다.★
"""
import re

P = 'build_t14_p9.py'
src = open(P, encoding='utf-8').read()

CHOICES_RE = re.compile(r"\['(.+?)'\], (\d)", re.S)
BEFORE = CHOICES_RE.findall(src)
assert len(BEFORE) == 10
CH_BEFORE = [re.findall(r"'([^']+)'", f"'{b}'") for b, _ in BEFORE]
ANS_BEFORE = [a for _, a in BEFORE]


def sub(old, new, n=1):
    global src
    c = src.count(old)
    assert c == n, f'{c}곳(기대 {n}): {old[:56]!r}'
    src = src.replace(old, new)


# ══ M02220 ② ── 두 칸을 안전지대로 넘겨주지 않는다 ═════════════════════════
sub("          '②는 좁은 구간의 보증을 규칙으로 넓혔어. 껍질 쪽이 이기는 것이 확실한 자리는 '\n"
    "          '질소와 황처럼 오른쪽으로 한 칸만 건너뛴 쌍이고, 가로로 멀리 건너뛴 쌍에서는 '\n"
    "          '껍질이 더 많은 쪽이 오히려 작기도 해. '",
    "          '②는 좁은 구간의 보증을 규칙으로 넓혔어. 껍질 쪽이 이기는 것이 확실한 자리는 '\n"
    "          '질소와 황처럼 한 주기 내려가면서 오른쪽으로 한 칸만 간 쌍이고, 리튬과 '\n"
    "          '알루미늄처럼 두 칸만 벌어져도 껍질이 더 많은 쪽이 오히려 작기도 해. '")
sub("': '멀리 건너뛴 쌍에서는 오히려 '", "': '두 칸만 벌어져도 오히려 '")

open(P, 'w', encoding='utf-8').write(src)


# ── ★기계로 센다★ ─────────────────────────────────────────────────────────────
body = '\n'.join(l for l in src.split('\n') if not l.strip().startswith('#'))
body = body[body.index('def build('):]
flat = re.sub(r"'\s*\n\s*'", '', body)

assert '멀리 건너뛴' not in flat, '옛 낱말이 남았다'
assert '두 칸 넘게' not in flat, '검증자 문면의 어긋난 쪽을 그대로 썼다'
assert not re.search(r'[가-힣]★\s(를|을|은|의|으로|로|에서|에|과|보다|처럼|까지|부터'
                     r'|이고|이다|이야|이라|이지|인|야|다)(?=[\s,.·)?!\'"])', flat), \
    '★ 뒤에서 조사를 뗐다'
assert not re.search(r'[가-힣]\s(를|을|로)(?=[\s,.·)?!])', flat), '조사를 앞말에서 뗐다'
assert not re.search(r'\d+\s*pm', flat), '이 배치는 pm 값을 싣지 않는다'

AFTER = CHOICES_RE.findall(src)
assert len(AFTER) == 10
assert [a for _, a in AFTER] == ANS_BEFORE, '정답 자리가 바뀌었다'
CH = [re.findall(r"'([^']+)'", f"'{blk}'") for blk, _ in AFTER]
assert CH == CH_BEFORE, '선지 문면이 바뀌었다 — 이번 조치는 해설의 자리다'

# ★두 단평이 같은 쌍을 같은 이름으로 부르는가★ — M02220 ②③
s20 = flat[flat.index("T.mk('M02220'"):flat.index("T.mk('M02221'")]
assert s20.count('리튬과 알루미늄') == 3, 'M02220 의 ②③ 이 같은 쌍을 맞물지 않는다'
assert s20.count('두 칸만 벌어져도') == 2, '두 칸을 안전지대로 남겨 두었다'
assert '한 주기 내려가면서 오른쪽으로 한 칸만 간' in s20, '세로 이동을 적지 않았다'

print('fix_t14_p9_r4 적용 완료 — 선지 문면 불변, M02220 해설과 단평 한 자리')
