CIR = '①②③④'


def spread(ch):
    L = sorted(len(str(x)) for x in ch)
    return (L[3] - L[0]) / ((L[1] + L[2]) / 2) if L[1] + L[2] else 0.0


def main():
    bank = json.load(open(BANK, encoding='utf-8'))
    items = bank if isinstance(bank, list) else bank['items']
    idx = {x['id']: x for x in items}
    n = 0
    for fid, st in STEM_SET.items():
        assert idx[fid]['stem'] != st
        idx[fid]['stem'] = st; n += 1
    for fid, ch in CH_SET.items():
        assert len(ch) == 4
        idx[fid]['choices'] = ch; n += 1
    for (fid, opt), err in DIST_SET.items():
        for d in idx[fid]['distractors']:
            if d['opt'] == opt:
                d['error'] = err; n += 1
    for fid, (lead, cor, wmap, diag) in SOL.items():
        c, a = idx[fid]['choices'], idx[fid]['answer']
        idx[fid]['solution'] = (f"{lead}\n\n[정답] {CIR[a]} {c[a]} — {cor}\n\n"
                                + "\n".join(f"{CIR[i]} {c[i]}: {wmap[c[i]]}" for i in range(4) if i != a)
                                + f"\n\n자가진단: {diag}"); n += 1
    for fid, old, new in SOL_REPL:
        s = idx[fid]['solution']; assert old in s, fid
        idx[fid]['solution'] = s.replace(old, new); n += 1
    for fid, add in WATCH_ADD.items():
        v = idx[fid].setdefault('verified', {})
        v['watch'] = (v.get('watch', '') + ' / ' + add).strip(' /'); n += 1

    print(f"조치 {n}곳\n")
    bad, ranks = [], {}
    for i in range(1857, 1867):
        fid = f'M0{i}'; it = idx[fid]
        L = [len(str(x)) for x in it['choices']]
        r = sorted(range(4), key=lambda k: (-L[k], k)).index(it['answer']) + 1
        sp = spread(it['choices']); sol = it['solution']
        ranks[r] = ranks.get(r, 0) + 1
        print(f"{fid} {it['track']} 답{CIR[it['answer']]} 길이{L} 순위{r} 산포{sp:.2f} 해설{len(sol)}자")
        if sp > 0.25 and sorted(L)[1] >= 8: print(f"  ⛔ G3b {sp:.2f}"); bad.append('G3b')
        if L[it['answer']] == max(L) and L.count(max(L)) == 1: print("  ⛔ G3 최장"); bad.append('G3')
        if L[it['answer']] == min(L) and L.count(min(L)) == 1: print("  ⛔ G3 최단"); bad.append('G3')
        if len(sol) < 300: print("  ⛔ G9"); bad.append('G9')
        if '**' in sol or '★' in sol: print("  ⛔ G10"); bad.append('G10')
        for d in it['distractors']:
            if CIR[d['opt']] not in sol: print(f"  ⛔ G9 오답 {CIR[d['opt']]} 미언급"); bad.append('G9')
    pos = {}
    for i in range(1857, 1867):
        a = idx[f'M0{i}']['answer']; pos[a] = pos.get(a, 0) + 1
    print("\n위치 " + ' '.join(f"{CIR[k]}{pos.get(k,0)}" for k in range(4)) + f" · 길이순위 {dict(sorted(ranks.items()))}")
    for r, c in ranks.items():
        if c > 4: print(f"  ⛔ G3c 순위 {r} 가 {c}/10"); bad.append('G3c')
    if bad: print("\n⛔ " + ', '.join(sorted(set(bad)))); sys.exit(1)
    print("✅ 규칙 위반 없음")
    if '--apply' in sys.argv:
        json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print("✅ 반영 완료")
    else:
        print("※ 검증만. 반영하려면 --apply")


if __name__ == '__main__':
    main()
