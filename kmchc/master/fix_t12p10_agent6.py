import json, os

BANK = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'master_bank.json')

M1903_STEM = ('보어는 "허용된 궤도를 도는 동안에는 전자기파를 내놓지 않는다"는 가정을 세워 원자가 '
              '무너지지 않게 했다. 그런데 이 가정 하나만으로는 수소가 이어진 띠가 아니라 끊어진 '
              '선으로만 빛을 낸다는 것이 설명되지 않는다. 빛이 왜 이렇게 끊어져 나오는지를 '
              '설명해 주는 가정으로 옳은 것은?')

REPL = {'M01903': {'stem': M1903_STEM}}

SUB = [
    ('M01902', 'solution',
     '무너지는 쪽에서도 빛은 나오니까, 빛이 나온다는 사실만으로는 두 쪽이 갈리지 않지.',
     '무너지든 그대로 있든 빛은 나올 수 있으니까, 빛이 나온다는 사실만으로는 두 쪽이 '
     '갈리지 않지.'),
    ('M01900', 'solution',
     '그 예측대로라면 알파 입자는 모두 진행 방향 쪽으로 나올 테니',
     '그 예측대로라면 알파 입자는 거의 다 진행 방향 쪽으로 나올 테니'),
    ('M01900', 'answer_proof',
     '그 예측대로라면 알파 입자는 모두 진행 방향 쪽으로 나오니',
     '그 예측대로라면 알파 입자는 거의 다 진행 방향 쪽으로 나오니'),
]

STALE = [
    ('M01903', 'stem', '떨어진 선'),
    ('M01902', 'solution', '무너지는 쪽에서도'),
    ('M01900', 'solution', '알파 입자는 모두'),
    ('M01900', 'answer_proof', '알파 입자는 모두'),
]


def main():
    d = json.load(open(BANK, encoding='utf-8'))
    items = d if isinstance(d, list) else d['items']
    x = {it['id']: it for it in items}
    n = 0

    for fid, r in REPL.items():
        it = x[fid]
        for key, val in r.items():
            assert it[key] != val, f'{fid}: {key} 가 이미 같음'
            it[key] = val
            n += 1

    for fid, key, old, new in SUB:
        it = x[fid]
        assert old in it[key], f'{fid}.{key}: 대상 조각 없음 -> {old[:40]}'
        assert it[key].count(old) == 1, f'{fid}.{key}: 조각이 둘 이상'
        it[key] = it[key].replace(old, new)
        n += 1

    for fid, key, frag in STALE:
        assert frag not in x[fid][key], f'{fid}.{key}: 옛 문면 잔존 -> {frag}'

    # ── 자체 점검 ──────────────────────────────────────────────
    it = x['M01903']
    stem, ans = it['stem'], it['choices'][it['answer']]
    assert '끊어진 선으로만' in stem, 'M01903: 최소 문면 아님'
    assert '몇' not in stem, 'M01903: 개수 표현 잔존'
    # 발문과 정답 선지가 두 글자 이상 이어지는 낱말을 공유하지 않는가
    shared = [w for w in ('띄엄띄엄', '떨어진', '정해져', '에너지') if w in stem and w in ans]
    assert not shared, f'M01903: 발문-정답 낱말 겹침 {shared}'
    # M01902: 두 방출 기제를 한 낱말로 묶지 않는가
    assert x['M01902']['solution'].count('러더퍼드 모형도 빛이 나온다') == 1

    for fid in ('M01900', 'M01902', 'M01903'):
        s = x[fid]['solution']
        assert len(s) >= 300, f'{fid}: 해설 {len(s)}자'
        for mk in ('①', '②', '③', '④'):
            assert mk in s, f'{fid}: {mk} 줄 없음'
        assert '**' not in s and '★' not in s, f'{fid}: 금지 기호'

    json.dump(d, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

    print(f'P10 6차 조치 {n}곳 · 채택 3 · 반려 4 (solver 0건)')
    for fid in ('M01900', 'M01902', 'M01903'):
        it = x[fid]
        L = [len(c) for c in it['choices']]
        s = sorted(L)
        sp = (s[3] - s[0]) / ((s[1] + s[2]) / 2)
        rk = sorted(range(4), key=lambda i: -L[i]).index(it['answer']) + 1
        print(f"  {fid} 정답{'①②③④'[it['answer']]} 길이{L} 산포{sp:.2f} "
              f"길이순위{rk} 해설{len(it['solution'])}자")


if __name__ == '__main__':
    main()
