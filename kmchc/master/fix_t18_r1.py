    sub(x, 'prose', '안쪽 껍질 전자는 점으로 옮기지 않으니 점의 수가 더 적어.',
        '안쪽 껍질에 전자가 있는 원자에서는 점의 수가 더 적어. 산소는 전자 여덟인데 점은 여섯이야.')
    #  M02960 — '이 이론이 주는 것은 배치와 각의 차례뿐' 이 제 계산 줄(180·120·109.5도)과 부딪쳤다
