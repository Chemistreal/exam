"""T12 마감 14제 4차 조치 — 3차 재설계가 ★다른 문항의 정답을 발문에 적어★ 놓았다

★4차 성적표★ defender ★조치 0건★ · factchecker 지금 고쳐야 1 · 두고 볼 것 1 · 참고 2 ·
solver 중 1 · 경 1. 실체는 거의 닫혔고, 남은 것 가운데 하나가 무겁다.

■ ★M01968 발문이 M01967 의 정답을 그대로 알려 준다 (solver '중')★
  3차에 M01968 을 '끊을 수 없는 빛은?' 으로 재설계하면서 발문에
  ★"수소 원자의 이온화 에너지 1312 kJ/mol 이 파장 91.1 nm 의 빛에 해당한다"★ 를 넣었다.
  그런데 M01967 이 묻는 것이 바로 '91.1 nm 가 무엇인가' 이고 그 정답이
  ★"수소의 이온화 에너지에 해당하는 빛의 파장이다"★ 다. ★두 문장은 동어반복이다.★
  같은 배치를 이어서 푸는 학생은 M01968 발문만 읽고 M01967 을 맞힌다.
  ◆규칙: 발문에 상수·등가 관계를 적을 때는 ★같은 배치의 다른 문항이 그것을 묻고 있지
    않은지★ 를 볼 것. 한 문항의 발문이 다른 문항의 답이 되면 세트가 무너진다.◆
  ▸ ★이것은 내가 3차에 만든 자리다.★ P15 에서 sim 의 M01947 대안을 같은 까닭으로 반려해
    놓고(그 대안이 M01948 의 정답과 같은 사실을 끌어왔다) 정작 내가 저질렀다.
  ▸ solver 의 개정안을 그대로 받는다 — 기준을 ★'파장 1000 nm 인 빛 1 몰의 에너지가 약
    120 kJ'★ 로 바꾸면 91.1 도 '이온화 에너지' 도 발문에서 사라진다.
    검산: 실제 1000 nm 의 몰당 에너지는 119.6 kJ 이라 120 은 정확한 어림이다.
    문턱 = 120 × 1000/170 = ★705.9 nm★.

■ ★M01968 선지 배열 — 800 만 홀로 튄다 (solver '경')★
  12 · 91 · 105 · 800 에서 ★800 만 자릿수와 영역이 홀로 다르다.★ 부정 발문과 겹치면
  '튀는 하나 고르기' 로 화학 없이 맞는다. 그리고 새 발문에서는 ★91 과 105 의 오류 경로가
  통째로 사라진다★ — 91.1 도 1312 도 발문에 없으니 '상수를 그대로 문턱으로' 도
  '1312 − 170 = 1142' 도 성립하지 않는다. 넷을 다시 짠다:
    ① 약 12 nm  — 가장 짧은 것이 가장 약하다고 본 λ–E 뒤집기 (10000 kJ/mol)
    ② 약 120 nm — 발문의 '120 kJ' 을 파장 자리로 옮겨 적음 (1000 kJ/mol)
    ③ 약 400 nm — 가시광선의 짧은 쪽 끝이라 익숙한 값 (300 kJ/mol)
    ④ 약 800 nm — ★150 kJ/mol 로 170 에 미치지 못한다★ (정답)
  검산: 문턱 705.9 nm 를 넘는 것은 800 하나뿐. 400 대 800 이 두 배 차이라 ★실제 계산이 든다.★

■ ★M01957 ③ 반박 — 부정이 한 겹 잘못 끼었다 (factchecker '지금 고쳐야')★
  "질량이 고르게 퍼져 있지 ★않다★ 는 것은 되튐이 반박하지" 라고 적었는데,
  되튐이 반박하는 것은 선지의 뒷짝인 '질량이 고르게 퍼져 있다' 쪽이다.
  지금 문장은 바로 앞의 '뒷짝이 거꾸로야' 와도, 뒤따르는 '가벼운 것에 부딪혔다면 되튀지
  못하거든' 과도 정면으로 어긋난다. ★2차에 이 반박을 고치면서 새로 들어간 흠이다.★

■ M01963 — '발머 계열은 출발이 3 · 4 · 5 · 6' 은 과잉 축소 (factchecker '두고 볼 것')
  발머 계열은 출발이 7 · 8 · … 로 이어지고 한계는 ∞ 다. 같은 해설 뒷부분이
  '출발을 ∞ 로 보낸 발머 계열 한계' 를 말하므로 ★내적으로도 어긋난다.★
  '눈에 보이는 네 선은' 으로 한정한다.

■ 참고 둘
  ▸ M01968 '빛 하나가 나르는 에너지가 170 kJ/mol' — ★광자 하나와 몰당 값을 한 문장에 섞었다.★
    계산은 전부 몰당으로 일관되므로 결과에는 영향이 없다. 새 해설에서 정리한다.
  ▸ M01970 factchecker 가 '발문이 정말 비정렬인지 대조해 달라' 고 했다 —
    ★확인했다. 486 · 656 · 410 · 434 로 흐트러져 있다.★ 조치 없음.

■ ★길이순위 조정★ M01968 이 [7,8,8,8] 이 되어 정답이 3 위로 내려간다. 그러면 배치의 3 위가
  다섯이 되므로, ★M01958 ② 를 1차 보정 이전 길이(23)로 되돌려★ 그 문항을 3 위 → 2 위로 옮긴다.
  (1차 보정 때 2 위가 일곱이라 옮겨 두었던 자리인데, 이제 M01968 이 그 몫을 가져간다.)

■ ★반려★
  ▸ solver 의 선지안 '91 · 105 · 400 · 800' — 새 발문에서 ★91 과 105 는 오류 경로를 잃는다★
    (91.1 도 1312 도 발문에 없다). 12(λ–E 뒤집기)와 120(발문 숫자 옮겨 적기)으로 바꿔
    네 값 모두에 경로를 붙였다. 배열이 홀로 튀지 않게 하려는 solver 의 뜻은 그대로 살렸다.
  ▸ solver 'M01963 이 단일 경로 문항이 되었다'(기록용) — 파장 → 에너지 환산 상수를 이 문항에
    두지 않은 것은 ★의도★ 다. 상수를 주면 전이 식별을 건너뛰어 3차에 회수한 첫 걸음이 다시
    사라진다. 난도 상승은 감수한다(심화 등급이 아니라 일반·중간이지만 두 걸음이 맞다).
  ▸ solver 'M01963 · M01970 이 발머 네 선을 함께 쓴다'(참고) — 한쪽이 다른 쪽의 답을 주지
    않는다는 것을 solver 자신이 확인했다. 세트 균형 기록으로만 남긴다.
"""
import json
import os

BANK = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'master_bank.json')


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:40]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


def main():
    bank = json.load(open(BANK, encoding='utf-8'))
    d = {x['id']: x for x in bank}

    # ══ M01957 ─ ③ 반박의 부정어 한 겹 ═══════════════════════════════════════
    sub(d['M01957'],
        '질량이 고르게 퍼져 있지 않다는 것은 되튐이 반박하지',
        '질량이 고르게 퍼져 있다는 뒷짝은 되튐이 반박하지')

    # ══ M01958 ─ ② 를 되돌려 길이순위를 3 위 → 2 위로 ═══════════════════════
    it = d['M01958']
    o2, n2 = '전자는 정해진 궤도에 있는 동안 빛을 내지 않는다', '전자는 정해진 궤도에서는 빛을 내지 않는다'
    assert it['choices'][1] == o2
    it['choices'][1] = n2
    sub(it, f'② {o2}: ', f'② {n2}: ')

    # ══ M01963 ─ '출발은 3·4·5·6' 을 눈에 보이는 넷으로 한정 ═══════════════
    sub(d['M01963'], '발머 계열은 도착이 2 이고 출발은 3 · 4 · 5 · 6 이야.',
        '발머 계열은 도착이 2 이고, 그 가운데 눈에 보이는 네 선은 출발이 3 · 4 · 5 · 6 이야.')

    # ══ M01968 ─ 발문에서 91.1·1312 를 걷어내고 선지 넷을 다시 짬 ═══════════
    it = d['M01968']
    it['stem'] = ('어떤 결합을 끊는 데 몰당 170 kJ 이 든다. 파장 1000 nm 인 빛 1 몰의 에너지가 '
                  '약 120 kJ 이고 빛의 에너지가 파장에 반비례한다고 할 때, 다음 빛 가운데 '
                  '이 결합을 끊을 수 없는 것은?')
    it['choices'] = ['약 12 nm', '약 120 nm', '약 400 nm', '약 800 nm']
    it['answer'] = 3
    it['distractors'] = [
        {'opt': 0, 'error': '파장이 짧을수록 에너지가 작다고 보아 가장 짧은 것을 골랐음', 'type': 'sign'},
        {'opt': 1, 'error': "발문의 '120 kJ' 이라는 수를 파장 자리로 옮겨 적음", 'type': 'unit'},
        {'opt': 2, 'error': '가시광선의 짧은 쪽 끝이라는 익숙함만으로 약한 빛이라고 봄', 'type': 'scale'}]
    it['answer_proof'] = ('빛의 에너지는 파장에 반비례하므로 파장 λ 인 빛 1 몰의 에너지는 '
                          '120 × 1000/λ kJ 이다. 12 nm 는 10000, 120 nm 는 1000, 400 nm 는 '
                          '300 kJ/mol 로 모두 170 을 넘지만 800 nm 는 150 kJ/mol 이라 170 에 '
                          '미치지 못한다. 끊을 수 있는 가장 긴 파장은 120 × 1000/170 = 706 nm '
                          '이므로 그보다 긴 800 nm 만 끊지 못한다')
    it['calc_check'] = '문턱 120 × 1000/170 = 706 nm → 800 nm 만 그보다 길다'
    it['solution'] = '\n'.join([
        '문턱을 하나 세워 놓고 넷을 견주는 문항이야.',
        '',
        '[정답] ④ 약 800 nm — 두 양의 관계부터 못 박자. 빛의 에너지는 파장에 반비례해. '
        '그러니 파장이 길수록 나르는 에너지가 작아지지. 이제 문턱을 구하자. 기준으로 준 것은 '
        '1000 nm 짜리 빛 1 몰이 약 120 kJ 이라는 짝이야. 결합을 끊으려면 빛이 나르는 몰당 '
        '에너지가 170 kJ 보다 작지 않아야 해. 120 에서 170 으로 에너지를 올리려면 몇 배가 '
        '필요한지 보면 170 나누기 120 은 약 1.42 배지. 에너지를 1.42 배로 올리려면 파장은 '
        '거꾸로 1.42 로 나눠야 하니 1000 나누기 1.42 는 약 706 이야. 곧 706 nm 가 끊을 수 있는 '
        '가장 긴 파장이지. 이제 넷을 대 보자. 12 · 120 · 400 nm 는 모두 706 보다 짧으니 '
        '에너지가 넉넉해 끊을 수 있어. 800 nm 만 706 보다 길지 — ④가 옳아. 값으로도 확인해 '
        '볼까. 800 nm 인 빛 1 몰은 120 × 1000 ÷ 800 이니 150 kJ 이야. 170 에 못 미치니 끊지 '
        '못하지. 여기서 방향을 한 번 더 새겨 두자. 파장이 길수록 약한 빛이야 — 짧은 쪽이 아니라.',
        '',
        '① 약 12 nm: 가장 짧으니 가장 약하다고 본 거야. 거꾸로지 — 12 nm 인 빛 1 몰은 약 '
        '10000 kJ 이라 이 결합쯤은 거뜬히 끊어.',
        '② 약 120 nm: 발문에 적힌 120 이라는 수를 파장 자리로 옮겨 적은 거야. 그 120 은 '
        '에너지(kJ)이지 파장이 아니지. 120 nm 인 빛은 1 몰에 1000 kJ 이나 돼.',
        '③ 약 400 nm: 눈에 보이는 빛의 짧은 쪽 끝이라 익숙하지만, 1 몰에 300 kJ 이라 '
        '170 을 훌쩍 넘어 끊을 수 있어.',
        '',
        '자가진단: 문턱 706 nm. 그보다 긴 빛만 못 끊는다.'])

    for x in bank:
        assert '**' not in x['stem'] and '**' not in x['solution'], x['id']
        assert '★' not in x['stem'] and '★' not in x['solution'], x['id']

    json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    from collections import Counter
    print('T12 마감 14제 4차 조치 완료 — 발문 1 · 문항 재설계 1 · 선지 1 · 해설 3')
    ranks = []
    for i in range(1957, 1971):
        x = d[f'M0{i}']
        L = [len(c) for c in x['choices']]
        s = sorted(L)
        sp = (s[3] - s[0]) / ((s[1] + s[2]) / 2)
        rk = sorted(range(4), key=lambda j: -L[j]).index(x['answer']) + 1
        ranks.append(rk)
        flag = '' if (sp <= 0.25 or s[1] < 8) else '  ← G3b'
        if L[x['answer']] == s[3] and L.count(s[3]) == 1:
            flag += '  ← G3 최장'
        if L[x['answer']] == s[0] and L.count(s[0]) == 1:
            flag += '  ← G3 최단'
        print(f'  {x["id"]} {L} 산포{sp:.2f} 순위{rk}{flag}')
    print('  길이순위', dict(sorted(Counter(ranks).items())))
    ad = Counter(x['answer'] for x in bank)
    print(f'  정답분포 ①{ad[0]}②{ad[1]}③{ad[2]}④{ad[3]} 편차{max(ad.values())-min(ad.values())}')


if __name__ == '__main__':
    main()
