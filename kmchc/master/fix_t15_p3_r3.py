# -*- coding: utf-8 -*-
"""T15 P3 3차 조치 — 2차 순회(defender 블로커 1 · factchecker ✗1 · 권고 여섯).

★★두 게이팅이 같은 자리를 냈다 — 선지를 갈면서 반박문을 함께 갈지 않았다★★
 M02323 ④ 를 '3주기에서만 …' 에서 '두 주기에서 모두 작아졌으므로 13족은 어느 주기에서나
 최솟값이다' 로 바꿨는데, 반박문('2주기도 작아졌어')은 옛 선지용 그대로 남았다. 새 ④ 는
 ★2주기도 작아졌다는 것을 스스로 인정하고 시작하는★ 선지라, 그 반박은 선지가 이미 말한 것을
 되풀이할 뿐 거짓인 부분(최솟값 주장)을 건드리지 못한다 — 학생이 읽으면 "④ 도 맞다는 말인가"
 가 된다. ▸ ★선지를 갈면 그 선지를 가리키는 모든 필드를 함께 센다★(계산줄은 갈았는데 해설과
 단평만 남았다 — 부분 적용 누락).

그 밖에 이번 조치가 심은 것 넷을 함께 닫는다(모두 낱말·어미 자리).
"""
import ast, io, sys

SRC = 'build_t15_p3.py'
BEFORE = io.open(SRC, encoding='utf-8').read()
body = BEFORE
log = []


def rep(old, new, expect=None):
    global body
    c = body.count(old)
    assert c > 0, '0곳: %r' % old[:60]
    if expect is not None:
        assert c == expect, '%d곳 (기대 %d): %r' % (c, expect, old[:60])
    body = body.replace(old, new)
    log.append('%d곳 %s' % (c, old[:22]))


# ════ 블로커 — M02323 ④ 반박문이 새 선지를 가리키지 못했다 ════
rep("'④는 두 주기에서 모두 작아졌으므로 13족은 어느 주기에서나 최솟값이다 라고 했어. 2주기도 '\n"
    "          '작아졌어. '",
    "'④는 두 주기에서 모두 작아졌으므로 13족은 어느 주기에서나 최솟값이다 라고 했어. 작아진 '\n"
    "          '것과 밑바닥인 것은 다른 말이야 — 2주기의 최솟값은 리튬 520 이고 3주기의 최솟값은 '\n"
    "          '나트륨 496 이라 어느 주기에서도 13족이 밑바닥은 아니지. '")
rep("'두 주기에서 모두 작아졌으므로 13족은 어느 주기에서나 최솟값이다': '2주기도 작아져.'",
    "'두 주기에서 모두 작아졌으므로 13족은 어느 주기에서나 최솟값이다': '1족이 더 작아.'")

# ════ 권고 A — M02320 ③④ 의 조사가 어긋나 정답만 문형이 달랐다 ════
#   ③ 을 ④ 에 맞추면 길이가 도로 유일 최단이 되므로 ★④ 를 ③ 에 맞춘다★.
rep('이온화 에너지 쪽은 알칼리 금속이 봉우리이고 반지름 쪽은 골이다',
    '이온화 에너지 쪽은 알칼리 금속이 봉우리이고 반지름 쪽에서는 골이다')

# ════ 권고 B — M02320 발문에 18족 단서 ════
#   반데르발스 반지름을 쓴 그래프라면 2주기에서 Ne 154 > Li 152 로 봉우리가 흔들린다.
rep("'번호이고 세로축이 원자 반지름인 그래프를 나란히 그렸다. 두 그래프 모두 톱니 '\n"
    "             '모양이다. 각 주기에서 알칼리 금속이 놓이는 자리로 옳은 것은?',",
    "'번호이고 세로축이 원자 반지름인 그래프를 나란히 그렸다. 반지름 그래프에는 18족 '\n"
    "             '원소가 실려 있지 않으며, 두 그래프 모두 톱니 모양이다. 각 주기에서 알칼리 '\n"
    "             '금속이 놓이는 자리로 옳은 것은?',")

# ════ 권고 C — M02319 ② 의 주술이 헐거웠다(헬륨이 껍질 안에 있고 헬륨이 붙잡힌다로 읽힌다) ════
rep('헬륨은 전자 둘이 다 찬 K 껍질에 있어 핵에 바짝 붙잡히기 때문이다',
    '헬륨은 전자 둘이 K 껍질을 다 채워 그 전자가 핵에 바짝 붙잡히기 때문이다')

# ════ 권고 D — M02319 ① 반박이 발문에서 걷어 낸 값에 기댔다 ════
rep("'수소가 하나로 더 적은데 그 값은 1312 로 헬륨보다 작지. '",
    "'수소가 하나로 더 적은데 그 값은 헬륨보다 작지. '")

# ════ 권고 E — M02321 ④ 어미가 셋과 어긋나고 해설이 축자 인용이 아니었다 ════
rep('질소는 탄소보다 원자 반지름이 커서 전자를 더 세게 붙잡고 있는 것이다',
    '질소는 탄소보다 원자 반지름이 커서 전자를 세게 붙잡고 있기 때문이다')
rep("'④는 질소는 탄소보다 반지름이 커서 전자를 더 세게 붙잡기 때문이라고 했어. 같은 주기에서 '",
    "'④는 질소는 탄소보다 원자 반지름이 커서 전자를 세게 붙잡고 있기 때문이라고 했어. 같은 주기에서 '")

# ════ 권고 F — M02328 ①④ 단평이 글자까지 같아졌다(저지른 셈은 서로 다르다) ════
rep("'리튬과 플루오린의 사이에 있으므로 520 과 1681 의 한가운데다': '간격이 고르지 않아.'",
    "'리튬과 플루오린의 사이에 있으므로 520 과 1681 의 한가운데다': '값이 곧은 줄이 아니야.'")

try:
    ast.parse(body)
except SyntaxError as e:
    sys.stderr.write('문법 오류 %s — 원본 복구\n' % e)
    io.open(SRC, 'w', encoding='utf-8').write(BEFORE)
    raise

GONE = ["2주기도 '\n          '작아졌어.", "'2주기도 작아져.'", '반지름 쪽은 골이다',
        '붙잡고 있는 것이다', "그 값은 1312 로 헬륨보다"]
for g in GONE:
    assert g not in body, 'GONE 남음: %r' % g

io.open(SRC, 'w', encoding='utf-8').write(body)
print('조치 %d건' % len(log))
for l in log:
    print('  ·', l)
