# -*- coding: utf-8 -*-
"""T13 P6 (M02021~M02030) 층5 6차(마감) 조치 — 사실 한 어절, 중복 둘, 재발 질문 하나.

5차 마감 확인 순회: ★네 검증자 전원 마감 가능★
  solver     — F1 0 · 열 문항 내 답 전부 정답 · "마감 가능"
  defender   — 오답 30 개를 다섯 경로로 다시 걸어 ★변호 성공 0 건★ · "마감해도 좋습니다"
  factchecker— ★확정 사실 오류 0 건★(셈 0 · 사실 0 · 문단 정합 0 · 문항 간 모순 0)
  student-sim— A 1 / B 0 / C 8 / D 10 · A·B 10/10 분리 · D 전항 정답 · "마감해도 좋습니다"

세 검증자(solver·defender·factchecker) 동시 0건이 성립했다. 남은 것은 다듬기뿐이라
따로 순회를 돌리지 않고 여기서 닫는다(P5 와 같은 절차).

받은 것 넷 (모두 해설 문면 — 발문·선지는 건드리지 않는다)
──────────────────────────────────────────────────────────────────────────
1. ★M02026 — '한 껍질 안에서 값의 가짓수가 늘어난다' 는 성립하지 않는다 (factchecker 사실)★
   한 껍질 안에서는 l 의 가짓수가 n 으로 고정이라 늘어날 것이 없다. 늘어나는 것은
   ★껍질이 커질 때★ 다. → '껍질이 커질수록 …' 으로 고친다.
2. ★M02024 — 해설이 '중성' 만 인용해 factchecker 가 두 회차 연속 같은 질문을 했다★
   발문은 '어떤 중성 원자의 ★바닥상태 전자배치가★ 3p⁴ 로 끝난다' 로 이미 두 겹이
   닫혀 있는데, 해설이 '중성 원자' 만 되짚어 4차·5차에 같은 확인 요청이 왔다.
   → ★해설이 발문의 두 못을 모두 되짚게 한다.★ 들뜬 배치(인 1s²2s²2p⁶3s¹3p⁴)가
     '바닥상태' 로 막힌다는 것을 한 마디로 적어 둔다.
   ▸ ★가드가 발문에 있어도 해설이 그것을 되짚지 않으면 검증자가 되풀이해 묻는다.★
3. ★M02022 — 도입부와 본문이 같은 이미지를 두 번 쓴다 (factchecker △, 두 회차 연속)★
   4차에 본문을 줄였는데도 '옆 칸에 내려앉게' 와 '옆 선지에 앉게' 가 남았다.
   → 도입부를 '기호를 l 로 옮기는 첫걸음에서 미끄러지도록 짜 두었지' 로 줄인다.
4. ★M02022 와 M02028 이 같은 문형을 쓴다 (factchecker △)★
   '앞자리 4 는 껍질을 말할 뿐이니' ↔ '발문의 4 는 껍질을 말할 뿐이고'.
   → M02022 쪽을 '앞자리 4 는 어느 껍질인지만 알려 줄 뿐이니' 로 변주한다.

반려한 것 여섯 (근거를 남긴다)
──────────────────────────────────────────────────────────────────────────
 · ★N2 M02022 를 4p → 4d 로 (solver 보통 · 이번 회차 최대 지적)★ — 반려.
   지적 자체는 맞다. 정답을 정하는 수 '6' 이 M02023 발문(`2p⁶ … 3p⁶`)과 M02025
   발문에 인쇄돼 있고, 6 을 품은 선지가 ② 하나뿐이다.
   그런데 ★완전 사다리에서는 정답값이 자리를 정한다★(설계 문서 §7-2). 4d 로 옮기면
   정답이 ③ 자리로 가는데,
     ㉠ 배치의 정답 차례가 ③②①③④②①②④① 이라 M02021(③)과 ★인접 중복 ③③★ 이
        생긴다. 이 차례는 앞 배치 꼬리까지 이어 붙여 G3d·G3e·G3f 와 반복 무늬를
        미리 돌려 정한 것이라 한 자리만 흔들 수 없다.
     ㉡ ③ 자리를 쓰는 문항이 이미 둘(M02021·M02024)이라 셋이 되면 차례 자체를
        다시 짜야 한다.
     ㉢ 이 문항은 sim 실측에서 ★네 프로필이 A① B③ C② D② 로 갈리는★ 자리다.
        선지를 통째로 갈면 그 측정을 버리고 다시 재야 한다.
   ▸ 그리고 이 우회로는 ★반쪽이다★ — `2p⁶` 를 4p 에 옮겨 쓰려면 ★앞자리 껍질 번호가
     정원과 무관하다★ 는 것을 알아야 하는데, 그것이 바로 이 문항의 첫걸음이다.
   → ★다음 개정 후보로 남긴다★(watch·대장). 값이 큰 지적이라 지우지 않고 적어 둔다.
 · ★N3 M02027 ③ 에서 '네온' 을 지워 [Ne] 노출을 끊기 (solver 경미)★ — 반려.
   [Ne] = 1s² 2s² 2p⁶ 이 M02023 의 심지 판정을 도와주는 것은 맞다. 그러나
   ㉠ 네온의 원자 번호 10 은 이 단원 어디서나 쓰는 기본값이고,
   ㉡ sim 실측에서 A 가 이 선지에 착지한다. ★살아 있는 착지점을 경미한 교차 단서와
     맞바꾸지 않는다★(3~5차 내내 지켜 온 잣대). → 관찰로 이월.
 · ★△5 M02030 의 2s < 2p 근거에 가려막기·침투를 덧붙이기 (factchecker)★ — ★반려.★
   ★침투는 금지 축이다★ — P5 에서 '가려막기 정도가 부껍질마다 다르다' 를 썼다가
   '이름만 안 쓴 침투 논증' 으로 범위 위반 판정을 받은 자리와 같다. 지금 문면
   ('전자가 둘 이상이면 서로 밀어내기 때문에')이 교재가 쓰는 문장이다.
   ▸ ★검증자가 침투 논거를 권하는 것은 이번이 두 번째다★(P5·P6). 범위 판정은 언제나
     우선한다 — 개념 대장에 못 박아 되풀이를 끊는다.
 · ★M02025 발문에 '바닥상태 Fe²⁺' 한 낱말 보험 (defender 선택 · 심각도 없음)★ — 반려.
   defender 스스로 변호 실패로 판정했고, 그 독법을 허용하면 ③(3p 이중 이온화)까지
   함께 열려 선지 구분이 무너진다고 적었다. 열리지 않은 문을 잠그지 않는다.
 · ★M02030 에 '일전자 화학종' 각주 (defender 선택)★ — 반려. 해설이 이미
   "전자가 하나뿐이어야 해" 로 기준을 전자 개수에 두고 있고, 발문 각주는 조판 부담만 는다.
 · ★M02028 을 n = 5 로 올려 A·C 동칸 충돌 풀기 (sim 다음 개정 후보)★ — 반려.
   n = 5 에서 mₗ = +2 를 갖는 부껍질은 5d·5f·★5g★ 셋이라 범위 밖이다(§7-7 ㉠).
   solver 도 4차에 같은 안을 냈다가 이 근거로 철회했다. → 관찰로 이월.

★내가 적은 근거 하나를 정정한다 (solver 가 잡았다)★
──────────────────────────────────────────────────────────────────────────
 5차 조치 문서에서 D6 을 반려하며 "채워진 원자에서 3d 가 4s 보다 ★높은★ 것은 참" 이라
 썼다. ★거꾸로다.★ 3d 가 채워지기 시작하면 원자 안에서 3d 가 4s 보다 ★낮아지고★,
 그래서 이온화 때 4s 가 먼저 빠진다. 반려 결론은 그대로 유효하되 근거를 고쳐 적는다 —
 solver 안 '부껍질 에너지가 높은 3d' 는 ★채우기 전 기준으로는 참★(쌓음 순서에서 3d 가
 4s 보다 높다)이고 ★채운 뒤 기준으로는 거짓★ 이라, 양쪽 독법이 갈리는 축을 오답의
 근거로 삼는 꼴이 된다. 금지 축인 까닭이 바로 그것이다.
 ▸ ★검증자의 지적을 반려할 때 적는 근거도 내가 직접 검산할 것★(P4·P6 에서 두 번째).
"""
import json
from collections import Counter

BANK = 'master/master_bank.json'
MK = ['①', '②', '③', '④']
IDS = ['M%05d' % n for n in range(2021, 2031)]
TOUCHED = {'M02022', 'M02024', 'M02026'}


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:40]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


bank = json.load(open(BANK, encoding='utf-8'))
D = {i['id']: i for i in bank}
before = {k: json.loads(json.dumps(D[k])) for k in IDS}

# ── 1. M02026 — 가짓수가 늘어나는 것은 껍질이 커질 때다 ────────────────────
sub(D['M02026'],
    '한 껍질 안에서 값의 가짓수가 늘어나는 것은 부양자수와 자기양자수 둘이고, '
    'mₛ 는 어느 껍질에서나 언제나 두 가지야.',
    '껍질이 커질수록 값의 가짓수가 늘어나는 것은 부양자수와 자기양자수 둘이고, '
    'mₛ 는 어느 껍질에서나 언제나 두 가지야.')

# ── 2. M02024 — 해설이 발문의 두 못을 모두 되짚게 한다 ────────────────────
sub(D['M02024'],
    '발문이 "중성 원자" 라고 못 박은 것도 눈여겨보자. 이온까지 열어 두면 아르곤에서 '
    '전자 둘을 뺀 것도 3p⁴ 로 끝나 버려 선지 안에서만도 답이 둘이 되거든.',
    '발문이 "중성 원자" 와 "바닥상태" 를 함께 못 박은 것도 눈여겨보자. 이온까지 열어 두면 '
    '아르곤에서 전자 둘을 뺀 것도 3p⁴ 로 끝나 버려 선지 안에서만도 답이 둘이 되고, '
    '들뜬 배치까지 열어 두면 인의 1s² 2s² 2p⁶ 3s¹ 3p⁴ 도 3p⁴ 로 끝나 버리거든. '
    '두 못이 함께 있어야 답이 하나로 좁혀져.')

# ── 3·4. M02022 — 도입부의 겹치는 이미지 · 다른 문항과 같은 문형 ──────────
it = D['M02022']
sub(it, '두 값을 함께 물었어. 어느 쪽으로 세든 기호를 l 로 옮기는 첫걸음에서 '
        '미끄러지면 그대로 옆 칸에 내려앉게 짜 두었지.',
        '두 값을 함께 물었어. 기호를 l 로 옮기는 첫걸음에서 미끄러지도록 짜 두었지.')
sub(it, '앞자리 4 는 껍질을 말할 뿐이니 일단 옆으로 밀어 두자.',
        '앞자리 4 는 어느 껍질인지만 알려 줄 뿐이니 일단 옆으로 밀어 두자.')

# ── 검사 ──────────────────────────────────────────────────────────────────
items = [D[k] for k in IDS]
assert Counter(i['answer'] for i in items) == {0: 3, 1: 3, 2: 2, 3: 2}
for k in IDS:
    assert D[k]['answer'] == before[k]['answer'], k
    assert D[k]['choices'] == before[k]['choices'], (k, '선지를 건드리지 않는다')
    assert D[k]['stem'] == before[k]['stem'], (k, '발문을 건드리지 않는다')
for k in set(IDS) - TOUCHED:
    assert D[k] == before[k], k

for it in items:
    cs = it['choices']
    assert len(cs) == 4 and len(set(cs)) == 4, it['id']
    assert sorted(d['opt'] for d in it['distractors']) == sorted(set(range(4)) - {it['answer']}), it['id']
    assert len(it['solution']) >= 300, (it['id'], len(it['solution']))
    assert '★' not in it['stem'] and '★' not in it['solution'], it['id']
    assert it['objective'], it['id']
    L = sorted(len(c) for c in cs)
    a = len(cs[it['answer']])
    assert not (a == L[3] and L[2] < L[3]), (it['id'], 'G3 최장 단독', cs)
    assert not (a == L[0] and L[0] < L[1]), (it['id'], 'G3 최단 단독', cs)
    mid = (L[1] + L[2]) / 2
    if mid >= 8:
        assert (L[3] - L[0]) / mid <= 0.25, (it['id'], 'G3b', cs, L)
    assert '가 옳아' in it['solution'] or '이 옳아' in it['solution'], it['id']
    for k in range(4):
        assert MK[k] + ' ' + cs[k] in it['solution'], (it['id'], MK[k], cs[k])

# ── 마감 검산 ─────────────────────────────────────────────────────────────
# ㉠ 발문의 두 못이 해설에서 되짚어지는가
assert '중성 원자' in D['M02024']['stem'] and '바닥상태 전자배치가 3p⁴ 로 끝난다' in D['M02024']['stem']
assert '"중성 원자" 와 "바닥상태" 를 함께 못 박은' in D['M02024']['solution']
# ㉡ 금지 축(침투·가려막기)이 어느 해설에도 들어오지 않았는가
for it in items:
    for bad in ('침투', '가려막', '가리움'):
        assert bad not in it['solution'], (it['id'], bad)
# ㉢ 같은 문형이 두 문항에 겹치지 않는가
assert '껍질을 말할 뿐' not in D['M02022']['solution']
assert '껍질을 말할 뿐' in D['M02028']['solution']
# ㉣ 같은 이미지가 한 해설에서 두 번 쓰이지 않는가
assert D['M02022']['solution'].count('옆') == 2      # '옆으로 밀어 두자' + '옆 선지에 앉게'
assert '옆 칸에 내려앉' not in D['M02022']['solution']

json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('T13 P6 6차(마감) 조치 완료 — 3 문항 · 해설 문면만')
print('  M02026 가짓수가 느는 것은 껍질이 커질 때 · M02024 두 못을 해설이 되짚음')
print('  M02022 도입부 중복 해소 · M02028 과의 동일 문형 변주')
