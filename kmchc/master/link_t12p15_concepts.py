def main():
    obj = json.load(open(CJ, encoding='utf-8'))
    C = obj[THEME]
    d = {c['id']: c for c in C}

    for cid, note in (('C12-018', NOTE_018), ('C12-N01', NOTE_N01), ('C12-028', NOTE_028),
                      ('C12-039', NOTE_039), ('C12-N04', NOTE_N04), ('C12-010', NOTE_010),
                      ('C12-N02', NOTE_N02)):
        d[cid]['note'] = (d[cid].get('note', '') + ' ' + note).strip()

    n = 0
    for cid, idx, mid in LINK:
        a = d[cid]['angles'][idx]
        assert not a['by'], f'{cid}[{idx}]: 이미 소진된 각도 -> {a["by"]}'
        a['by'].append(mid)
        n += 1

    have = {b for c in C for x in c['angles'] for b in x['by']}
    p15 = [f'M0{i}' for i in range(1947, 1957)]
    missing = [m for m in p15 if m not in have]
    assert not missing, f'대장 미링크 잔존: {missing}'
    dup = [m for m in p15 if sum(1 for c in C for x in c['angles'] for b in x['by'] if b == m) != 1]
    assert not dup, f'중복 링크: {dup}'
    free = sum(1 for c in C for x in c['angles'] if not x['by'])
    total = sum(len(c['angles']) for c in C)

    json.dump(obj, open(CJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'P15 대장 링크 {n}건 · 저작 주의 7건 추가')
    print(f'  개념 {len(C)}개 · 각도 {total}개 · 미소진 {free}개')


if __name__ == '__main__':
    main()
