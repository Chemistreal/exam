"""T15 P3 9차 조치 — solver 4차의 진단: ★남은 취약점은 세트 바깥에서 온다★.

solver 4차: 차단 2·좁힘 8. 3차의 주력이던 네 갈래(길이·발문 되풀이·포함관계·유일 결론)는
실제로 잦아들었고, 남은 두 갈래는 ★자멸하는 오답★ 과 ★문항 간 누출★ 이다.
 ▸ "문항 안쪽 손질은 이미 수익이 줄었습니다. M02320·M02322·M02323 은 더 건드리지 마십시오 —
   셋 다 대칭적으로 잘 짜여 있고 남은 취약점은 전부 세트 바깥에서 옵니다."

우선순위 다섯 가운데 ★셋을 받고 둘을 물린다★.

■ 받은 셋
 ① M02321 ①② — '2p 세 방' 을 뺐지만 ① 의 '홀로 하나씩' 과 ② 의 '셋뿐' 이 같은 정보를
   그대로 날라 M02324 행 고리가 살아 있었다. 둘을 함께 눅여 실제로 끊는다.
   덤으로 ①② 가 '질소는 2p 에 전자가' 로 글자까지 같던 도입도 갈라진다.
 ② M02326 발문 — 양성자 수만 주고 원자가전자 수를 주지 않아 ★발문이 준 자료를 쓰는 쪽★ 이
   ① 이라는 포인터가 섰다. 원자가전자 수 1 과 7 을 함께 실어 상쇄한다.
 ③ M02327 ④ · M02328 ① — 8차에 심은 자멸(전제와 결론이 어긋남)과 누설(오답이 탄소의
   자리를 알려 줌)을 한 줄씩 갈아 닫는다.

■ ★물린 둘과 그 까닭★
 ㉠ **M02325 의 첫 값 738 을 갈라** — 갈 수 없다. 3껍질·급증 2회·나머지 이음이 모두 2배
   아래인 원소는 화학I 범위에서 Mg·Na·Si 셋뿐인데, Na 의 496 과 Si 의 첫 비 2.05 가 각각
   ★이미 마감한 P2 의 문항★ 과 ★해설의 '모두 두 배 아래' 주장★ 에 걸린다. 값을 갈려면
   마감한 배치를 다시 열어야 하므로 ★부채로 넘긴다★ — 다만 'M' 고리를 끊었으므로 남은
   길은 '3주기' 라는 낱말과 '셋' 이라는 수의 표면 일치뿐이다.
 ㉡ **수치 선지를 오름차순으로 되돌려라** — 받지 않는다. 오름차순으로 두려면 정답이 ① 로
   가고, 자리 분포를 맞추려 ★다른 문항의 정답 자리까지 옮겨야★ 하는데 그러면 G3e·G3f 를
   맞물려 고른 열 전체를 다시 골라야 한다. 내림차순도 ★단조★ 이므로 P1 이 세운 규약
   (정답이 유일한 파괴자가 되지 않게)은 지켜진다. 관행 어긋남은 부채로 적는다.
"""
import ast, io, sys

SRC = 'build_t15_p3.py'
BEFORE = io.open(SRC, encoding='utf-8').read()
body = BEFORE
log = []


def rep(old, new, expect=None):
    global body
    c = body.count(old)
    assert c > 0, '0곳: %r' % old[:60]
    if expect is not None:
        assert c == expect, '%d곳 (기대 %d)' % (c, expect)
    body = body.replace(old, new)
    log.append('%d곳 %s' % (c, old[:24]))


# ════ ① M02321 ①② — M02324 행 고리를 실제로 끊는다 ════
rep('질소는 2p 에 전자가 홀로 하나씩 들어 안정한 배치이기 때문이다',
    '질소는 2p 가 반쯤 채워져 그만큼 안정한 배치이기 때문이다')
rep('질소는 2p 에 전자가 셋뿐이라 서로 밀치는 몫이 가장 작기 때문이다',
    '질소는 2p 전자끼리 밀치는 몫이 이웃보다 작기 때문이다')
rep("'②는 질소는 2p 에 전자가 셋뿐이라 서로 밀치는 몫이 가장 작기 때문이라고 했어. 밀침이 '",
    "'②는 질소는 2p 전자끼리 밀치는 몫이 이웃보다 작기 때문이라고 했어. 밀침이 '")

# ════ ② M02326 발문 — 원자가전자 수를 함께 실어 포인터를 상쇄한다 ════
rep("'같은 3주기이고 원자가전자가 든 껍질도 서로 같은데, 양성자 수는 11 과 17 이다. '",
    "'같은 3주기이고 원자가전자가 든 껍질도 서로 같은데, 양성자 수는 11 과 17 이고 '\n"
    "             '원자가전자 수는 1 과 7 이다. '")

# ════ ③ M02327 ④ — 전제와 결론이 어긋나 스스로 죽던 것을 단정으로 바꾼다 ════
rep('두 경향이 같은 쪽으로 겹쳐 더해지므로 대소가 정해지지 않는다',
    '두 경향이 같은 쪽으로 겹쳐 더해지므로 나가 가보다 크다')
rep("('두 경향이 같은 쪽으로 겹쳐 더해지므로 나가 가보다 크다', '반대로 미는 둘을 '\n"
    "               '같은 쪽으로 봄', 'conserv')",
    "('두 경향이 같은 쪽으로 겹쳐 더해지므로 나가 가보다 크다', '반대로 미는 둘을 같은 쪽으로 '\n"
    "               '보고 대소까지 단정함', 'conserv')")

# ════ ③' M02328 ① — 오답이 탄소의 자리를 알려 주던 것을 끊는다 ════
rep('붕소와 질소의 값을 평균한 1101.5 kJ/mol 이다',
    '리튬과 붕소의 값을 평균한 660.5 kJ/mol 이다')
rep("'①은 리튬과 붕소의 값을 평균한 660.5 kJ/mol 이다 라고 했어. 평균은 간격이 일정할 때만 '\n"
    "          '맞는데 적힌 네 값의 간격도 281, 601, 279 로 고르지 않지. '",
    "'①은 리튬과 붕소의 값을 평균한 660.5 kJ/mol 이다 라고 했어. 탄소는 리튬과 붕소 사이가 '\n"
    "          '아니라 붕소보다 뒤에 있고, 평균은 간격이 일정할 때만 맞는데 적힌 네 값의 간격도 '\n"
    "          '281, 601, 279 로 고르지 않지. '")
rep("'리튬과 붕소의 값을 평균한 660.5 kJ/mol 이다': '간격이 고르지 않아.'",
    "'리튬과 붕소의 값을 평균한 660.5 kJ/mol 이다': '탄소는 붕소 뒤야.'")
rep("'① 평균은 간격이 일정할 때만 맞고 적힌 네 값의 간격도 281·601·279 로 고르지 않음 / '",
    "'① 탄소는 리튬과 붕소 사이가 아니고, 평균은 간격이 일정할 때만 맞음(간격 281·601·279) / '")

try:
    ast.parse(body)
except SyntaxError as e:
    sys.stderr.write('문법 오류 %s — 원본 복구\n' % e)
    io.open(SRC, 'w', encoding='utf-8').write(BEFORE)
    raise

for g in ['홀로 하나씩 들어', '셋뿐이라 서로 밀치는', '대소가 정해지지 않는다',
          '붕소와 질소의 값을 평균한']:
    assert g not in body, 'GONE 남음: %r' % g

io.open(SRC, 'w', encoding='utf-8').write(body)
print('조치 %d건' % len(log))
for l in log:
    print('  ·', l)
