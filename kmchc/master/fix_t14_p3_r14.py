"""T14 P3 14차 조치 — 한 구절. 셋 중 둘이 0건, 하나가 범위 한정 하나.

14차 순회의 자리
────────────────────────────────────────────────────────────────────
▸ solver: ★0건 (확신도 높음) — 세 회차 연속.★ 13차에 넣은 M02161 발문의 원자 번호가
  실제로 작동했다: '원자 번호 3·11·19 → 껍질 수 1·2·3' 으로 ② 를 발문 안에서 깼다.
  M02161 ①과 M02162 ① 이 겉보기에 충돌하는 자리도 값을 인용해 스스로 닫았다.
▸ defender: ★0건.★ 네 회차를 끌던 겨냥 겹침 셋(M02163 ③④ · M02164 ②④ · M02160 ①③)을
  ★구조적 근거로 직접 닫았다★ — 특히 M02163 은 두 줄 내부가 각각 전순서로 완결돼 있어
  미결정 쌍이 '다른 줄' 아니면 '미수록 원소' 둘뿐이고, 셋째 유형을 넣으면 곧바로 F2 가
  된다는 것을 보였다. ★네 회차 만에 '고칠 수 없다' 가 아니라 '고칠 필요가 없다' 로
  결론이 바뀌었다.★ 13차에 넣은 '닫은 자리를 다시 올리려면 달라진 근거를 대라' 는
  조항이 효과를 냈다 — 재상정 0건.
▸ student-sim: ★문항 결함 없음 (여섯 회차 연속).★ 대안 없음 + 후보 셋 자진 기각.
▸ factchecker: ★지적 1건★ — 사실 오류가 아니라 한 구절의 범위 한정이다.

14차 조치 하나
────────────────────────────────────────────────────────────────────
① M02164 ④ 본문·압축 줄의 범위 한정 (factchecker 중)
   '전자가 둘 이상인 원자에서는 … 유효 핵전하가 핵전하보다 작아' 로 ★다르다는 것을 이미
   단정★ 해 놓고, 바로 뒤에서 '같다 다르다를 말할 수가 없지' 라고 해 앞을 도로 무르는
   모양이 됐다. 말할 수 없는 것은 ★수치로 맞대어 보는 일★ 이지 대소 자체가 아니다.
   ▸ ★factchecker 가 검증한 문면을 그대로 쓴다.★ 열네 회차를 돌아 보니, 내가 다시
     고쳐 쓰면 다음 회차에 새 결이 생겼다(9→10→11→12→13차의 M02164 ④·M02159 ④·
     M02160 ③ 이 모두 그랬다). ★남은 것이 한 구절뿐일 때는 검증된 문면을 옮겨 적는다.★

기각
────────────────────────────────────────────────────────────────────
▸ ★기각★ M02160 ② 죽은 선지(student-sim, 실질 사망) — 세 회차 연속 '안전한 대안 없음'
  이다. student-sim 이 후보 셋을 스스로 기각했다(③과 같은 계열 · 절이 발문상 참 ·
  발문에서 반박되지 않음). ★이 문항은 ③④ 가 표를 다 가져가는 구조라 나머지 두 칸 중
  하나는 늘 빈다★ — 회차마다 ①과 ② 사이를 옮겨 다닌다. 문항 설계 부채로 적는다.
▸ ★기각★ M02157·M02156 의 두 척도 수치(factchecker 낮음, 참고) — 검증자 자신이
  '판정의 근거가 배수·차가 아니라 전자 배치에 있어 그대로 두어도 된다' 고 적었다.
  12차에 선을 한 칸 안으로 옮긴 것이 여기서 확인됐다.
▸ ★기각★ M02162 스트론튬(factchecker 낮음, 참고) — 자료 귀속과 한정이 되어 있다.
"""
import re

P = 'build_t14_p3.py'
src = open(P, encoding='utf-8').read()
orig = src

R = [
    ("          '핵을 가려 유효 핵전하가 핵전하보다 작아. 게다가 유효 핵전하 축에는 숫자가 없으니, '\n"
     "          '원자 번호로 알 수 있는 양성자 수와 견주어 같다 다르다를 말할 수가 없지. '\n",
     "          '핵을 가려 유효 핵전하가 핵전하보다 작아. 게다가 유효 핵전하 축에는 숫자가 없으니, '\n"
     "          '원자 번호로 알 수 있는 양성자 수와 이 그래프 위에서 수치로 맞대어 볼 수는 없지. '\n"),
    ("                                                            '유효 핵전하가 더 작고, 축에 숫자가 '\n"
     "                                                            '없어 견줄 수도 없어.'},\n",
     "                                                            '유효 핵전하가 더 작고, 축에 숫자가 '\n"
     "                                                            '없어 수치로 견줄 수도 없어.'},\n"),
]

for a, b in R:
    n = src.count(a)
    assert n == 1, f'{n}곳 — {a[:56]!r}'
    src = src.replace(a, b)

body = '\n'.join(l for l in src.split('\n') if not l.lstrip().startswith('#'))
body = body[body.index('def build('):]
for b in ('같다 다르다를 말할 수가 없지', '없어 견줄 수도 없어'):
    assert b not in body, f'금지 문면 잔존 — {b}'

flat = re.sub(r"'\s*\n\s*'", '', body)
for s, k in (('이 그래프 위에서 수치로 맞대어 볼 수는 없지', 1),
             ('축에 숫자가 없어 수치로 견줄 수도 없어', 1)):
    n = flat.count(s)
    assert n == k, f'{s[:34]!r} — {n}곳 (기대 {k})'

assert src != orig
open(P, 'w', encoding='utf-8').write(src)
print('✅ 14차 조치 적용 — M02164 ④ 본문·압축 줄의 범위 한정')
