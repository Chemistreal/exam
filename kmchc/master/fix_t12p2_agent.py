def _replace_item(x, ch, dist, solution, answer):
    x['choices'] = list(ch)
    x['distractors'] = [dict(d) for d in dist]
    x['solution'] = solution
    x['answer'] = answer


def apply(bank):
    idx = {x['id']: x for x in bank}
    n = 0

    it = idx['M01817']
    assert '원자를 이루는 것들' in it['stem'], "M01817 원본 stem 불일치"
    it['stem'] = M17_STEM
    _replace_item(it, M17_CH, M17_DIST, M17_SOL, 2); n += 4

    it = idx['M01820']
    assert it['choices'][0] == "라이먼 계열 — 자외선", "M01820 원본 보기 불일치"
    _replace_item(it, M20_CH, M20_DIST, M20_SOL, 2); n += 4

    it = idx['M01823']
    assert it['choices'][1] == "흡수와 방출의 크기가 서로 같다", "M01823 원본 보기 불일치"
    _replace_item(it, M23_CH, M23_DIST, M23_SOL, 1); n += 4

    it = idx['M01825']
    assert it['choices'][3] == "n 이 한없이 커진 상태를 0 으로 잡았기 때문이다", "M01825 원본 보기 불일치"
    _replace_item(it, M25_CH, M25_DIST, M25_SOL, 3); n += 4

    it = idx['M01826']
    assert it['choices'][1] == "−328 kJ/mol", "M01826 원본 보기 불일치"
    _replace_item(it, M26_CH, M26_DIST, M26_SOL, 2)
    it['answer_expr'] = "-1312//4"; n += 5

    for fid, old, new in STEM_REPL:
        x = idx[fid]
        assert x['stem'] == old, f"{fid} stem 불일치:\n기대 {old}\n실제 {x['stem']}"
        x['stem'] = new; n += 1
    for fid, i, old, new in CH_REPL:
        x = idx[fid]
        assert x['choices'][i] == old, f"{fid} {CIR[i]} 불일치: {x['choices'][i]}"
        x['choices'][i] = new
        for d in x['distractors']:
            if d['opt'] == i:
                d['text'] = new
        n += 1
    for fid, old, new in SOL_REPL:
        x = idx[fid]
        assert old in x['solution'], f"{fid} 해설 불일치: {old[:44]}"
        x['solution'] = x['solution'].replace(old, new, 1); n += 1

    # 교체된 보기의 오답 메타 갱신
    for fid, opt, err, typ in [
            ('M01818', 2, '이 실험은 입자의 정체를 재지 않음 · 기체 무관은 음극선 쪽', 'proc'),
            ('M01821', 3, '한 번에 낼 때가 에너지 최대이므로 파장 최단', 'sign'),
            ('M01822', 3, '위로 올라갈 때는 방출이 아니라 흡수', 'sign'),
            ('M01824', 3, '바깥 궤도일수록 반지름이 큼', 'sign')]:
        hit = [d for d in idx[fid]['distractors'] if d['opt'] == opt]
        assert hit, f"{fid} opt{opt} 없음"
        hit[0]['error'] = err; hit[0]['type'] = typ; n += 1

    for fid in [f"M0{i}" for i in range(1817, 1827)]:
        idx[fid]['verified'] = dict(VERIFIED)
        if fid in WATCH:
            idx[fid]['verified']['watch'] = WATCH[fid]
    return bank, n


