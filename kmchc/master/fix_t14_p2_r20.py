import os
import re

BASE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(BASE, 'build_t14_p2.py')

R = [
    ("['리튬 Li, 플루오린 F', '나트륨 Na, 염소 Cl',",
     "['플루오린 F, 리튬 Li', '나트륨 Na, 염소 Cl',"),
    ("[('리튬 Li, 플루오린 F', '같은 주기인데 족이 멀어 껍질도 다르다고 봄', 'surface'),",
     "[('플루오린 F, 리튬 Li', '같은 주기인데 족이 멀어 껍질도 다르다고 봄', 'surface'),"),
    ("'①은 리튬과 플루오린인데 둘 다 2주기야. 주기율표에서 왼쪽 끝과 오른쪽 가까이로 멀리 '",
     "'①은 플루오린과 리튬인데 둘 다 2주기야. 주기율표에서 오른쪽 가까이와 왼쪽 끝으로 멀리 '"),
    ("{'리튬 Li, 플루오린 F': '주기율표에서 멀리 떨어진 것은 족이고 주기는 같아. '",
     "{'플루오린 F, 리튬 Li': '주기율표에서 멀리 떨어진 것은 족이고 주기는 같아. '"),
]

BAN_AFTER = ['리튬 Li, 플루오린 F', '리튬과 플루오린']


def main():
    src = open(SRC, encoding='utf-8').read()
    for i, (a, b) in enumerate(R, 1):
        n = src.count(a)
        assert n == 1, f'{i}번 문면이 {n}곳 — 손으로 볼 것\n---\n{a[:160]}'
        src = src.replace(a, b)
    for s in BAN_AFTER:
        assert s not in src, f'조치 뒤에도 남았다: {s}'
    flat = re.sub(r"'\s*\n\s*'", '', src)
    assert flat.count('플루오린 F, 리튬 Li') == 3, '선지·wrongs·wmap 세 곳'
    open(SRC, 'w', encoding='utf-8').write(src)
    print(f'T14 P2 20차 조치 — {len(R)}곳 교체')
    print('  M02145 ① 을 뒤집어 원자 번호 배열 방향을 2:2 로 (13자 그대로)')
    print('  ★표면 단서는 층으로 쌓여 있다 — 하나를 걷어낸 뒤 같은 문항을 다시 훑는다.★')


if __name__ == '__main__':
    main()
