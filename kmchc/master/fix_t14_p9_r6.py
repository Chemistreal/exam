# -*- coding: utf-8 -*-
"""T14 P9 6차 조치 — 문단의 범위는 절마다가 아니라 문단 앞에서 한 번에 박는다.

6차 보고. factchecker ★✗ 0 · △ 1★(1차 ✗4△12 → 2차 ✗0△5 → 3차 ✗1△3 → 4차 ✗0△1 →
5차 ✗0△1 → 6차 ✗0△1). ✗ 는 세 회차 연속 0 이고, 남은 △ 는 세 회차 내내 ★M02220 ②
해설 한 문단★ 안에서만 자리를 옮겨 다녔다.

★① 한 절에 범위를 박으면 이웃 절의 무한정이 도드라진다 — 문단의 범위는 문단 앞에서
   한 번에 박는다.★
  세 회차의 무늬를 나란히 적는다.
  · 3차 → ② 의 예시가 ★엇갈리는 쌍이 아니었다★(F–Na 는 두 규칙이 같은 쪽). 질소·황으로.
  · 4차 → 뒤 절의 '가로로 멀리 건너뛴 쌍' 이 ★두 칸을 안전지대로 넘겨주었다.★
    '두 칸만 벌어져도' 로.
  · 5차 → 그 단평이 ★그 줄만 떼면 새 규칙으로 굳었다.★ 주어와 쌍 이름을 되돌렸다.
  · 6차 → 이제 앞 절의 '확실한' 이 도드라졌다. ★한 칸도 2·3주기 밖에서는 껍질이 진다★ —
    Mg 160 / Ga 135, Ca 197 / In 167(d-구역이 끼어 양성자가 열 개 더 붙는 자리).
  ▸ ★절마다 따라가며 박으면 이웃이 계속 남는다.★ 범위를 문단 앞에 한 번 세워 두 절을
    함께 덮는다 — '2주기와 3주기에서 보면' 을 문단 머리에 놓는다.
  ▸ 그 범위 안에서는 factchecker 가 검산한 대로 한 칸 대각 쌍 여섯이 모두 껍질 쪽
    승리이고(Li–Mg · Be–Al · B–Si · C–P · N–S · O–Cl) '확실한' 이 성립하며, 두 칸은
    갈리므로(Be 112 < Si 117 은 이기고 Li 152 > Al 143 은 진다) '기도 해' 라는 헤지가
    그 갈림을 규칙으로 굳히지 않은 채 담는다.

★② 한 반례가 두 규칙을 동시에 무너뜨리는 것은 되풀이가 아니다.★ (되묻기 답)
  5차 조치로 ②③ 단평이 둘 다 리튬–알루미늄을 들게 되었다. 되묻자 factchecker 가
  판정했다 — ★두 단평은 같은 사실 하나에 기대지만 서로 다른 명제를 무너뜨린다.★
  ② 는 '엇갈리면 껍질 수 쪽이 반드시 이긴다' 를 쳐서 초점이 ★요인의 우열★ 에 있고,
  ③ 은 '번호가 큰 쪽이 크다' 를 쳐서 초점이 ★잣대의 무효★ 에 있다. 선지 문면이 각 줄
  앞머리에 붙어 있어 무엇을 치는지도 갈린다. ▸ 되풀이가 아니라고 확인되었다.

이번 조치도 ★선지 문면을 하나도 건드리지 않는다★ — 3차 이후 마흔 개가 고정이다.
"""
import re

P = 'build_t14_p9.py'
src = open(P, encoding='utf-8').read()

CHOICES_RE = re.compile(r"\['(.+?)'\], (\d)", re.S)
BEFORE = CHOICES_RE.findall(src)
assert len(BEFORE) == 10
CH_BEFORE = [re.findall(r"'([^']+)'", f"'{b}'") for b, _ in BEFORE]
ANS_BEFORE = [a for _, a in BEFORE]


def sub(old, new, n=1):
    global src
    c = src.count(old)
    assert c == n, f'{c}곳(기대 {n}): {old[:56]!r}'
    src = src.replace(old, new)


# ══ M02220 ② ── 범위를 문단 앞에 한 번 세워 두 절을 함께 덮는다 ═════════════
sub("          '②는 좁은 구간의 보증을 규칙으로 넓혔어. 껍질 쪽이 이기는 것이 확실한 자리는 '\n"
    "          '질소와 황처럼 한 주기 내려가면서 오른쪽으로 한 칸만 간 쌍이고, 리튬과 '\n"
    "          '알루미늄처럼 두 칸만 벌어져도 껍질이 더 많은 쪽이 오히려 작기도 해. '",
    "          '②는 좁은 구간의 보증을 규칙으로 넓혔어. 2주기와 3주기에서 보면, 껍질 쪽이 '\n"
    "          '이기는 것이 확실한 자리는 질소와 황처럼 한 주기 내려가면서 오른쪽으로 한 '\n"
    "          '칸만 간 쌍이고, 리튬과 알루미늄처럼 두 칸만 벌어져도 껍질이 더 많은 쪽이 '\n"
    "          '오히려 작기도 해. '")

open(P, 'w', encoding='utf-8').write(src)


# ── ★기계로 센다★ ─────────────────────────────────────────────────────────────
body = '\n'.join(l for l in src.split('\n') if not l.strip().startswith('#'))
body = body[body.index('def build('):]
flat = re.sub(r"'\s*\n\s*'", '', body)

assert not re.search(r'[가-힣]★\s(를|을|은|의|으로|로|에서|에|과|보다|처럼|까지|부터'
                     r'|이고|이다|이야|이라|이지|인|야|다)(?=[\s,.·)?!\'"])', flat), \
    '★ 뒤에서 조사를 뗐다'
assert not re.search(r'[가-힣]\s(를|을|로)(?=[\s,.·)?!])', flat), '조사를 앞말에서 뗐다'
assert not re.search(r'\d+\s*pm', flat), '이 배치는 pm 값을 싣지 않는다'

AFTER = CHOICES_RE.findall(src)
assert len(AFTER) == 10
assert [a for _, a in AFTER] == ANS_BEFORE, '정답 자리가 바뀌었다'
CH = [re.findall(r"'([^']+)'", f"'{blk}'") for blk, _ in AFTER]
assert CH == CH_BEFORE, '선지 문면이 바뀌었다 — 3차 이후 마흔 개는 고정이다'

# ★범위가 문단 앞에 한 번 서서 두 절을 함께 덮는가★ — M02220 ②
s20 = flat[flat.index("T.mk('M02220'"):flat.index("T.mk('M02221'")]
i = s20.index('②는 좁은 구간의 보증을')
para = s20[i:s20.index('③은 번호가 크면', i)]
assert para.index('2주기와 3주기에서 보면') < para.index('확실한'), \
    '범위가 확실한 앞에 서지 않았다'
assert para.index('2주기와 3주기에서 보면') < para.index('두 칸만 벌어져도'), \
    '범위가 두 절을 함께 덮지 않는다'

print('fix_t14_p9_r6 적용 완료 — 선지 문면 불변, M02220 ② 해설 한 문단의 범위')
