STALE = [
    ('M01900', 'stem', '어디에만 두어도 충분했겠는가'),
    ('M01900', 'solution', '대비였던 셈이야'),
    ('M01902', 'solution', '논증과 같은 방향'),
    ('M01902', 'answer_proof', '점점 작아지다 사라져야'),
    ('M01903', 'solution', '네 조각'),
    ('M01901', 'solution', '부호를 놓친 거지'),
    ('M01906', 'stem', '1→'),
    ('M01906', 'solution', '1→m'),
    ('M01906', 'answer_proof', '1→m'),
]


def main():
    d = json.load(open(BANK, encoding='utf-8'))
    items = d if isinstance(d, list) else d['items']
    x = {it['id']: it for it in items}
    n = 0

    for fid, r in REPL.items():
        it = x[fid]
        for key, val in r.items():
            assert it[key] != val, f'{fid}: {key} 가 이미 같음'
            it[key] = val
            n += 1

    for fid, key, old, new in SUB:
        it = x[fid]
        assert old in it[key], f'{fid}.{key}: 대상 조각 없음 -> {old[:40]}'
        assert it[key].count(old) == 1, f'{fid}.{key}: 조각이 둘 이상'
        it[key] = it[key].replace(old, new)
        n += 1

    for fid, key, frag in STALE:
        assert frag not in x[fid][key], f'{fid}.{key}: 옛 문면 잔존 -> {frag}'

    # ── 자체 점검 ──────────────────────────────────────────────
    it = x['M01900']
    assert it['choices'][it['answer']] == M1900_CH[0]
    for c in it['choices']:
        assert c.endswith('줄일 수 있다') or c.endswith('둘러야 한다'), c
    # 화살표 방향이 모두 m→1 인가
    for key in ('stem', 'solution', 'answer_proof'):
        s = x['M01906'][key]
        assert '1→' not in s, f'M01906.{key}: 1→ 잔존'
    # 해설 길이·오답 줄 유지
    for fid in ('M01900', 'M01901', 'M01902', 'M01903', 'M01906'):
        s = x[fid]['solution']
        assert len(s) >= 300, f'{fid}: 해설 {len(s)}자'
        for mk in ('①', '②', '③', '④'):
            assert mk in s, f'{fid}: {mk} 줄 없음'
        assert '**' not in s and '★' not in s, f'{fid}: 금지 기호'

    json.dump(d, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

    print(f'P10 2차 조치 {n}곳 · 채택 7 · 반려 3')
    for fid in ('M01900', 'M01901', 'M01902', 'M01903', 'M01906'):
        it = x[fid]
        L = [len(c) for c in it['choices']]
        s = sorted(L)
        sp = (s[3] - s[0]) / ((s[1] + s[2]) / 2)
        rk = sorted(range(4), key=lambda i: -L[i]).index(it['answer']) + 1
        print(f"  {fid} 정답{'①②③④'[it['answer']]} 길이{L} 산포{sp:.2f} "
              f"길이순위{rk} 해설{len(it['solution'])}자")


if __name__ == '__main__':
    main()
