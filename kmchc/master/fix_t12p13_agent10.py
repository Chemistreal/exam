import json, os

BANK = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'master_bank.json')


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:30]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


def main():
    bank = json.load(open(BANK, encoding='utf-8'))
    d = {x['id']: x for x in bank}

    sub(d['M01928'],
        '게다가 이 논증은 중성자를 작다고 본 것이 아니라 아예 셈에 두지 않았지 — '
        '빠뜨린 두 개분이 곧 어긋남의 정체야.',
        '게다가 이 논증이 예상을 세울 때는 중성자를 작다고 본 것이 아니라 아예 셈에 두지 '
        '않았어 — 그러니 "작아서 무시했다"는 전제가 될 수 없지. 빠뜨린 두 몫이 곧 어긋남의 '
        '정체이고, 논증이 중성자를 불러낸 것은 그 어긋남을 보고 난 뒤야.')

    sub(d['M01932'],
        '그 계열이 내놓는 에너지의 크기도 함께 정해져. 세 계열의 에너지 구간은 서로 '
        '겹치지도 않아.',
        '그 계열이 내놓는 에너지의 범위도 함께 정해져. 그리고 세 범위는 서로 겹치지도 않아.')

    sub(d['M01934'],
        '원자가 대부분 비어 있다는 결론은 이 둘이 아니라 세 번째 결과, 곧 대부분이 그대로 '
        '지나갔다는 데서 나와.',
        '원자가 대부분 비어 있다는 결론은 이 둘이 아니라 세 번째 결과, 곧 대부분이 그대로 '
        '지나갔다는 데서 나와. 되튐이 드물다는 것과 대부분이 지나갔다는 것은 사실 같은 셈을 '
        '양쪽에서 읽은 거야 — 드문 쪽을 보면 표적이 좁다는 말이 되고, 나머지 대부분을 보면 '
        '길이 비어 있다는 말이 되지.')

    it = d['M01935']
    sub(it, '만약 극을 바꾸었는데도 같은 쪽으로 휘었다면 그때는 전기장이 원인이 아니라고 '
            '의심해야 하지.',
        '만약 극을 바꾸었는데도 같은 쪽으로 휘었다면 그때는 휘어짐의 원인이 전기장이 아니라고 '
        '의심해야 하지.')
    sub(it, '① 위로 휘고, 음극선이 (−)전하를 띤다는 결론도 그대로다: 극을 바꾸었는데 휘는 '
            '방향까지 그대로일 수는 없어. 끌리는 쪽이 반대편으로 옮겨 갔거든.',
        '① 위로 휘고, 음극선이 (−)전하를 띤다는 결론도 그대로다: 휘어짐이 전기장 때문인 한 '
        '극을 바꾸면 휘는 쪽도 반대로 가. 끌리는 쪽이 반대편으로 옮겨 갔거든.')
    sub(it, '③ 위로 휘고, 음극선이 (+)전하를 띤다는 결론으로 바뀐다: 극을 바꾸었는데 같은 '
            '쪽으로 휠 수는 없어. 결론도 바뀌지 않지 — 바뀐 것은 장치야.',
        '③ 위로 휘고, 음극선이 (+)전하를 띤다는 결론으로 바뀐다: 어긋난 것은 뒤가 아니라 '
        '앞이야. 정말로 위로 휘었다면 위쪽이 이제 (−)극이니 (+)전하라는 결론이 따라 나오긴 해. '
        '그런데 전기장이 원인인 한 그 관측 자체가 일어나지 않아.')

    for x in bank:
        assert '**' not in x['stem'] and '**' not in x['solution'], x['id']
        assert '★' not in x['stem'] and '★' not in x['solution'], x['id']

    json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('P13 10차 조치 완료 — 해설 문면 4')
    for i in (1928, 1932, 1934, 1935):
        print(f'  M0{i} 해설 {len(d[f"M0{i}"]["solution"])}자')


if __name__ == '__main__':
    main()
