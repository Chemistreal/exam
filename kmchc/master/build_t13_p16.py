    if REFERENT['아르곤의 원자 번호'] + 10 + 2 + 3 != REFERENT['비소의 원자 번호']:
        bad.append('지시 대상표 오류 — M02123 의 합이 어긋남')

    # ⑧ 정답 길이 순위 (G3c 예고) — ★동률은 세지 않고, 표본이 넷 미만이면 비율을 재지 않는다★
    ranks = []
    for x in items:
        ls = [len(c) for c in x['choices']]
        a = x['answer']
        if ls.count(ls[a]) > 1:
            continue
        ranks.append(sum(1 for v in ls if v > ls[a]) + 1)
