def toks(s):
    return {w for w in TOK.findall(s.replace('★C★', '')) if w not in STOP}


def crosscheck(rows, thr=0.55):
    """★모두 서로 맞댄다★ — 문턱을 넘는 짝을 돌려준다."""
    hits = []
    for i in range(len(rows)):
        for j in range(i + 1, len(rows)):
            a, b = toks(rows[i][1]), toks(rows[j][1])
            if not a or not b:
                continue
            s = len(a & b) / len(a | b)
            key = (rows[i][0], rows[j][0])
            if s >= thr and key not in ALLOW and (key[1], key[0]) not in ALLOW:
                hits.append((s, rows[i], rows[j]))
    return sorted(hits, reverse=True, key=lambda h: h[0])


