# -*- coding: utf-8 -*-
"""T14 P4 7차 조치 — 마감 앞의 두 낱말.

solver 0건 · defender F2 0건·교체 제안 0건 · factchecker 중대한 오류 0건.
6차에 고친 다섯 자리가 모두 제대로 앉았고, M02169 는 세 검증자가 각각
'① 여전히 거짓 · ④ 유일하게 참 · W 완화가 다른 선지를 되살리지 않음' 으로
확인했다. factchecker 는 ★수정 전이라면 깨졌을 비유(교재가 염소를 먼저
얻어 둔 것 ↔ W)가 수정으로 오히려 맞아떨어졌다★ 고 덧붙였다.

남은 것은 factchecker 가 '손대지 않아도 무방' 을 달아 올린 저확신 셋이다.
둘을 받고 하나를 기각한다 — 받는 둘은 뜻을 건드리지 않는 낱말 교체라
새 자국을 낼 여지가 없다.

★① 교과 밖 용어는 저확신으로 올라와도 받는다.★
  M02166 ④ 논박에 '배위수' 가 정의 없이 한 번 들어가 있었다. 화학I 에서
  다루지 않는 말이라 학생에게는 빈 낱말이고, 논박 자체는 발문이 준 여덟·
  여섯만으로 성립한다. '외운 이웃 수' 로 풀어 쓴다. ★확신도는 지적이 옳을
  가능성을 말할 뿐 지적의 무게를 말하지 않는다★ — 교과 밖은 이 대장의
  기준선이라 저확신으로 와도 조치한다.

★② 줄바꿈 자리에 넣은 공백이 낱말을 가른다.★
  M02172 본문의 '따라가면' 이 줄 끝 '따라 ' 와 다음 줄 '가면' 으로 갈려
  이어 붙이면 '따라 가면' 이 된다. 같은 문항 압축 줄은 '따라가면' 으로
  붙여 쓴다. 이어 붙인 문장에서만 보이는 흠이라 소스만 읽어서는 지나친다.
  ★문자열을 여러 줄로 나눌 때 공백은 낱말 경계에만 둔다.★

기각한 것 하나.
  factchecker: M02165 가 두 배의 조건을 둘('단일 결합' 과 '같은 원소')로
  걸어 놓고 본문에서는 '같은 원소' 만 확인한다(확신 낮음) — 발문이 '두 탄소
  원자가 단일 결합으로 이어져 있을 때' 라고 이미 못 박았고, factchecker
  스스로 '문항 고유의 결함이라기보다 배치 전체의 문체' 이며 '발문에 이미
  있다면 무시해도 된다' 고 적었다. 조건을 문장마다 되짚는 문체로 바꾸면
  해설이 늘어지기만 한다.
"""
import re

P = 'build_t14_p4.py'
src = open(P, encoding='utf-8').read()

R = [
    # ── M02166 교과 밖 용어를 풀어 쓴다 ─────────────────────────────────────
    ("              ('이웃 원자 열둘과의 핵 사이 거리', '외운 배위수를 발문이 준 짜임 위에 '",
     "              ('이웃 원자 열둘과의 핵 사이 거리', '외운 이웃 수를 발문이 준 짜임 위에 '"),
    ("          '④는 외운 배위수를 발문이 준 짜임 위에 얹었어. 이 결정은 가장 가까운 이웃이 '",
     "          '④는 외운 이웃 수를 발문이 준 짜임 위에 얹었어. 이 결정은 가장 가까운 이웃이 '"),

    # ── M02172 줄바꿈이 낱말을 가르던 자리 ──────────────────────────────────
    ("          '②는 세로줄과 가로줄을 뒤바꿔 읽었어. 족은 주기율표의 세로줄이라 원자 번호를 따라 '\n"
     "          '가면 띄엄띄엄 나타나지, 이어진 한 마디가 되지 않아. '",
     "          '②는 세로줄과 가로줄을 뒤바꿔 읽었어. 족은 주기율표의 세로줄이라 원자 번호를 '\n"
     "          '따라가면 띄엄띄엄 나타나지, 이어진 한 마디가 되지 않아. '"),
]

for a, b in R:
    n = src.count(a)
    assert n == 1, f'{n}곳: {a[:60]!r}'
    src = src.replace(a, b)

open(P, 'w', encoding='utf-8').write(src)

body = src[src.index('def build():'):]
body = '\n'.join(l for l in body.split('\n') if not l.strip().startswith('#'))
flat = re.sub(r"'\s*\n\s*'", '', body)

for w in ['배위수', '따라 가면']:
    assert w not in flat, f'물러난 문면이 남았다: {w}'
for w, k in [('외운 이웃 수', 2), ('따라가면', 2)]:
    n = flat.count(w)
    assert n == k, f'{w}: {n} ≠ {k}'

print('fix_t14_p4_r7 적용 완료 —', len(R), '곳')
