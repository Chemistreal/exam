def swap_choice(it, idx, new_txt, new_rebut, err, typ):
    mark = MK[idx]
    old = it['choices'][idx]
    assert idx != it['answer'], f"{it['id']}: 정답 자리는 이 헬퍼로 바꾸지 않는다"
    lines = it['solution'].split('\n')
    hit = [i for i, L in enumerate(lines) if L.startswith(f'{mark} {old}:')]
    assert len(hit) == 1, f"{it['id']}: 해설 {mark} 줄을 못 찾음"
    lines[hit[0]] = f'{mark} {new_txt}: {new_rebut}'
    it['solution'] = '\n'.join(lines)
    it['choices'][idx] = new_txt
    for dd in it['distractors']:
        if dd['opt'] == idx:
            dd['error'], dd['type'] = err, typ
            break
    else:
        raise AssertionError(f"{it['id']}: distractor {idx} 없음")


def swap_positions(it, i, j):
    """선지 두 자리를 문면 그대로 맞바꾼다 — 해설의 기호와 오답 주석까지 함께 옮긴다.
    정답 분포를 손볼 때 쓰는 유일한 안전한 길이다(문면을 새로 쓰면 검증이 처음부터다)."""
    ch = it['choices']
    ti, tj = ch[i], ch[j]
    sol = it['solution']
    ans = it['answer']
    assert ans in (i, j), f"{it['id']}: 정답이 맞바꿀 두 자리 밖에 있다"
    other = j if ans == i else i
    a_txt, o_txt = ch[ans], ch[other]

    head_old = f'[정답] {MK[ans]} {a_txt} —'
    line_old = f'{MK[other]} {o_txt}:'
    tail_old = f'— {MK[ans]}이 옳아' if MK[ans] in '①③' else f'— {MK[ans]}가 옳아'
    for s in (head_old, line_old, tail_old):
        assert s in sol, f"{it['id']}: 못 찾음 -> {s}"

    new_ans, new_other = other, ans
    head_new = f'[정답] {MK[new_ans]} {a_txt} —'
    line_new = f'{MK[new_other]} {o_txt}:'
    tail_new = f'— {MK[new_ans]}이 옳아' if MK[new_ans] in '①③' else f'— {MK[new_ans]}가 옳아'

    sol = sol.replace(head_old, '\x00', 1).replace(line_old, '\x01', 1).replace(tail_old, '\x02', 1)
    sol = sol.replace('\x00', head_new).replace('\x01', line_new).replace('\x02', tail_new)
    it['solution'] = sol

    ch[i], ch[j] = tj, ti
    it['answer'] = new_ans
    for dd in it['distractors']:
        if dd['opt'] == other:
            dd['opt'] = ans
    # 해설의 오답 줄이 ①②③④ 차례를 지키는가 (집안 규칙)
    order = [k for k in range(4) if k != it['answer']]
    pos = [it['solution'].index(f'{MK[k]} {ch[k]}:') for k in order]
    assert pos == sorted(pos), f"{it['id']}: 오답 줄 차례가 어긋났다"


