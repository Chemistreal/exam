    if left:
        print('\n  ❌ 저작 점검 실패')
        for b in left:
            print(f'     · {b}')
        raise SystemExit(1)
    if exited:
        print(f'  ✅ 저작 점검 통과 (⑪ 트랙만 마감 규모로 갈아 끼움 — 일반 {gc} · 심화 {ac})')

