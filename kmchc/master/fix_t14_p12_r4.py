    global body
    pat = re.compile(r'\s*\n\s*'.join(re.escape(t) for t in re.split(r'\s*\n\s*', old)))
    out, c = pat.subn(lambda m: new, body)
    assert c == n, f'{c}곳(기대 {n}) — {old[:44]!r}'
    body = out
    return out


