"""T12 P10 마감 — 개념 대장에 P10 10제 링크 + 대장 자체의 부채 두 건 처리

대장은 '무엇을 이미 썼나'와 '무엇을 쓰면 안 되나'를 함께 담는 자리다.
P9 에서 C12-026[3] 의 전제가 거짓이었고, P10 1차에서 C12-002[5] 의 "(돌턴만 별명 없음)"이
거짓이었다. ★대장도 틀린다.★ 이번에는 거짓은 없고 ★구조적 부채 둘★ 이 드러났다.

★부채1 — 같은 사실을 가리키는 각도가 둘이다★
  C12-026[4] "H 에는 노란·오렌지 구간(570~620 nm) 선이 없는데 Hg·Ne 에는 있다"
  C12-N04[9] "노란색·오렌지색 구간(약 570~620 nm)에는 수소 발머 선이 하나도 없다 [두 쪽 잇기]"
  두 각도가 사실상 같은 문항을 낳는다. M01904 를 [4] 에 링크하면 [9] 는 ★죽은 각도★ 가 된다
  (같은 문항을 또 내면 selfaudit 이 R1 충돌로 잡는다).
  ▸ [9] 를 ★남은 몫★ 으로 좁힌다. 75쪽 스펙트럼과 77쪽 색 사다리를 잇는 '두 쪽 잇기'가
    이 각도의 본래 값어치이므로, "수소에 없다"가 아니라 ★"그 구간이 무슨 색인지를 색
    사다리에서 독립으로 정한 뒤 스펙트럼과 대조한다"★ 로 각도를 옮긴다.

★부채2 — 전이 표기의 방향★
  C12-027[6] 이 "표에 없는 1→7 = 48/49 k 를 예측"이라 적혀 있다. 표는 준위 쌍의 차를
  담아 방향이 없지만(대각선이 비고 값이 21개뿐인 대칭표다), ★문항이 이 표기를 그대로
  베끼면 안 된다★ — P10 4차 순회에서 M01906 이 "n=1 로 떨어질 때 내놓는 에너지"라 해 놓고
  전이를 1→2, 1→7 로 적어 ★화살표가 뒤집힌 채★ 나갔다.
  ▸ 각도에 그 사유를 붙여 다음 배치가 같은 곳에서 넘어지지 않게 한다.
"""
import json, os

CJ = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'concepts.json')
THEME = '원자 모형'

# (개념 id, 각도 index, 문항 id)
LINK = [
    ('C12-002', 5, 'M01897'),   # 모형 별명 짝짓기
    ('C12-001', 2, 'M01898'),   # 동위원소가 뒤집은 명제는 전자 발견과 따로다
    ('C12-005', 3, 'M01899'),   # 자석(자기장)과 평행판(전기장)은 서로 다른 장치
    ('C12-010', 7, 'M01900'),   # 검출기를 360°로 두른 까닭 — 되튐까지 잡기 위해
    ('C12-N02', 2, 'M01901'),   # 1 C 은 전자 몇 개분인가
    ('C12-011', 4, 'M01902'),   # 안정한 원자의 증거 = 일정한 크기를 유지한다
    ('C12-015', 5, 'M01903'),   # 러더퍼드 한계 ①을 막는 가정과 ②를 막는 가정 가르기
    ('C12-026', 4, 'M01904'),   # 570~620 nm 에 H 만 선이 없다
    ('C12-N04', 6, 'M01905'),   # X선 파장이 원자 크기와 같은 자릿수
    ('C12-027', 6, 'M01906'),   # 1행이 (m²−1)/m² 꼴 — 표 밖의 값 외삽
]

# 부채1 — 중복 각도를 남은 몫으로 옮긴다
FIX_ANGLE = ('C12-N04', 9,
             '노란색·오렌지색 구간(약 570~620 nm)에는 수소 발머 선이 하나도 없다 [두 쪽 잇기]',
             '색 사다리로 570~620 nm 가 무슨 색인지 먼저 정한 뒤 75쪽 스펙트럼과 대조하기 '
             '[두 쪽 잇기]')
FIX_NOTE = ("★각도 정리(P10)★ 옛 [9]('570~620 nm 에 수소 선이 없다')는 C12-026[4] 와 "
            "★사실상 같은 각도★ 였다. M01904 가 C12-026[4] 로 나갔으므로 그대로 두면 죽은 "
            "각도가 된다(같은 문항을 또 내면 selfaudit 이 R1 충돌로 잡는다). "
            "이 각도의 본래 값어치는 77쪽 색 사다리와 75쪽 스펙트럼을 잇는 데 있으므로 "
            "★'없다'가 아니라 '색을 독립으로 정한 뒤 대조한다'★ 쪽으로 옮겼다.")

# 부채2 — 표기 방향에 대한 저작 주의
NOTE_027 = ("★저작 주의(P10)★ [6] 의 '1→7' 은 ★대칭표의 칸 이름★ 이지 전이 방향이 아니다"
            "(표는 준위 쌍의 차를 담아 대각선이 비고 서로 다른 값이 21개뿐이다). "
            "문항이 이 표기를 그대로 베끼면 안 된다 — M01906 이 'n=1 로 ★떨어질 때 내놓는★ "
            "에너지'라 해 놓고 전이를 1→2, 1→7 로 적어 화살표가 뒤집힌 채 나갔고 "
            "4차 순회에서야 잡혔다. ★내놓는 에너지를 물으면 m→1 로 적을 것.★")


def main():
    obj = json.load(open(CJ, encoding='utf-8'))
    C = obj[THEME]
    d = {c['id']: c for c in C}

    # 1. 중복 각도 정리
    cid, idx, old, new = FIX_ANGLE
    a = d[cid]['angles'][idx]
    assert a['a'] == old, f'{cid}[{idx}]: 대상 각도 어긋남 -> {a["a"]}'
    assert not a['by'], f'{cid}[{idx}]: 이미 소진된 각도라 함부로 못 고침 -> {a["by"]}'
    a['a'] = new
    d[cid]['note'] = (d[cid].get('note', '') + ' ' + FIX_NOTE).strip()

    # 2. 표기 방향 주의
    d['C12-027']['note'] = (d['C12-027'].get('note', '') + ' ' + NOTE_027).strip()

    # 3. 링크
    n = 0
    for cid, idx, mid in LINK:
        a = d[cid]['angles'][idx]
        assert mid not in a['by'], f'{cid}[{idx}]: {mid} 이미 링크됨'
        assert not a['by'], f'{cid}[{idx}]: 이미 소진된 각도 -> {a["by"]}'
        a['by'].append(mid)
        n += 1

    # ── 검증 ────────────────────────────────────────────────
    have = {b for c in C for x in c['angles'] for b in x['by']}
    p10 = [f'M0{i}' for i in range(1897, 1907)]
    missing = [m for m in p10 if m not in have]
    assert not missing, f'대장 미링크 잔존: {missing}'
    dup = [m for m in p10 if sum(1 for c in C for x in c['angles'] for b in x['by'] if b == m) != 1]
    assert not dup, f'중복 링크: {dup}'
    free = sum(1 for c in C for x in c['angles'] if not x['by'])
    total = sum(len(c['angles']) for c in C)

    json.dump(obj, open(CJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'P10 대장 링크 {n}건 · 중복 각도 1건 정리 · 저작 주의 1건 추가')
    print(f'  개념 {len(C)}개 · 각도 {total}개 · 미소진 {free}개 (잔여 64제)')


if __name__ == '__main__':
    main()
