        '물음마다 자료가 닿는지 표를 해 세어 본다.',
        {'넷 모두 답할 수 있어 네 물음이 열린다': '이름은 못 가.',
         '원자가전자 수 하나만 답할 수 있게 된다': '족도 나와.',
         '넷 가운데 어느 것도 답할 수 없게 된다': '둘은 나와.'},
