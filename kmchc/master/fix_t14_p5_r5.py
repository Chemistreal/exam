"""T14 P5 5차 조치 — 발문이 두 낱말을 섞어 쓰면 오답 하나가 그 틈으로 들어온다.

solver ★0건★ ("마감을 막아야 할 자리 없음") · defender ★F2 0건 · 교체 제안
없음 · 마감에 이견 없음★ · factchecker 1건(조건부, 확신 0.55).
한 문항만 고친다.

★① M02179 가 요건을 두 낱말로 적고 있었다.★
  발문 첫 문장은 '전자 수 하나만 ★달라진★ 자리를 찾으려 한다', 물음은 '전자
  수만 ★늘어난★ 짝은 어느 것인가' 다. skill·본문 첫 문장·자가진단도 '달라짐'
  쪽이고, ② 논박만 방향까지 요구한다 — factchecker 가 ★네 자리와 한 자리가
  갈려 있다★ 고 짚었다(자기가 발문을 볼 수 없어 조건부로 올렸는데, 조건이
  실제로 성립한다).
  ▸ 이것이 낱말 고르기 문제가 아닌 까닭: ★첫 문장만 읽으면 ②(양이온)도 '전자
    수가 달라진' 짝이다.★ 물음의 '늘어난' 하나가 유일한 방어선이었다.
  ▸ '늘어남' 쪽으로 통일했다. 요건을 좁히는 쪽이 안전하고, 요인 3 이 홀로
    작동하는 자리(같은 원소의 원자와 그 음이온)와도 정확히 맞는다.
  ▸ 규약: ★요건을 적는 낱말은 발문·skill·본문·압축 줄·자가진단 다섯 자리에서
    같아야 한다.★ 4차에 '한 주장을 고칠 때 다섯을 한 묶음으로 센다' 를 세웠는데,
    ★고칠 때만이 아니라 처음 쓸 때부터 다섯을 맞춘다.★

★② ② 논박의 결정적 근거를 가정형에서 단정형으로 옮겼다.★
  '전자를 잃으면 … 가장 바깥 껍질이 통째로 빌 수도 있어서 껍질 수까지 달라질
  수 있지' — ★② 를 배제하는 근거가 가정형에 걸려 있었다★(factchecker).
  방향("전자를 잃으면 전자 수가 줄어드니 늘어난 짝이 아니다")은 가정 없이
  단정할 수 있으므로 그것을 앞에 세우고, 껍질 이야기는 뒤에 덧붙였다.

받지 않은 것 하나 — factchecker 가 ★"고치지 마십시오" 로 명시★ 했다.
  M02178 자가진단의 '중성 원자라면' 은 M02175 에서 뺀 것과 성격이 다르다.
  그 문장은 껍질이 열리는 자리를 ★주기의 경계★ 로 지목하므로 껍질 수 = 주기
  번호를 쓰고 있고, 그 등식은 중성 원자에서만 참이다. 떼면 거짓이 된다.
  ▸ ★같은 낱말이라도 그 문장이 무엇을 떠받치는지에 따라 값이 다르다★ —
    4차에 M02175 에서 뺀 것은 우세 주장에 얹힌 군더더기였고, 여기 것은 등식을
    떠받치는 한정어다. 검증자가 오탐을 미리 막아 준 자리라 그대로 적어 둔다.

기각한 것 둘(둘 다 확신 낮음, 제안자가 마감 보류 사유가 아니라고 적었다).
  ㄱ) solver: M02176 ④('한 몸으로 움직인다')와 M02181 ③('늘 함께 나타난다')의
     ★정답 어휘 패턴 반복★ — 묻는 두 요인 쌍이 서로 다르므로(껍질+전자 vs
     양성자+전자) 내용 누설이 아니고 형식 패턴에 그친다. 세트 조립 규약에 이미
     들어 있다.
  ㄴ) solver: M02182 의 선지 톤 편차(①③④ 가 강한 오류 주장이고 ② 만 온건한
     구분 진술) — 오답이 명백히 틀린 진술인 것은 4지선다의 정상 상태이고,
     ② 를 고르려면 '방향 대 대소' 라는 내용 판단이 여전히 필요하다.
"""
import re

P = 'build_t14_p5.py'
src = open(P, encoding='utf-8').read()

R = [
    ("    # ── M02179 ── C14-008[3] 전자 수만 달라지는 자리 (심화·중간) 정답 ① ──",
     "    # ── M02179 ── C14-008[3] 전자 수만 늘어나는 자리 (심화·중간) 정답 ① ──\n"
     "    #   ★5차에 요건의 낱말을 '늘어남' 으로 통일했다★ — 발문 첫 문장이 '달라진' 이라\n"
     "    #   그 문장만 읽으면 양이온도 '전자 수가 달라진' 짝이 되었다. 물음의 '늘어난'\n"
     "    #   하나가 유일한 방어선이었다."),
    ("    x = T.mk('M02179', '전자 수만 홀로 달라지는 비교 자리를 고르기',",
     "    x = T.mk('M02179', '전자 수만 홀로 늘어나는 비교 자리를 고르기',"),
    ("             '전자 수 하나만 달라진 자리를 찾으려 한다. 껍질 수와 양성자 수는 그대로이고 '",
     "             '전자 수 하나만 늘어난 자리를 찾으려 한다. 껍질 수와 양성자 수는 그대로이고 '"),
    ("             '전자 수만 달라지는 자리',",
     "             '전자 수만 늘어나는 자리',"),
    ("          '전자 수 하나만 달라진 자리를 찾는 것이니, 나머지 둘이 그대로인 짝을 골라야 해. '",
     "          '전자 수 하나만 늘어난 자리를 찾는 것이니, 나머지 둘이 그대로인 짝을 골라야 해. '"),
    ("          '②는 전자를 잃는 쪽과 얻는 쪽을 뒤집었어. 전자를 잃으면 전자 수가 줄지 늘지 않고, '\n"
     "          '게다가 가장 바깥 껍질이 통째로 빌 수도 있어서 껍질 수까지 달라질 수 있지. 물음이 '\n"
     "          '요구한 것과 두 군데가 어긋나. '",
     "          '②는 전자를 잃는 쪽과 얻는 쪽을 뒤집었어. 전자를 잃으면 전자 수가 줄어드니 '\n"
     "          '늘어난 짝이 아니야. 게다가 가장 바깥 껍질이 통째로 비면 껍질 수까지 달라지지. '"),
    ("          {'어떤 원자와 그 원자가 전자를 잃어 만든 양이온': '전자를 잃으면 전자 수가 줄고 '\n"
     "                                                          '껍질 수까지 달라질 수 있어.',",
     "          {'어떤 원자와 그 원자가 전자를 잃어 만든 양이온': '전자를 잃으면 전자 수가 '\n"
     "                                                          '줄어들어 늘어난 짝이 아니야.',"),
    ("          '전자 수만 홀로 달라지는 자리는 같은 원소의 원자와 그 음이온이다.')",
     "          '전자 수만 홀로 늘어나는 자리는 같은 원소의 원자와 그 음이온이다.')"),
]

for a, b in R:
    n = src.count(a)
    assert n == 1, f'{n}곳: {a[:50]!r}'
    src = src.replace(a, b)

open(P, 'w', encoding='utf-8').write(src)

body = src[src.index('def build():'):]
body = '\n'.join(l for l in body.split('\n') if not l.strip().startswith('#'))

BAN_AFTER = [
    '전자 수 하나만 달라진 자리',
    '전자 수만 홀로 달라지는',
    '전자 수만 달라지는 자리',
    '전자 수가 줄지 늘지 않고',
    '물음이 요구한 것과 두 군데가',
]
for w in BAN_AFTER:
    assert w not in body, f'물러난 문면이 남았다: {w}'

flat = re.sub(r"'\s*\n\s*'", '', body)
for w, k in [('전자 수 하나만 늘어난 자리', 2),
             ('전자 수만 홀로 늘어나는', 2),
             ('전자 수만 늘어나는 자리', 1),
             ('늘어난 짝이 아니야', 2)]:
    n = flat.count(w)
    assert n == k, f'{w}: {n} ≠ {k}'

print('fix_t14_p5_r5 적용 완료 —', len(R), '곳')
