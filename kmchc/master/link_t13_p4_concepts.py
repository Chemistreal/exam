def main():
    obj = json.load(open(CJ, encoding='utf-8'))
    C = obj[THEME]
    d = {c['id']: c for c in C}

    for cid, note in (('C13-009', NOTE_009), ('C13-007', NOTE_007), ('C13-018', NOTE_018),
                      ('C13-015', NOTE_015), ('C13-023', NOTE_023), ('C13-005', NOTE_005),
                      ('C13-011', NOTE_011), ('C13-021', NOTE_021), ('C13-003', NOTE_003),
                      ('C13-014', NOTE_014)):
        d[cid]['note'] = (d[cid].get('note', '') + ' ' + note).strip()

    n = 0
    for cid, idx, mid in LINK:
        a = d[cid]['angles'][idx]
        assert not a['by'], f'{cid}[{idx}]: 이미 소진된 각도 -> {a["by"]}'
        a['by'].append(mid)
        n += 1

    have = {b for c in C for x in c['angles'] for b in x['by']}
    fin = [f'M0{i}' for i in range(2001, 2011)]
    missing = [m for m in fin if m not in have]
    assert not missing, f'대장 미링크 잔존: {missing}'
    dup = [m for m in fin if sum(1 for c in C for x in c['angles'] for b in x['by'] if b == m) != 1]
    assert not dup, f'중복 링크: {dup}'
    free = sum(1 for c in C for x in c['angles'] if not x['by'])
    total = sum(len(c['angles']) for c in C)

    json.dump(obj, open(CJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'T13 P4 대장 링크 {n}건 · 저작 주의 10건 추가')
    print(f'  개념 {len(C)}개 · 각도 {total}개 · 소진 {total - free}개 · 미소진 {free}개')


if __name__ == '__main__':
    main()
