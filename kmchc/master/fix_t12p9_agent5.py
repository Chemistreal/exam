    solution=(
        "한 실험이 어디까지 떠받칠 수 있는지를 재는 문항이야.\n\n"
        "[정답] ④ 원자 질량의 대부분이 한곳에 몰려 있다는 것 — 질량이 한곳에 몰려 있다는 것은 알파 입자를 쏘아 "
        "크게 되튀는 것을 본 뒤에야 나온 결론이고, 그 결론이 나온 것은 이 실험보다 열네 해 뒤의 일이야 — ④가 옳아. "
        "음극선관이 떠받치는 것은 여기까지야. 금속을 바꿔도 같은 알갱이가 나왔으니 그 알갱이는 금속의 종류를 타지 "
        "않고, 그 알갱이가 금속을 이루는 원자에서 떨어져 나온 것이니 원자는 더 쪼갤 수 없는 것이 아니며, (+)극 "
        "쪽으로 휘었으니 부호는 (−)지. 실험 하나를 읽을 때는 '무엇이 관찰됐나'와 '그것이 무엇까지 말해 주나'를 "
        "갈라 두어야 해. 뒤엣것을 넉넉히 잡으면 다른 실험의 공을 가져다 쓰게 돼.\n\n"
        "① 원자가 더 쪼갤 수 없는 것이 아니라는 것: 어떤 금속에서든 알갱이가 떨어져 나왔으니, 원자를 더 쪼갤 수 "
        "없다던 생각은 이것으로 무너져.\n"
        "② 그 알갱이가 금속의 종류와 상관없이 같다는 것: 금속을 바꿔도 같은 알갱이가 나온 것이 근거지.\n"
        "③ 그 알갱이가 (−)전하를 띠고 있다는 것: (+)극 쪽으로 휘었다는 것이 부호를 말해 줘.\n\n"
        "자가진단: 이 실험이 닿는 데까지만. 질량 집중은 열네 해 뒤의 결론."),
