import ast, io, sys

SRC = 'build_t15_p3.py'
BEFORE = io.open(SRC, encoding='utf-8').read()
body = BEFORE
log = []


def rep(old, new, expect=None):
    global body
    c = body.count(old)
    assert c > 0, '0곳: %r' % old[:60]
    if expect is not None:
        assert c == expect, '%d곳 (기대 %d)' % (c, expect)
    body = body.replace(old, new)
    log.append('%d곳 %s' % (c, old[:24]))


# ════ B1 M02323 ④ — 반박이 '밑바닥' 을 치는데 새 ④ 에는 그 말이 없다 ════
rep("'④는 3주기의 두 값이 2주기의 두 값보다 모두 커서 아래로 갈수록 커진다 라고 했어. 2주기의 '\n"
    "          '최솟값은 리튬 520 이고 3주기의 최솟값은 나트륨 496 이라 13족은 어느 주기에서도 '\n"
    "          '밑바닥이 아니고, 밑바닥이라는 말로는 이웃보다 작아진 까닭도 되지 못해. '",
    "'④는 3주기의 두 값이 2주기의 두 값보다 모두 커서 아래로 갈수록 커진다 라고 했어. 738 은 '\n"
    "          '900 보다, 578 은 801 보다 작으니 3주기 쪽이 오히려 작아 — 같은 족에서 아래로 가면 '\n"
    "          '값은 작아지지. '")
rep("'3주기의 두 값이 2주기의 두 값보다 모두 커서 아래로 갈수록 커진다': '1족이 더 작아.'",
    "'3주기의 두 값이 2주기의 두 값보다 모두 커서 아래로 갈수록 커진다': '3주기 쪽이 더 작아.'")
rep("④ 3주기의 최솟값은 알루미늄 578 이 아니라 '\n             '나트륨 496 이므로 거짓",
    "④ 738 < 900 이고 578 < 801 이라 3주기 쪽이 '\n             '오히려 작으므로 거짓")

# ════ B2 M02326 ④ — 반박이 옛 '자료만으로는' 을 치고, 새 ④ 의 전제를 거들어 준다 ════
rep("'④는 껍질 수가 같으므로 값의 차이는 원자가전자 수가 낸 것이다 라고 했어. 자료에는 값 둘만 있는 것이 '\n"
    "          '아니라 껍질이 같다는 문장도 있으니 요인 하나가 이미 지워져 있지. '",
    "'④는 껍질 수가 같으므로 값의 차이는 원자가전자 수가 낸 셈이 된다 라고 했어. 같은 껍질에 '\n"
    "          '전자가 하나 더 들어도 그 전자는 가려막기를 잘 하지 못해 값을 끌어올리지 못해. '\n"
    "          '벌어진 것은 양성자 11 과 17 이고, 차이를 낸 것은 그것이 키운 유효 핵전하야. '")
rep('껍질 수가 같으므로 값의 차이는 원자가전자 수가 낸 것이다',
    '껍질 수가 같으므로 값의 차이는 원자가전자 수가 낸 셈이 된다')
rep("④ 발문이 껍질을 같다고 적어 요인 하나가 '\n             '이미 지워졌으므로 정할 수 있음",
    "④ 같은 껍질의 전자는 가려막기를 잘 하지 못해 '\n             '값을 끌어올리지 못함")

# ════ B3 M02327 ④ — 반박이 '크기' 를 치는데 새 ④ 는 '방향' 을 틀리게 말한다 ════
rep("'④는 두 경향이 같은 쪽으로 겹쳐 더해지므로 대소가 정해지지 않는다 라고 했어. 크기는 주어지지 '",
    "'④는 두 경향이 같은 쪽으로 겹쳐 더해지므로 대소가 정해지지 않는다 라고 했어. 오른쪽으로 '")
rep("'두 경향이 같은 쪽으로 겹쳐 더해지므로 대소가 정해지지 않는다': '크기는 주어지지 않았어.'",
    "'두 경향이 같은 쪽으로 겹쳐 더해지므로 대소가 정해지지 않는다': '둘은 반대쪽으로 밀어.'")

# ════ B4 M02328 ③ — 반박이 '방향을 지웠다' 인데 새 ③ 은 방향을 거꾸로 잡았다 ════
rep("'③은 경향으로 보아 질소보다 클 것으로 보이나 값은 정해지지 않는다 라고 했어. 방향까지 함께 지운 '\n"
    "          '거야. '",
    "'③은 경향으로 보아 질소보다 클 것으로 보이나 값은 정해지지 않는다 라고 했어. 탄소는 질소보다 '\n"
    "          '원자 번호가 작으니 경향이 가리키는 쪽은 질소보다 작은 쪽이야 — 방향을 거꾸로 잡았지. '")
rep("'경향으로 보아 질소보다 클 것으로 보이나 값은 정해지지 않는다': '방향까지 지웠어.'",
    "'경향으로 보아 질소보다 클 것으로 보이나 값은 정해지지 않는다': '방향이 거꾸로야.'")
