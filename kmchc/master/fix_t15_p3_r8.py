GONE = ['밑바닥이라는 말', "'1족이 더 작아.'", '자료에는 값 둘만 있는 것이',
        '크기는 주어지지 않았', '방향까지 함께 지운', '방향까지 지웠어',
        '오른쪽으로 갈수록 '"'\n                                          '작아져.'",
        '원자가전자 수가 낸 것이다', '③ 방향까지 지움']
