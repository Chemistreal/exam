    swap_choice(d['M01948'], 1, '가벼운 바람개비가 잘 돌아간다 — 음극선은 직선으로 나아간다',
                '뒷짝 자체는 참이야. 하지만 곧게 나아간다는 것을 밝힌 것은 앞에 물체를 놓아 '
                '그림자를 본 실험이지. 바람개비가 준 것은 운동량을 나른다는 사실이야.',
                '뒷짝이 참이니 짝도 맞다고 봄 — 직진을 밝힌 것은 그림자 실험이다', 'proc')

    # ══ M01949 ─ 정답 ① 을 단정형으로, 칸 이름이 방향을 담음을 문면에 ═════
    it = d['M01949']
    set_answer_text(it, '표에 적힌 값은 차의 크기이고 방향은 칸 이름이 말해 준다')
    sub(it, '표는 그 양의 크기만 적으니 한 칸을 보고 흡수인지 방출인지는 알 수 없어 — ①이 옳아.',
        '표에 적힌 수는 그 크기 하나뿐이야. 그러니 수만 보고는 흡수인지 방출인지 가릴 수 없지. '
        '방향을 말해 주는 것은 그 수가 아니라 3 → 5 냐 5 → 3 이냐 하는 칸 이름이야 — ①이 옳아.')
    sub(it, '준위 값은 Eₙ = −1312/n² 이라 모두 음수이고',
        '수소의 준위 값은 Eₙ = −1312/n² 이라 모두 음수이고')
    sub(it, '준위 값은 −1312/n² 로 모두 음수지', '수소의 준위 값은 −1312/n² 로 모두 음수지')
    sub(it, '자가진단: 표는 차의 크기만 담는다. 방향도 준위 값도 아니다.',
        '자가진단: 표의 수는 차의 크기. 방향은 칸 이름이 말해 준다.')
