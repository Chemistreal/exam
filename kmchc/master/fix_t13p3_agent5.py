bank = json.load(open(BANK, encoding='utf-8'))
by = {x['id']: x for x in bank}
before_ans = {i: by[f'M0{i}']['answer'] for i in range(1991, 2001)}
untouched = {i: json.dumps(by[f'M0{i}']['choices'], ensure_ascii=False)
             for i in range(1991, 2001) if i != 1996}


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:40]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


# ══ M01996 ③ ── 거짓을 주절로 되돌린다 (defender 중 · solver) ═══════════
x = by['M01996']
old3 = '주껍질 번호가 4 이면 g 오비탈이 있으나 채워지지는 않는다'
new3 = '채워지지는 않지만 주껍질 번호가 4 인 껍질에도 g 오비탈은 있다'
assert x['choices'][2] == old3, x['choices'][2]
x['choices'][2] = new3
x['solution'] = x['solution'].replace(old3, new3)
assert len(set(x['choices'])) == 4

# ══ M01991 ── '한 칸 먼저' 의 기준을 밝힌다 (factchecker △) ═════════════
sub(by['M01991'],
    '원소로 보면 3d 가 처음 열 개로 꽉 차는 것은 구리인데 구리는 예외 배치라 한 칸 먼저 찬 '
    '것이고, 3d 블록은 아연까지 이어져.',
    '원소로 보면 쌓음원리대로라면 3d 가 처음 꽉 차는 것은 아연이어야 하는데, 구리가 예외 '
    '배치라 한 원소 먼저 3d¹⁰ 이 돼. 어느 쪽이든 3d 블록이 아연에서 끝나는 것은 같아.')

# ══ M01992 ── ㉠ 계를 앞으로 + 중복 문장 정리 (factchecker 우선) ════════
