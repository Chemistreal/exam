assert Counter(seq) == Counter({0: 3, 1: 3, 2: 2, 3: 2}), dict(Counter(seq))
for i in range(1991, 2001):
    z = by[f'M0{i}']
    assert z['answer'] == before_ans[i], f'M0{i}: 정답 자리가 바뀌었다'
    if i in untouched:
        assert json.dumps(z['choices'], ensure_ascii=False) == untouched[i], \
            f'M0{i}: 손대지 않기로 한 문항인데 선지가 바뀌었다'
    assert len(z['choices']) == 4 and len(set(z['choices'])) == 4, z['id']
    assert {d['opt'] for d in z['distractors']} == {0, 1, 2, 3} - {z['answer']}, z['id']
    assert len(z['solution']) >= 300, (i, len(z['solution']))
    assert '★' not in z['solution'] and '★' not in z['stem'], f'M0{i}: G10 강조 표기'
    L = [len(c) for c in z['choices']]
    a = z['answer']
    assert not (L[a] == max(L) and L.count(max(L)) == 1), (i, 'G3 유일최장', L)
    assert not (L[a] == min(L) and L.count(min(L)) == 1), (i, 'G3 유일최단', L)
    s = sorted(L)
    if (s[1] + s[2]) / 2 >= 8:
        sp = (s[3] - s[0]) / ((s[1] + s[2]) / 2)
        assert sp <= 0.25, (i, f'G3b {sp:.2f}', L)
    head = z['solution'].split('\n\n')[1]
    assert (MK[a] + '가 옳아' in head) or (MK[a] + '이 옳아' in head), z['id']
    for k in range(4):
        assert (MK[k] + ' ' + z['choices'][k]) in z['solution'], (z['id'], k)
    assert z.get('objective'), z['id']

