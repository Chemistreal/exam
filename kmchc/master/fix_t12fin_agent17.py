# -*- coding: utf-8 -*-
"""T12 마감 14제(M01957~M01970) 층5 순회 — 17차 조치.

16차 defender: **정답 붕괴 0 · 오답 승격 0.** 다만 하나를 '이 14 문항 중
유일한 실질 리스크' 로 올렸다.

────────────────────────────────────────────────────────────────
M01961 ③ — 교과서 관용 서술로 읽으면 참이 될 여지가 남는다
────────────────────────────────────────────────────────────────
15차에 ③ 을 '모여드는 자리에 놓인 선이 파장이 가장 짧은 선이다' 로 놓았다.
엄밀히는 거짓이다 — 364.4 nm 는 선들의 집적점이고 n = ∞ 는 속박 준위가
아니므로 그 자리에 이산선이 없다. 그런데 **한국 교과서가 '계열 한계 = 그
계열에서 가장 짧은 파장' 이라고 자주 서술한다.** 그 관용을 근거로 "한계도
선으로 친다" 고 읽으면 ③ 이 참이 된다(defender 16차).

오답은 거짓이면서 매력적이어야 하고, **참으로 읽힐 여지가 남으면 그것이
최악의 결함**이다. 중재 규칙상 이 한 건만으로 조치 대상이다.

solver 도 같은 자리를 1 순위로 올리면서 조건 하나를 더 붙였다 —
**③ 이 '모여드는 자리' 라는 말을 쓰는 한 그 말 자체가 정답 ① 의 핵심
주장(수렴한다)을 확인해 준다.** 곧 새 ③ 은 수렴을 전제하지 않는 문장이어야
한다. 처음 고쳐 쓴 '모여드는 자리보다 더 짧은 쪽에도 …' 는 이 조건에
걸려 폐기했다.

→ ③ 을 '선이 짧은 파장 쪽으로 끝없이 이어져 0 에 다가간다' 로 한다.
선이 무한히 많다는 것은 맞지만 파장은 0 이 아니라 계열 한계 364.4 nm 로
모인다. 어떤 관용 서술로도 참이 될 수 없고, 수렴이라는 말을 쓰지 않으므로
① 을 확인해 주지도 않는다. '무한히 많으면 끝까지 간다' 는 실재하는 오해다.

이제 네 선지가 두 축을 이룬다.
    ①②③ = 짧은 파장 쪽에서 어떻게 되는가 (모여든다 / 벌어진다 / 0 까지 간다)
    ④     = 긴 파장 쪽으로도 이어지는가
논리적 포함 관계가 없고, 대칭쌍도 서지 않는다.

★잃은 것도 적어 둔다★ — '계열 한계는 극한이지 선이 아니다' 라는 구분이
이 문항에서 빠졌다. 같은 구분은 15차에 M01967 ④(파셴 최장선 1874.1 nm 를
한계로 착각)가 다른 각도로 떠맡고 있으므로 배치 안에서는 유지된다.

★교훈★ **엄밀히 거짓인 것과 교과서 관용으로 읽어도 거짓인 것은 다르다.**
오답을 검사할 때 "이 문장이 참이 되는 독법이 있는가" 에 **교과서가 흔히
쓰는 느슨한 서술**까지 넣어야 한다. 이 배치에서 같은 유형이 세 번 나왔다
— M01966 ④(다전자 원자로 넓히면 참), M01961 옛 ③(비로 읽으면 참),
그리고 이번(관용 서술로 읽으면 참).
"""
import json

BANK = 'master/master_bank.json'
MK = ['①', '②', '③', '④']

bank = json.load(open(BANK, encoding='utf-8'))
by = {x['id']: x for x in bank}


def parts(it):
    lines = it['solution'].split('\n')
    lead = lines[0]
    diag = [L for L in lines if L.startswith('자가진단:')][0]
    a = it['answer']
    head = f'[정답] {MK[a]} {it["choices"][a]} — '
    hit = [L for L in lines if L.startswith('[정답] ')]
    assert len(hit) == 1 and hit[0].startswith(head), it['id']
    cor = hit[0][len(head):]
    reb = {}
    for k in range(4):
        if k == a:
            continue
        pfx = f'{MK[k]} {it["choices"][k]}: '
        h = [L for L in lines if L.startswith(pfx)]
        assert len(h) == 1, (it['id'], k)
        reb[k] = h[0][len(pfx):]
    return lead, cor, reb, diag


def emit(it, lead, cor, reb, diag):
    a = it['answer']
    body = [lead, '', f'[정답] {MK[a]} {it["choices"][a]} — {cor}', '']
    body += [f'{MK[k]} {it["choices"][k]}: {reb[k]}' for k in range(4) if k != a]
    body += ['', diag]
    it['solution'] = '\n'.join(body)


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:40]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


def field(it, key, old, new):
    assert it[key].count(old) == 1, (it['id'], key)
    it[key] = it[key].replace(old, new)


def dmeta(it, idx, error=None, typ=None):
    for dd in it['distractors']:
        if dd['opt'] == idx:
            if error:
                dd['error'] = error
            if typ:
                dd['type'] = typ
            return
    raise AssertionError(f"{it['id']}: distractor {idx} 없음")


def retext(it, idx, new_txt, new_reb=None):
    assert idx != it['answer'], it['id']
    lead, cor, reb, diag = parts(it)
    it['choices'][idx] = new_txt
    if new_reb is not None:
        reb[idx] = new_reb
    emit(it, lead, cor, reb, diag)


def audit(it):
    lead, cor, reb, diag = parts(it)
    a = it['answer']
    for k in range(4):
        if k == a:
            continue
        for tail in ('가 옳아', '이 옳아', '가 맞아', '이 맞아'):
            assert MK[k] + tail not in cor, f"{it['id']}: 정답 본문에 {MK[k]}{tail}"
    assert (MK[a] + '가 옳아' in cor) or (MK[a] + '이 옳아' in cor), f"{it['id']}: 정답 번호 미표시"


def g3(it):
    L, a = [len(c) for c in it['choices']], it['answer']
    assert not (L[a] == max(L) and L.count(max(L)) == 1), f"{it['id']}: G3 유일최장"
    assert not (L[a] == min(L) and L.count(min(L)) == 1), f"{it['id']}: G3 유일최단"
    s = sorted(L)
    if (s[1] + s[2]) / 2 >= 8:
        sp = (s[3] - s[0]) / ((s[1] + s[2]) / 2)
        assert sp <= 0.25, f"{it['id']}: G3b 산포 {sp:.2f}"
    return L, sorted(range(4), key=lambda i: -L[i]).index(a) + 1


it = by['M01961']
retext(it, 2, '선이 짧은 파장 쪽으로 끝없이 이어져 0 에 다가간다',
       '선이 무한히 많다는 데까지는 맞아. 그런데 출발이 아무리 높아도 전이 에너지가 k/4 를 '
       '넘지 못하니 파장은 0 이 아니라 계열 한계에서 멎어. 개수가 끝이 없다고 값도 끝까지 '
       '가는 것은 아니지.')
dmeta(it, 2, error='선이 무한히 많으니 파장도 끝까지 작아진다고 보아 0 으로 수렴한다고 함',
      typ='scale')
sub(it, '둘째, 계열 한계는 선들이 한없이 다가가는 값이지 거기에 선이 하나 놓여 있는 것이 '
        '아니야. 다가가되 닿지는 않으니 "가장 짧은 선" 이라는 것도 없지.',
    '둘째, 선은 한계에 다가가되 넘지는 못해. 출발이 아무리 높아도 전이 에너지가 k/4 를 '
    '넘을 수 없으니 한계보다 짧은 파장 쪽에는 발머 선이 없지.')
field(it, 'answer_proof',
      '선은 무한히 많고 가장 짧은 선은 따로 없으며, 계열 한계는 선들이 한없이 다가가되 '
      '닿지 않는 극한이지 실제로 나오는 한 개의 선이 아니다',
      '선은 무한히 많지만 전이 에너지가 k/4 를 넘지 못하므로 계열 한계보다 짧은 파장 쪽에는 '
      '발머 선이 놓이지 않고, 긴 쪽으로도 최장선 3 → 2 의 656 nm 를 넘어서는 선이 없다')

