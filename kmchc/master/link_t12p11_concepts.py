"""T12 P11 마감 — 개념 대장에 P11 10제 링크 + 각도에 저작 주의 둘

P10 에서는 대장의 ★중복★ 이 드러났고, P9·P10 1차에서는 각도의 ★전제가 거짓★ 이었다.
P11 에서는 거짓도 중복도 없었다. 대신 순회가 드러낸 ★저작 주의★ 둘을 각도에 새긴다.

★주의1 — C12-042(광자 수) : '세기'를 정의하지 않으면 문항이 무너진다★
  M01914 를 만들며 "같은 세기의 빛을 같은 시간 동안"이라 적었는데, 3차 순회에서
  ★'세기'가 정의되지 않았다★ 는 지적이 나왔다. 세기를 단위 시간당 ★광자 수★ 로 읽으면
  파장을 바꿔도 개수가 그대로여서 오답 하나가 참이 된다. 이 각도를 쓸 때는
  ★"세기는 단위 시간에 건네는 에너지로 잰다"를 문면에 놓을 것.★

★주의2 — C12-016(전자껍질) : 대응표를 발문에 적으면 문항이 사라진다★
  M01907 은 발문이 "K, L, M, N ↔ n = 1, 2, 3, 4"를 통째로 적어 두어
  ★화학을 하나도 몰라도 순서만 세면 풀렸다.★ 1차에 앵커 하나만 남겼는데도 대응표가
  복원되어 2차에 아예 걷어냈다. 이 각도가 재려는 것이 바로 그 대응이므로
  ★대응은 학생이 알고 있어야 할 것이지 발문이 줄 것이 아니다.★
"""
import json, os

CJ = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'concepts.json')
THEME = '원자 모형'

# (개념 id, 각도 index, 문항 id)
LINK = [
    ('C12-016', 0, 'M01907'),   # 껍질 기호와 n 값의 대응
    ('C12-022', 1, 'M01908'),   # 계열과 전자기파 영역 — 영역 이름이 기구를 정하지 않는다
    ('C12-013', 1, 'M01909'),   # 양성자 수에서 세운 헬륨 질량 예상
    ('C12-033', 0, 'M01910'),   # 되튐 빈도의 희소성이 뜻하는 것
    ('C12-N01', 0, 'M01911'),   # 불확정성 원리 — '동시에'가 빠지면 틀림
    ('C12-029', 0, 'M01912'),   # 전이표의 대각선이 비어 있는 까닭
    ('C12-019', 1, 'M01913'),   # 에너지 비에서 파장 비·진동수 비
    ('C12-042', 1, 'M01914'),   # 같은 에너지라도 광자 수는 파장에 비례
    ('C12-018', 8, 'M01915'),   # 방출만 그린 준위도에 흡수를 더하면
    ('C12-027', 2, 'M01916'),   # n→∞ 가 뜻하는 것(이온화)
]

NOTE_042 = ("★저작 주의(P11)★ 이 각도를 문항으로 만들 때는 ★'세기'를 반드시 정의할 것.★ "
            "M01914 가 '같은 세기의 빛을 같은 시간 동안'이라고만 적었더니, 세기를 단위 시간당 "
            "★광자 수★ 로 읽는 독법에서 '개수가 그대로다'라는 오답이 참이 됐다. "
            "'빛의 세기는 단위 시간에 건네는 에너지로 잰다'를 문면에 놓아야 총 에너지가 고정된다.")

NOTE_016 = ("★저작 주의(P11)★ 껍질 이름과 n 의 대응을 ★발문에 적지 말 것.★ "
            "M01907 은 발문이 대응표를 통째로 주어 화학 없이 순서만 세면 풀렸다. "
            "1차에 'K 가 n = 1' 앵커 하나만 남겼는데도 대응표가 복원돼 2차에 아예 걷어냈다. "
            "★이 각도가 재려는 것이 그 대응 자체다.★")


def main():
    obj = json.load(open(CJ, encoding='utf-8'))
    C = obj[THEME]
    d = {c['id']: c for c in C}

    for cid, note in (('C12-042', NOTE_042), ('C12-016', NOTE_016)):
        d[cid]['note'] = (d[cid].get('note', '') + ' ' + note).strip()

    n = 0
    for cid, idx, mid in LINK:
        a = d[cid]['angles'][idx]
        assert not a['by'], f'{cid}[{idx}]: 이미 소진된 각도 -> {a["by"]}'
        a['by'].append(mid)
        n += 1

    # ── 검증 ────────────────────────────────────────────────
    have = {b for c in C for x in c['angles'] for b in x['by']}
    p11 = [f'M0{i}' for i in range(1907, 1917)]
    missing = [m for m in p11 if m not in have]
    assert not missing, f'대장 미링크 잔존: {missing}'
    dup = [m for m in p11 if sum(1 for c in C for x in c['angles'] for b in x['by'] if b == m) != 1]
    assert not dup, f'중복 링크: {dup}'
    free = sum(1 for c in C for x in c['angles'] if not x['by'])
    total = sum(len(c['angles']) for c in C)

    json.dump(obj, open(CJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'P11 대장 링크 {n}건 · 저작 주의 2건 추가')
    print(f'  개념 {len(C)}개 · 각도 {total}개 · 미소진 {free}개 (잔여 54제)')


if __name__ == '__main__':
    main()
