# -*- coding: utf-8 -*-
"""T14 P11 4차 조치 — ★한 항목에 새 예를 넣으면 그 항목의 압축된 문장을 다시 읽는다★

4차 보고: solver ★차단 0(4차 연속)·열 문항 정답 전부 일치·확신도 전부 '확실'·자족성 전부
충족·지적 없음★ · defender ★[상] 0 · [중] 0 · 열 문항 전부 동결 권고★ ·
factchecker ★✗ 0 · △ 2 — '이대로 닫아도 된다'★.
  → ★세 게이팅 동시 0건 달성.★ 이 조치는 factchecker 가 닫기 전에 청한 구절 다듬기다.

■ factchecker 가 '이번 수정이 낸 유일한 새 구멍' 이라 부른 자리
  M02244 계산 줄의 '같은 주기라도 전자 수는 맞지 않음(3주기 Na⁺ 는 10개, Cl⁻ 는 18개)' 이
  ★같은 항목 안에 3차에 새로 들어온 예(Na⁺ 와 Mg²⁺ 는 둘 다 3주기이고 둘 다 열 개)와 정면으로
  어긋나 읽힌다.★ 해설 본문은 이미 '주기가 같다고 전자 수가 맞지는 않지' 로 완화되어 있으므로
  압축 줄만 그 결에 맞춘다.
  ▸ ★새로 얻는다 — 한 항목에 새 예를 넣으면 그 항목의 압축된 문장을 다시 읽는다. 압축 줄은
    문장이 짧아 전칭으로 읽히고, 새 예가 그 전칭의 반례가 되기 쉽다.★

■ 함께 고친 △ 하나
  M02242 ④ 해설 꼬리의 '점을 빼면 두 원소가 가로축에서 이웃해 보이는 것뿐' — 가로축이 원자
  번호이므로 Cl(17)과 K(19)는 축에서 이웃이 아니라 ★한 칸 빈 채로 남는다.★ '두 원소가 이웃'
  으로 굳으면 원자 번호가 나란하다고 잘못 일반화할 여지가 있다. 그리고 같은 문항이 세 곳에서
  '핵전하만 늘면' 이라고 적는데 이 단원이 세운 요인은 유효 핵전하이므로 고리를 한 번 넣어
  M02240 의 처리('양성자 수 대목은 유효 핵전하 쪽을 가리킨다')와 결을 맞춘다.

■ defender 가 단 조건 하나는 ★개념 대장이 이미 답한다★
  '같은 껍질 전자는 절반쯤 가린다' 류 어림 규칙이 교재에 실려 있으면 M02238 ④가 국소적으로
  참이 된다고 했다. 개념 대장 C14-010 이 ★정의식도 슬레이터도 가림 상수도 없다★ 고 못 박아
  두었으므로 그런 문구는 없다. 조건 충족.
"""
import ast
import os
import re

BASE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(BASE, 'build_t14_p11.py')

body = open(SRC, encoding='utf-8').read()
BEFORE = body


def rep(old, new, n=1):
    pat = re.compile(r'\s*\n\s*'.join(re.escape(t) for t in re.split(r'\s*\n\s*', old)))
    out, c = pat.subn(lambda m: new, body)
    assert c == n, f'{c}곳(기대 {n}) — {old[:44]!r}'
    return out


# ══ M02244 ══ 압축 줄을 해설 본문의 결에 맞춘다 ═════════════════════════════
body = rep("같은 주기라도 전자 수는 맞지 않음(3주기 Na⁺ 는 10개, Cl⁻ 는 18개) /",
           "같은 주기라도 전자 수가 맞는다는 보장이 없음(3주기 Na⁺ 는 10개, Cl⁻ 는 18개) /")

# ══ M02242 ══ 빈 칸을 '이웃' 으로 굳히지 않고, 요인의 고리를 한 번 넣는다 ═════════
body = rep("'경계는 그 자리에 그대로 있어. 점을 빼면 두 원소가 가로축에서 이웃해 보이는 '\n"
           "          '것뿐이지. '",
           "'경계는 그 자리에 그대로 있어. 점을 빼면 두 점 사이에 찍힌 것이 없어 선이 곧장 '\n"
           "          '이어져 보이는 것뿐이지. '")
body = rep("'껍질이 하나 더 열리면 크게 오르고 껍질 수가 묶인 채 핵전하만 늘면 완만하게 '",
           "'껍질이 하나 더 열리면 크게 오르고 껍질 수가 묶인 채 양성자 수가 늘어 유효 '\n"
           "             '핵전하가 커지면 완만하게 '")
body = rep("'주기의 첫 자리★지. 반대로 껍질 수가 묶인 채 핵전하만 늘면 조금씩 내려가고, 그것이 '",
           "'주기의 첫 자리★지. 반대로 껍질 수가 묶인 채 유효 핵전하만 커지면 조금씩 '\n"
           "          '내려가고, 그것이 '")
#   ★조치 앵커가 줄 가운데에서 시작할 때는 앞에 따옴표가 없다★ — 이 세션에서 세 번째로
#   같은 자리에 걸렸다. 앵커를 잡기 전에 그 줄의 첫 글자를 눈으로 본다.
body = rep("완만하게 내려감 = '\n"
           "             '껍질 수가 묶인 채 핵전하만 늚 = 한 주기 안 /",
           "완만하게 내려감 = '\n"
           "             '껍질 수가 묶인 채 유효 핵전하만 커짐 = 한 주기 안 /")

assert body != BEFORE
open(SRC, 'w', encoding='utf-8').write(body)

# ══ 불변 검사 ═══════════════════════════════════════════════════════════
bad = []
try:
    ast.parse(body)
except SyntaxError as e:
    bad.append(f'치환 결과가 문법에 어긋난다 — {e.lineno}행: {e.msg}')

live = '\n'.join(l for l in body.split('def build()')[1].split('\n')
                 if not l.lstrip().startswith('#'))
flat = re.sub(r"'\s*\n\s*'", '', live)
for gone, why in (
        ('같은 주기라도 전자 수는 맞지 않음', 'M02244 압축 줄이 자기 예와 어긋난 채 남아 있다'),
        ('가로축에서 이웃해 보이는', 'M02242 의 이웃 표현이 남아 있다'),
        ('껍질 수가 묶인 채 핵전하만', 'M02242 의 요인 이름이 고쳐지지 않았다')):
    if gone in flat:
        bad.append(why)
#   ★선지 마흔은 이번 조치의 자리가 아니다★ — 4차는 해설과 압축 줄만 손댄다
CH_MARK = ("'전하가 같고 원자 번호가 이웃한 이온이면 놓인다'",
           "'늘어난 가림의 몫은 양성자 한 개 몫의 절반으로 정해진다'",
           "'양성자 대목은 살리고 껍질 대목만 지워야 한다는 것이다'")
for m in CH_MARK:
    if m not in re.sub(r"'\s*\n\s*'", '', body):
        bad.append(f'선지가 바뀌었다 — {m[:24]}')

print('T14 P11 4차 조치 — 두 문항, 선지는 하나도 건드리지 않았다')
if bad:
    print('  ❌ 불변 검사 실패')
    for b in bad:
        print('     ·', b)
    raise SystemExit(1)
print('  ✅ 불변 검사 통과')
