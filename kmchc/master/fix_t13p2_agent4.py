# -*- coding: utf-8 -*-
"""T13 P2 — 4차 조치 (서술만 · 발문·선지·정답 불변).

3차 순회. solver 10/10 확실 · 자족성 전원 충족 · **지적할 것 없음**(배치의 수치
극 편향이 해소된 것도 확인했다), defender **F2 승격 대상 0건**(오답 서른 전부
'변호 궁색'), factchecker 사실 오류 1건 + △ 4건.

★factchecker 가 잡은 것 — 두 오답의 경로가 서로 뒤바뀌어 있었다★
M01989 ③ 은 '주양자수 5 · 전자 10 개'(5d¹⁰)인데 반박은 "전자가 가장 많은
부껍질을 고른 값" 이라고 했다. 그런데 **전자가 가장 많은 부껍질은 4f 의 14 개**
이므로 그 경로는 ③ 이 아니라 ④ 를 낳는다. 정작 ④ 의 반박은 "적힌 차례의 첫 항"
이라는 다른 경로를 대고 있어, **한 선지는 경로가 비고 다른 선지는 겹쳤다.**

  ▸ 해로운 방향이 분명하다 — 개수로 골라 ④ 를 찍은 학생은 자기 오류를 ③ 항목
    에서 설명받고, ③ 을 찍은 학생은 왜 틀렸는지 끝내 못 듣는다.
  ▸ ★교훈: 오답 반박은 값과 짝을 맞춰 적었는지 **번호가 아니라 값으로** 검산할
    것.★ 서른 개 가운데 이 한 자리만 어긋났고, 앞 두 회차의 factchecker 는
    넘겼다. 이번에 "서른 개를 모두 돌려 보라" 고 적어 보내 잡혔다.

→ ③ 은 '5d 를 최외각으로 본 값'(전이금속에서 d 전자를 원자가처럼 다루는 습관),
  ④ 는 '전자가 가장 많은 부껍질을 고른 값'(4f 의 14)으로 서로 바꿔 적는다.

────────────────────────────────────────────────────────────────
△ 두 자리
────────────────────────────────────────────────────────────────
· **M01984** "교환에너지 몫도 함께 들어가는데 **어느 쪽이 큰지는 계에 따라
  달라서**" — 대비 구도가 부정확하다. 짝짓기 에너지는 쿨롱 반발 증가분과 교환
  안정화 상실분을 **합친** 양이지, 둘이 크기를 겨루어 승자가 바뀌는 항이 아니다.
  지금 문장은 "계에 따라서는 교환 쪽이 이겨 짝짓기가 유리해질 수도 있다" 로
  읽혀 **훈트 규칙 자체가 조건부처럼 보인다.** 방향을 고정한다.
· **M01981 자가진단** "축퇴는 전자가 하나일 때" — 본문 맥락은 2s 대 2p 라 옳지만,
  이 한 줄만 떼어 외우면 "전자가 둘 이상이면 축퇴가 없다" → "산소의 2px·2py 도
  다르다" 로 일반화되어 **같은 배치 M01987 의 요지와 정면으로 어긋난다.**
  "2s 와 2p 의 축퇴는" 으로 한정한다.

기록만 하고 남기는 것
· M01988 정답 선지가 아르곤 자신이 아니라 다음 자리를 가리킨다(defender·
  factchecker 둘 다 "수정 필수는 아님"). 발문의 '직접적인 까닭' 은 2차 defender 가
  ④(팔전자 인과 역전)를 닫으라고 요구해 넣은 것이고, 3차 defender 는 ④ 가 이제
  명확히 거짓이라고 했다. ★두 회차의 요구가 반대이므로 F2 를 닫는 쪽을 지킨다.★
· M01985 발문이 축약 정도가 아니라 중복 계수를 겨냥해야 한다(factchecker, 발문을
  볼 수 없어 확인 못 함) — 실제 발문은 "같은 전자를 두 번 적어 잘못된 것은?" 이라
  이미 그 조건을 담고 있다. 조치 불필요.
· M01982 의 오답 셋이 규칙적 수열이라 불규칙한 정답이 형태로 지목된다(solver) —
  홀전자 변화폭이 정해져 있어 회피가 어렵고 오답 셋이 각각 실재하는 오개념에
  대응한다. solver 스스로 손대지 말라고 했다.
· M01981 의 Li²⁺ 가 화학적으로 이질적이라 눈에 띈다(solver) — 1 전자 계를 묻는
  문항 특성상 그 이질성이 곧 정답의 본질이라 회피 불가.
"""
import json
from collections import Counter

BANK = 'master/master_bank.json'
MK = ['①', '②', '③', '④']

bank = json.load(open(BANK, encoding='utf-8'))
by = {x['id']: x for x in bank}
before = {i: (json.dumps(by[f'M0{i}']['choices'], ensure_ascii=False),
              by[f'M0{i}']['stem'], by[f'M0{i}']['answer']) for i in range(1981, 1991)}


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:40]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


# ── ★M01989 : 두 오답의 경로를 값에 맞게 맞바꾼다 (factchecker ✗) ────────
it = by['M01989']
sub(it, '③ 주양자수 5 · 전자 10 개: 전자가 가장 많은 부껍질을 고른 값이야. 바깥인지 안쪽인지는 '
        '개수가 아니라 주양자수로 정해져.',
    '③ 주양자수 5 · 전자 10 개: 5d 를 가장 바깥으로 본 값이야. 전이금속에서 d 전자를 '
    '원자가전자처럼 다루는 습관이 여기서 걸리지. 그런데 바깥인지 안쪽인지는 주양자수로 '
    '정해지고 5 는 6 보다 작아.')
sub(it, '④ 주양자수 4 · 전자 14 개: 적힌 차례의 첫 항이야. 축약 배치는 대개 안쪽부터 적으니 '
        '첫 항이 가장 안쪽 가까이에 있지. 다만 채움 순서로 적으면 이 관례가 깨지기도 하니 '
        '차례가 아니라 주양자수를 견주는 편이 안전해.',
    '④ 주양자수 4 · 전자 14 개: 전자가 가장 많은 부껍질을 고른 값이야. 4f 에 열넷이 들어 '
    '있어 셋 가운데 가장 많지. 그런데 바깥인지는 개수가 아니라 주양자수로 정해져. 게다가 '
    '이 항은 적힌 차례의 첫 항이고, 축약 배치는 대개 안쪽부터 적으니 오히려 가장 안쪽 '
    '가까이에 있어. 다만 채움 순서로 적으면 그 관례가 깨지기도 하니 차례가 아니라 '
    '주양자수를 견주는 편이 안전해.')
for d in it['distractors']:
    if d['opt'] == 2:
        d['error'] = '5d 를 가장 바깥으로 봄 — 전이금속에서 d 전자를 원자가처럼 다루는 습관'
    if d['opt'] == 3:
        d['error'] = '전자가 가장 많은 부껍질(4f 의 14)을 고름 — 바깥은 개수가 아니라 n 이 정한다'

# ── △ M01984 : 교환에너지 대비 구도를 바로잡는다 ─────────────────────────
sub(by['M01984'],
    '실제로는 여기에 교환에너지 몫도 함께 들어가는데, 어느 쪽이 큰지는 계에 따라 달라서 '
    '고등학교 범위에서는 반발 쪽으로 설명해.',
    '실제로는 여기에 교환에너지 몫도 함께 들어가는데, 두 몫을 합치면 언제나 짝짓는 쪽이 '
    '손해라 결과는 달라지지 않아. 고등학교 범위에서는 반발 쪽으로 설명해.')

# ── △ M01981 : 자가진단 한 줄을 2s·2p 로 한정한다 ───────────────────────
sub(by['M01981'], '자가진단: 축퇴는 전자가 하나일 때 — Li²⁺ 만 전자 1 개다.',
    '자가진단: 2s 와 2p 의 축퇴는 전자가 하나일 때 — Li²⁺ 만 전자 1 개다.')

# ── 불변 검사 ───────────────────────────────────────────────────────────
seq = [by[f'M0{i}']['answer'] for i in range(1981, 1991)]
assert Counter(seq) == Counter({0: 2, 1: 2, 2: 3, 3: 3}), dict(Counter(seq))
for i in range(1981, 1991):
    x = by[f'M0{i}']
    now = (json.dumps(x['choices'], ensure_ascii=False), x['stem'], x['answer'])
    assert now == before[i], f'M0{i}: 서술만 고치는 회차인데 구조가 바뀌었다'
    assert len(x['solution']) >= 300, (i, len(x['solution']))
    head = x['solution'].split('\n\n')[1]
    a = x['answer']
    assert (MK[a] + '가 옳아' in head) or (MK[a] + '이 옳아' in head), x['id']
    for k in range(4):
        assert (MK[k] + ' ' + x['choices'][k]) in x['solution'], x['id']

json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('4차 조치 완료 — M01989 두 오답 경로 맞바꿈 · M01984 교환에너지 · M01981 자가진단. 구조 불변.')
