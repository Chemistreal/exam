import json, os

BJ = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'master_bank.json')
MK = '①②③④'


def swap_choice(it, idx, new_txt, new_rebut, err, typ):
    mark = MK[idx]
    old = it['choices'][idx]
    assert idx != it['answer'], f"{it['id']}: 정답 자리는 이 헬퍼로 바꾸지 않는다"
    lines = it['solution'].split('\n')
    hit = [i for i, L in enumerate(lines) if L.startswith(f'{mark} {old}:')]
    assert len(hit) == 1, f"{it['id']}: 해설 {mark} 줄을 못 찾음"
    lines[hit[0]] = f'{mark} {new_txt}: {new_rebut}'
    it['solution'] = '\n'.join(lines)
    it['choices'][idx] = new_txt
    for dd in it['distractors']:
        if dd['opt'] == idx:
            dd['error'], dd['type'] = err, typ
            break
    else:
        raise AssertionError(f"{it['id']}: distractor {idx} 없음")


def main():
    bank = json.load(open(BJ, encoding='utf-8'))
    x = {i['id']: i for i in bank}
    ids = [f'M0{i}' for i in range(1927, 1937)]

    swap_choice(x['M01934'], 1, '휘어짐 — 핵이 아주 작다 · 되튐 — 알파 입자가 아주 무거워서다',
                '되튐이 말해 주는 것은 부딪힌 상대가 무겁다는 것이야. 알파 입자가 무거운 것은 '
                '실험을 하기 전에 이미 알고 있던 일이라 결론이 될 수 없지.',
                '되튐의 결론을 표적이 아니라 알파 입자 쪽에 붙임', 'surface')

    swap_choice(x['M01933'], 3, '선 사이가 빈 것은 그 빛이 약해 찍히지 않았기 때문이다',
                '선 사이에는 약한 빛이 있는 것이 아니라 아예 빛이 없어. '
                '준위가 띄엄띄엄해서 그 사이에 해당하는 빛이 나올 수 없거든.',
                '불연속을 세기 부족으로 읽음 — 선 사이에는 빛 자체가 없다', 'causal')

    swap_choice(x['M01927'], 1, '전자는 두 준위 사이를 옮겨 가며 빛을 조금씩 내놓는다',
                '전이는 조금씩 흘러가는 일이 아니라 한 번에 건너뛰는 일이야. '
                '조금씩 내놓으면 나오는 빛이 이어진 띠가 되어 선스펙트럼이 설명되지 않지.',
                '전이를 연속으로 봄 — 준위 차만큼을 한 번에 내놓는다', 'proc')

    # factchecker — ④ 의 진단이 ② 와 겹치던 것을 실제 오류 지점으로 옮긴다
    m = x['M01932']
    old = '④ 발머 > 파셴 > 라이먼: 도착 준위가 낮을수록 에너지가 커. 관계를 뒤집어 읽었어.'
    new = ('④ 발머 > 파셴 > 라이먼: 라이먼을 맨 뒤에 둔 것이 어긋났어. '
           '도착이 가장 낮은 라이먼이 에너지가 가장 크지.')
    assert old in m['solution'], 'M01932: ④ 반박 줄을 못 찾음'
    m['solution'] = m['solution'].replace(old, new, 1)
    for dd in m['distractors']:
        if dd['opt'] == 3:
            dd['error'] = '라이먼만 맨 뒤로 보냄 — 도착이 가장 낮은 라이먼이 가장 크다'
            dd['type'] = 'proc'
            break
    else:
        raise AssertionError('M01932: distractor 3 없음')

    # ── 자기 검사 ────────────────────────────────────────────────
    from collections import Counter
    for fid in ids:
        it = x[fid]
        sol = it['solution']
        for k, c in enumerate(it['choices']):
            if k == it['answer']:
                assert f'[정답] {MK[k]} {c} —' in sol, f'{fid}: [정답] 줄 어긋남'
            else:
                assert f'{MK[k]} {c}:' in sol, f'{fid}: {k + 1} 번 줄 어긋남'
        assert sorted(d['opt'] for d in it['distractors']) == \
            sorted(k for k in range(4) if k != it['answer']), f'{fid}: 오답 자리 어긋남'
        assert '★' not in it['stem'] and '★' not in sol, f'{fid}: 강조 기호 잔존'
        assert len(sol) >= 300, f'{fid}: 해설이 300자 미만 ({len(sol)})'
    assert Counter(x[f]['answer'] + 1 for f in ids) == Counter({1: 2, 2: 3, 3: 2, 4: 3})
    # M01934 — 되튐 축 네 값이 모두 다르고, 참인 반쪽만으로 된 선지가 없는가
    tails = [c.split('되튐 — ')[1] for c in x['M01934']['choices']]
    assert len(set(tails)) == 4, f'M01934 되튐 축 중복: {tails}'
    assert '원자가 대부분 비어 있다' not in tails, 'M01934: 참인 반쪽 잔존'
    # M01932 — ②와 ④의 진단이 겹치지 않는가
    errs = {d['opt']: d['error'] for d in x['M01932']['distractors']}
    assert errs[1] != errs[3] and '뒤집' not in errs[3], f'M01932 진단 겹침: {errs}'

    json.dump(bank, open(BJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('P13 4차 조치 완료 — 오답 교체 3 · 오답 진단 정밀화 1')
    for fid in ids:
        L = [len(c) for c in x[fid]['choices']]
        s = sorted(L)
        sp = (s[3] - s[0]) / ((s[1] + s[2]) / 2)
        r = sorted(range(4), key=lambda i: -L[i]).index(x[fid]['answer']) + 1
        flag = ''
        if L[x[fid]['answer']] == max(L) and L.count(max(L)) == 1:
            flag = ' G3-최장'
        if L[x[fid]['answer']] == min(L) and L.count(min(L)) == 1:
            flag = ' G3-최단'
        if sp > 0.25 and s[1] >= 8:
            flag += ' G3b'
        print(f'  {fid} {L} 산포{sp:.2f} 순위{r}{flag}')


if __name__ == '__main__':
    main()
