def rebuild(it, *, stem, choices, ans, lead, cor, reb, diag,
            wrongs, proof, calc, device, scenario, skill=None,
            objective=None, track=None, difficulty=None, dok=None, esr=None):
    """발문·선지·정답 자리·해설·오답 메타를 통째로 다시 세운다."""
    assert len(choices) == 4 and len(set(choices)) == 4, it['id']
    assert len(wrongs) == 3, it['id']
    it['stem'] = stem
    it['choices'] = list(choices)
    it['answer'] = ans
    it['distractors'] = sorted(
        [{'opt': choices.index(t), 'error': e, 'type': ty} for t, e, ty in wrongs],
        key=lambda d: d['opt'])
    assert [d['opt'] for d in it['distractors']] == sorted(set(range(4)) - {ans}), it['id']
    it['answer_proof'] = proof
    it['calc_check'] = calc
    it['device'] = device
    it['scenario'] = scenario
    if skill:
        it['skill'] = skill
    if objective:
        it['objective'] = objective
    if track:
        it['track'] = track
    if difficulty:
        it['difficulty'] = difficulty
    if dok:
        it['dok'] = dok
    if esr:
        it['expected_solve_rate'] = esr
    it.pop('answer_expr', None)
    body = [lead, '', f'[정답] {MK[ans]} {choices[ans]} — {cor}', '']
    body += [f'{MK[k]} {choices[k]}: {reb[k]}' for k in range(4) if k != ans]
    body += ['', diag]
    it['solution'] = '\n'.join(body)
    assert len(it['solution']) >= 300, (it['id'], len(it['solution']))


