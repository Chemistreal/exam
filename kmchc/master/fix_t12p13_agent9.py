import json, os

BANK = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'master_bank.json')


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:30]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


def main():
    bank = json.load(open(BANK, encoding='utf-8'))
    d = {x['id']: x for x in bank}

    sub(d['M01927'],
        '빛을 내지 않으니 에너지를 잃지 않아 무너지지 않아. 그리고 준위를 옮길 때 내놓는 '
        '빛은 두 자리의 차이만큼인데 자리가 띄엄띄엄하니 그 차이도 띄엄띄엄한 값뿐이야. '
        '그래서 빛이 이어진 띠가 아니라 몇 가닥의 선으로 나타나지.',
        '빛을 내지 않으니 에너지를 잃지 않아 무너지지 않아. 선스펙트럼 쪽은 여기에 한 걸음이 '
        '더 붙어. 빛은 준위를 옮기는 순간에만 나오고 그 크기가 두 자리의 차이와 같은데, '
        '머무를 수 있는 자리가 띄엄띄엄하니 그 차이도 띄엄띄엄한 값뿐이지. 그래서 빛이 이어진 '
        '띠가 아니라 몇 가닥의 선으로 나타나. 두 한계를 함께 푼 뿌리는 결국 "머무를 자리가 '
        '정해져 있다"는 한 마디야.')

    sub(d['M01928'], '그 어긋난 두 배분이 곧 전하를 띠지 않는 입자 두 개분이었고',
        '그 어긋난 두 몫이 곧 전하를 띠지 않는 입자 두 개분이었고')

    sub(d['M01933'], '사진의 바탕과 선 가운데 어느 쪽이 밝은지만 보면 되는 문항이야.',
        '사진의 바탕과 선 가운데 어느 쪽이 밝은지에서 출발하는 문항이야.')

    for x in bank:
        assert '**' not in x['stem'] and '**' not in x['solution'], x['id']
        assert '★' not in x['stem'] and '★' not in x['solution'], x['id']

    json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('P13 9차 조치 완료 — 해설 문면 3')
    for i in (1927, 1928, 1933):
        print(f'  M0{i} 해설 {len(d[f"M0{i}"]["solution"])}자')


if __name__ == '__main__':
    main()
