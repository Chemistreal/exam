    items = d if isinstance(d, list) else d['items']
    x = {it['id']: it for it in items}

    ids = [f'M0{i}' for i in range(1897, 1907)]
    assert set(WATCH) == set(ids), f'watch 대상 어긋남: {set(WATCH) ^ set(ids)}'

    tot = 0
    for fid in ids:
        it = x[fid]
        v = it.get('verified') or {}
