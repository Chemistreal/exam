def local_checks(items):
    import re
    from collections import Counter
    bad = []

    # ① 오답 유형이 한 문항 안에서 겹치지 않을 것
    for x in items:
        ts = [w['type'] for w in x['distractors']]
        if len(set(ts)) < len(ts):
            bad.append(f"{x['id']} 오답 유형 중복 — {ts}")

    # ② 발문에 정답 문자열이 통째로 들어가 있지 않을 것
    for x in items:
        core = re.sub(r'[^0-9A-Za-z가-힣]', '', x['choices'][x['answer']])
        stem = re.sub(r'[^0-9A-Za-z가-힣]', '', x['stem'])
        if len(core) >= 6 and core in stem:
            bad.append(f"{x['id']} 발문에 정답이 통째로 들어 있음")

    # ③ 정답 길이 순위 — 유일 최장·최단이 없을 것
    for x in items:
        ls = [len(c) for c in x['choices']]
        a = x['answer']
        if ls.count(ls[a]) == 1 and (ls[a] == max(ls) or ls[a] == min(ls)):
            bad.append(f"{x['id']} 정답이 유일 최장·최단 {ls} (정답 {a+1})")

    # ④ ★수치 봉인★ — 이 배치에는 pm 값이 하나도 없어야 한다.
    for x in items:
        for fld in ('stem', 'solution'):
            m = re.search(r'\d+\s*pm', x[fld])
            if m:
                bad.append(f"{x['id']} {fld} 에 pm 값 '{m.group(0)}' — 이 배치는 값 없이 선다")
        for c in x['choices']:
            if re.search(r'\d+\s*pm', c):
                bad.append(f"{x['id']} 선지에 pm 값 — 이 배치는 값 없이 선다")

    # ⑤ ★테마 2 봉인★ — 규칙을 발문에 인쇄하지 않았는가.
    BAN = ('요인', '⇒', '핵전하량', '유효 핵전하',
           '껍질 수가 많을수록', '껍질 수가 늘면', '껍질 수가 클수록',
           '전자 수가 많을수록', '전자 수가 늘면',
           '양성자 수가 많을수록', '양성자 수가 늘면')
    for x in items:
        for w in BAN:
            if w in x['stem']:
                bad.append(f"{x['id']} 발문에 '{w}' — 규칙을 인쇄한 셈")

    # ⑥ ★그래프 봉인★ — 교재 그래프에 숫자 라벨이 없으므로 이 배치는 그래프를 쓰지 않는다.
    for x in items:
        if '그래프' in x['stem']:
            bad.append(f"{x['id']} 발문에 그래프 — 그래프는 뒤 배치(C14-015·016·022)의 몫")

    # ⑦ ★낱말 하나로 통일★ — '핵전하량' 과 '양성자 수' 를 섞지 않는다(P1 5차의 값).
    for x in items:
        for w in ('핵전하량', '유효 핵전하', '핵전하'):
            if w in x['solution'] or any(w in c for c in x['choices']):
                bad.append(f"{x['id']} 해설·선지에 '{w}' — 이 배치는 '양성자 수' 로만 부른다")

    # ⑧ ★같은 뜻을 두 낱말로 부르지 않을 것★ (1차 factchecker 보통)
    for x in items:
        if re.search(r'같은 줄|다른 줄|한 줄에', x['solution']):
            bad.append(f"{x['id']} 해설에 '줄' — 이 배치는 '주기' 로만 부른다")
        if '플루오린 이온' in x['stem'] or '플루오린 이온' in x['solution']:
            bad.append(f"{x['id']} '플루오린 이온' — 정확한 이름은 '플루오린화 이온'")

    # ⑨ ★해설이 세운 규칙이 반례를 내지 않을 것★
    #    (1차 factchecker ★높음★ — 이 배치 최대의 결함이었다)
    #    "값이 다르면 순서를 정한다" 로 적으면 같은 주기에서 전자 수에도 걸려
    #    'S 가 Si 보다 크다' 는 틀린 결론이 나온다. 옳은 규칙만 쓴다.
    for x in items:
        if re.search(r'값이 (실제로 )?다른 (다른 )?(요인|쪽)이 (순서를 )?(정한|맡)',
                     x['solution']):
            bad.append(f"{x['id']} 해설이 '값이 다른 요인이 정한다' 로 규칙을 세움 — "
                       f"같은 주기에서 전자 수에도 걸려 반례가 나온다")

    # ⑩ ★G3g 예고★ — 칸별 최빈값 조합이 정답을 유일하게 짚지 않을 것
    for x in items:
        toks = [c.split() for c in x['choices']]
        if len(toks[0]) >= 2 and all(len(t) == len(toks[0]) for t in toks):
            picks = []
            for col in zip(*toks):
                cc = Counter(col).most_common()
                win = [v for v, k in cc if k == cc[0][1]]
                picks.append(win[0] if len(win) == 1 else None)
            if any(p is not None for p in picks):
                surv = [i for i, t in enumerate(toks)
                        if all(p is None or t[k] == p for k, p in enumerate(picks))]
                if surv == [x['answer']]:
                    bad.append(f"{x['id']} 칸별 최빈값 조합이 정답을 유일하게 짚음")

    # ⑪ ★선지 사이 포함관계★ — 한 선지가 다른 선지를 통째로 품지 않을 것
    for x in items:
        for i, c in enumerate(x['choices']):
            for j, d in enumerate(x['choices']):
                if i != j and len(c) >= 6 and c in d:
                    bad.append(f"{x['id']} {i+1} 이 {j+1} 안에 통째로 들어 있음")

    # ⑫ ★오답 두 칸이 같은 주장을 하지 않을 것★
    #    (1차 solver 높음 — M02147 ①≡④ · M02149 ①·④ 가 같은 전제를 깔았다)
    def _tk(s):
        return {t for t in re.findall(r'[가-힣]{2,}', s)}
    for x in items:
        cs = x['choices']
        for i in range(4):
            for j in range(i + 1, 4):
                if i == x['answer'] or j == x['answer']:
                    continue
                a, b = _tk(cs[i]), _tk(cs[j])
                if a and b and len(a & b) / len(a | b) >= 0.62:
                    bad.append(f"{x['id']} 오답 {i+1}·{j+1} 이 낱말을 크게 겹침 — "
                               f"같은 주장이면 함께 버려진다")

    # ⑬ ★문항 안에서 정답만 부정형이면 안 된다★
    #    1차에는 '세 문항 연달아' 만 보았는데 2차 solver 가 더 정확히 짚었다 —
    #    넷 중 한 칸만 '없다/못한다' 꼴이고 그 칸이 정답이면, ★단정형 셋 중 홀로 유보적인
    #    칸을 고르는 요령★ 으로 화학 없이 맞힌다. 이 배치는 세 문항이 그 꼴이었다.
    #    ▸ 은행 실측 24제(1.1%) · 우연 기대 2.6% — 은행은 이 축에서 이미 깨끗하다(부채 없음).
    #      그런데 이 배치만 3/10 = 30% 로 우연의 열한 배였다. ★배치가 유별났던 것이다.★
    NEG = re.compile(r'(없다|않는다|않다|못한다|불가능하다|아니다)$')
    for x in items:
        ns = [bool(NEG.search(c.strip())) for c in x['choices']]
        if sum(ns) == 1 and ns[x['answer']]:
            bad.append(f"{x['id']} 넷 중 정답만 부정형 — 단정형 셋 중 홀로 유보적인 칸이 된다")

    # ⑭ ★G10 평문★
    for x in items:
        if '★' in x['stem'] or any('★' in c for c in x['choices']):
            bad.append(f"{x['id']} 발문·선지에 강조 표기 — 은행은 평문")

    # ⑮ ★난이도 상한★ — 쉬움 2 를 넘기지 않는다(T13 부채)
    ec = sum(1 for x in items if x['difficulty'] == '쉬움')
    if ec > 2:
        bad.append(f'쉬움 {ec}제 — 착수 규약의 상한 2 를 넘김')

    # ⑯ ★경계를 넘는 부분열 주기★ — G3h 는 배치 안만 본다. 앞 배치 꼬리에 이어 붙여 다시 본다.
    import json as _j
    import os as _o
    try:
        prev = [b['answer'] for b in _j.load(
            open(_o.path.join(_o.path.dirname(_o.path.abspath(__file__)),
                              'master_bank.json'), encoding='utf-8'))[-8:]]
    except Exception:
        prev = []
    ext = prev + [x['answer'] for x in items]
    off = len(prev)
    for per, need in ((2, 4), (3, 3), (4, 2)):
        L = per * need
        for i in range(len(ext) - L + 1):
            if i + L <= off:
                continue
            if all(ext[i + k] == ext[i + k % per] for k in range(L)):
                bad.append(f'경계 포함 {i+1-off} 번 자리부터 주기 {per} 로 {need} 번 되풀이됨')

    if bad:
        print('\n  ❌ 저작 점검 실패')
        for b in bad:
            print(f'     · {b}')
        raise SystemExit(1)
