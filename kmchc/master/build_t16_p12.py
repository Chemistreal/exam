        '④는 차가 같으니 녹는점까지 서로 똑같아진다 라고 했어. 녹는점은 분자 사이의 힘이 갈라. '
        '한 값을 볼 때는 그 값이 말해 주지 않는 것을 함께 적는다.',
        {'성질이 모든 면에서 똑같아지게 된다': '다 정할 순 없어.',
         '차가 같으면 결합 길이까지 같아진다': '크기가 갈라.',
         '차가 같으니 녹는점까지 서로 똑같아진다': '사이의 힘이 갈라.'},
