import re

P = 'build_t14_p4.py'
src = open(P, encoding='utf-8').read()

R = [
    # ── M02167 맺음말 — 한정어를 넣다 주제어가 서술어를 잃었다 ──────────────
    ("          '단일 결합에서 되돌리는 방향은 두 원자가 같은 원소인지가 셈을 가른다.',",
     "          '단일 결합에서는 두 원자가 같은 원소인지가 되돌리는 셈을 가른다.',"),

    # ── M02169 맺음말 — M02168 의 교훈을 그대로 되풀이하던 자리 ─────────────
    ("          '자료를 더할 때는 식이 느는지 모르는 값이 함께 느는지를 세어 봐야 한다.',",
     "          '더 있어야 할 자료를 고를 때는 덜어 낼 몫이 손에 있는지 를 먼저 묻는다.',"),

    # ── M02170 본문 — 자가진단에만 있던 '단일 결합' 을 본문에도 ─────────────
    ("          '같은 원소끼리 이어진 결합이라면 핵 사이에 같은 몫이 둘 놓여 있어. 그러니 핵간 '",
     "          '같은 원소끼리 단일 결합으로 이어졌다면 핵 사이에 같은 몫이 둘 놓여 있어. '\n"
     "          '그러니 핵간 '"),

    # ── M02171 — 방금 논박한 쪽 어휘로 닫던 자리 셋 ─────────────────────────
    ("    # ── M02171 ── C14-001[5] 세 조건이 각각 막는 것 (일반·중간) 정답 ③ ──",
     "    # ── M02171 ── C14-001[5] 세 조건이 각각 받치는 것 (일반·중간) 정답 ③ ──"),
    ("    #   ★정의의 세 조건을 하나씩 떼어 무엇을 막는지 대응시킨다★ — P1 이 조건의 존재를",
     "    #   ★정의의 세 조건을 하나씩 떼어 무엇을 받치는지 대응시킨다★ — P1 이 조건의 존재를"),
    ("'정의의 조건 가운데 같은 원소라는 조건이 막는 것을 지목하기',",
     "'정의의 조건 가운데 같은 원소라는 조건이 받치는 것을 지목하기',"),
    ("          '조건을 외울 때는 무엇을 막는 조건인지 를 함께 적어 두면 헷갈리지 않아.',",
     "          '조건을 외울 때는 무엇을 받치는 조건인지 를 함께 적어 두면 헷갈리지 않아.',"),
]

for a, b in R:
    n = src.count(a)
    assert n == 1, f'{n}곳: {a[:60]!r}'
    src = src.replace(a, b)

open(P, 'w', encoding='utf-8').write(src)

body = src[src.index('def build():'):]
body = '\n'.join(l for l in body.split('\n') if not l.strip().startswith('#'))

BAN_AFTER = [
    '되돌리는 방향은 두 원자가',
    '식이 느는지 모르는 값이 함께 느는지',
    '같은 원소끼리 이어진 결합이라면',
    '조건이 막는 것을 지목하기',
    '무엇을 막는 조건인지',
]
for w in BAN_AFTER:
    assert w not in body, f'물러난 문면이 남았다: {w}'

flat = re.sub(r"'\s*\n\s*'", '', body)
for w, k in [('되돌리는 셈을 가른다', 1),
             ('덜어 낼 몫이 손에 있는지', 1),
             ('단일 결합으로 이어졌다면', 1),
             ('무엇을 받치는 조건인지', 1),
             ('받치는 것을 지목하기', 1)]:
    n = flat.count(w)
    assert n == k, f'{w}: {n} ≠ {k}'

print('fix_t14_p4_r4 적용 완료 —', len(R), '곳')
