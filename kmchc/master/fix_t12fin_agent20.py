# -*- coding: utf-8 -*-
"""T12 마감 14제(M01957~M01970) 층5 순회 — 20차 조치 · 진짜 마감.

★기록 정정★ 19차 커밋에서 "18차에 세 검증자 동시 0건" 이라 적었으나
그때 factchecker 보고가 아직 오지 않았다. 도착한 보고는 계산 0 · 사실 0 ·
번호 0 · 오답 경로 0 이지만 **서술 결함 일곱**을 올렸고, 그 가운데 넷은
17차 조치가 남긴 것이다. LAYER5 의 회차도 함께 고친다.

★교훈★ **검증자 셋이 다 돌아오기 전에 닫았다.** 순회의 종료 조건은
'세 검증자 동시 0건' 인데, 셋 중 둘만 보고 판단했다. 앞으로 마감 선언은
셋이 모두 도착한 뒤에만 한다.

────────────────────────────────────────────────────────────────
㉠ M01967 — 17차의 어법 통일이 네 군데를 빠뜨렸다 (최우선)
────────────────────────────────────────────────────────────────
17차에 '계열 한계' 를 위치어에서 수렴값 어법으로 바꿨는데 **"끝자리" 가
네 곳 그대로 남았다.** 특히 첫 문장이 한계를 "어떤 **전이**인지" 잡으라고
지시하고 세 문장 뒤에서 "거기에 선이 하나 놓인 것이 아니" 라고 부정한다 —
한 단락 안에서 같은 대상을 실체로도 비실체로도 다룬다.
④ 반박의 "수렴해 가는 반대쪽" 도 기준점이 없어 정반대로 읽힌다.

────────────────────────────────────────────────────────────────
㉡ M01965 — 17차에 문장을 지운 자리가 논증을 끊었다
────────────────────────────────────────────────────────────────
"이 세 숫자를 놓고 **선지를 하나씩** 대 보자" 라고 예고하고 ③ 을 건너뛴다.
게다가 ③ 판정에 필요한 110 년이 예고한 세 숫자(94·14·2)에 없어 **본문
논리만으로는 ③ 을 반박할 수 없다.** 세 간격의 합이라는 연결을 되살린다.

────────────────────────────────────────────────────────────────
㉢ M01960 — ∞ 행을 세 겹으로 뺀다
────────────────────────────────────────────────────────────────
같은 ∞ 행에 (a) 최댓값에서는 정식 후보 → (b) "실제 준위가 아니" 라는
원리적 배제 → (c) "유한한 준위 가운데" 라는 범위 제한 → (d) 수치 비교로
배제 가 차례로 걸린다. (c)로 이미 뺐다면 (d)는 헛돌고, (d)로 뺄 거면
(b)(c)는 부당한 사전 축소다. **수치 배제 하나로 통일한다.**

(확인됨 — 17차에 함정을 '셋' 으로 고친 것은 세 오답에 1:1 로 안착했다.)

────────────────────────────────────────────────────────────────
㉣ M01961 · M01970 · M01963 — 본문이 오답 반박을 선점한다
────────────────────────────────────────────────────────────────
본문 후반이 오답의 오류 경로를 미리 다 적어 두어 반박이 재탕이 된다.
세 문항에서 같은 꼴이 나왔고, M01961 은 ③ 을 갈아 끼우면서 옛 선지를
겨냥한 본문 "둘째" 못 박기가 그대로 남아 특히 겹친다.
→ 본문에서 덜어 내고 반박에 일을 넘긴다.
M01961 의 "계열 한계에서 **멎어**" 는 파장이 그 값에 닿는다는 뜻이 되어
같은 문항 자가진단·M01967 의 수렴 어법과 어긋나므로 "수렴해" 로 고친다.

────────────────────────────────────────────────────────────────
㉤ 잔가지 셋
────────────────────────────────────────────────────────────────
· M01970 ④ "410 nm 라 왼쪽에서 첫째야. 파장이 가장 짧은 쪽이고" —
  이 문항의 다섯 값에는 397 이 있으므로 410 은 가장 짧지 않다.
  **축 밖 값의 존재가 이 문항의 핵심 함정인데 바로 그 한정이 빠졌다.**
· M01966 자가진단의 둘째 문장은 ④ 반박(누가 풀었나)의 요약이라 이 문항의
  판정 기준(두 결함의 층위가 다르다)과 층이 어긋난다.
· M01962 자가진단 "값 읽기**만** 막는다" — 정량 비교도 함께 막히므로
  전칭이 과하다.
"""
import json

BANK = 'master/master_bank.json'
MK = ['①', '②', '③', '④']

bank = json.load(open(BANK, encoding='utf-8'))
by = {x['id']: x for x in bank}


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:40]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


# ── ㉠ M01967 : '끝자리' 잔재 네 곳 + 기준점 없는 '반대쪽' ────────────
it = by['M01967']
sub(it, '먼저 계열이 모여드는 끝자리가 어떤 전이인지부터 잡자.',
    '먼저 계열 한계가 어떤 극한에 해당하는지부터 잡자.')
sub(it, '셋은 모여드는 끝자리 대신 그 계열에서 파장이 가장 긴 선을 구하는 것이지. '
        '끝자리와 첫 선은 계열의 양 끝이라 값이 아주 멀어.',
    '셋은 수렴값 대신 그 계열에서 파장이 가장 긴 선을 구하는 것이지. '
    '수렴값과 첫 선은 계열의 양 끝이라 값이 아주 멀어.')
sub(it, '이것은 발머 계열(도착 2)이 모여드는 끝자리야.',
    '이것은 발머 계열(도착 2)의 수렴값이야.')
sub(it, '그건 계열에서 실제로 나오는 첫 선이고, 묻는 것은 파장이 수렴해 가는 반대쪽이야.',
    '그건 계열에서 실제로 나오는 가장 긴 선이고, 묻는 것은 그 반대편에서 파장이 수렴해 가는 값이야.')
assert '끝자리' not in it['solution'], 'M01967: 끝자리 잔재'

# ── ㉡ M01965 : 지운 자리가 끊은 논증을 잇는다 ───────────────────────
it = by['M01965']
sub(it, '이 세 숫자를 놓고 선지를 하나씩 대 보자.',
    '세 간격을 다 더하면 돌턴에서 보어까지가 110 년이야. 이 넷을 놓고 선지를 하나씩 대 보자.')

# ── ㉢ M01960 : ∞ 배제를 수치 하나로 통일 ────────────────────────────
it = by['M01960']
sub(it, '여기서 ∞ 는 실제 준위가 아니라 한없이 올렸을 때 다가가는 극한이고, 표는 그 극한값을 '
        '한 행으로 실어 둔 거야.',
    '표의 ∞ 행은 출발을 한없이 올렸을 때 다가가는 극한값을 실어 둔 것이고, 최댓값은 거기서 나와.')
sub(it, '표에 실린 유한한 준위 가운데 가장 위에서 이웃한 짝은 5 와 6 이야.',
    '표에 실린 이웃한 짝 가운데 가장 위는 5 와 6 이야.')

# ── ㉣ 본문이 반박을 선점하는 자리를 덜어 낸다 ───────────────────────
it = by['M01961']
sub(it, '여기서 두 가지를 못 박아 두자. 첫째, 발머 계열의 선은 무한히 많아. 출발 준위를 '
        '얼마든지 올릴 수 있으니까. 둘째, 선은 한계에 다가가되 넘지는 못해. 출발이 아무리 '
        '높아도 전이 에너지가 k/4 를 넘을 수 없으니 한계보다 짧은 파장 쪽에는 발머 선이 없지. '
        '눈에 보이는 넷은',
    '여기서 하나만 못 박아 두자. 발머 계열의 선은 무한히 많아 — 출발 준위를 얼마든지 올릴 수 '
    '있으니까. 눈에 보이는 넷은')
sub(it, '파장은 0 이 아니라 계열 한계에서 멎어.', '파장은 0 이 아니라 계열 한계로 수렴해.')

it = by['M01970']
sub(it, ' 여기서 397 을 빼지 않고 다섯을 그냥 세면 셋째가 434 nm 가 되어 답이 어긋나.', '')
sub(it, '④ 6 → 2: 410 nm 라 왼쪽에서 첫째야. 파장이 가장 짧은 쪽이고.',
    '④ 6 → 2: 410 nm 라 축에 보이는 넷 가운데 왼쪽에서 첫째야. 397 은 축 밖이라 세지 않지.')

# ── ㉤ 잔가지 ────────────────────────────────────────────────────────
sub(by['M01966'], '자가진단: 하나는 원자의 존재 · 하나는 빛의 모습. 수소에서는 둘 다 보어가 풀었다.',
    '자가진단: 하나는 원자의 존재 · 하나는 빛의 모습 — 층위가 다르니 막는 장치도 따로다.')
sub(by['M01962'], '자가진단: 성긴 눈금은 값 읽기만 막는다. 선 자체는 그대로다.',
    '자가진단: 성긴 눈금은 숫자로 옮기는 일을 막는다. 선 자체는 그대로다.')

for n in range(1957, 1971):
    x = by[f'M0{n}']
    assert len(x['solution']) >= 300, (x['id'], len(x['solution']))
    a = x['answer']
    hit = [L for L in x['solution'].split('\n') if L.startswith('[정답] ')]
    assert len(hit) == 1 and hit[0].startswith(f'[정답] {MK[a]} {x["choices"][a]} — '), x['id']
    for k in range(4):
        if k == a:
            continue
        assert sum(L.startswith(f'{MK[k]} {x["choices"][k]}: ')
                   for L in x['solution'].split('\n')) == 1, (x['id'], k)

json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('20차 조치 완료 — M01960 · M01961 · M01962 · M01965 · M01966 · M01967 · M01970')
