def main():
    cj = json.load(open(CJ, encoding='utf-8'))
    cs = {c['id']: c for c in cj[THEME]}
    before = sum(len(c['angles']) for c in cj[THEME])

    seen = {a['a'] for c in cj[THEME] for a in c['angles']}
    n = 0
    for cid, rows in NEW.items():
        for text, kind in rows:
            if text in seen:
                raise SystemExit('이미 있는 각도글: %s' % text)
            seen.add(text)
            cs[cid]['angles'].append({'a': text, 't': kind, 'b': False})
            n += 1

    after = sum(len(c['angles']) for c in cj[THEME])
    note = NOTE % (n, after)
    for cid in NEW:
        old = cs[cid].get('note') or ''
        if '대장 2차 확장' not in old:
            cs[cid]['note'] = (old + ' ' + note).strip()

    json.dump(cj, open(CJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    used = sum(1 for c in cj[THEME] for a in c['angles'] if a.get('by'))
    print('C16 대장 2차 확장 — 각도 %d 개 추가 (%d → %d)' % (n, before, after))
    print('  소진 %d · 미소진 %d' % (used, after - used))
    for c in cj[THEME]:
        print('  %s 각도 %d (미소진 %d)'
              % (c['id'], len(c['angles']),
                 sum(1 for a in c['angles'] if not a.get('by'))))


if __name__ == '__main__':
    main()
