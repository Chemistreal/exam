def spread(ch):
    L = sorted(len(str(c)) for c in ch)
    return (L[3] - L[0]) / ((L[1] + L[2]) / 2)


def rank(it):
    L = [len(str(c)) for c in it['choices']]
    return sorted(range(4), key=lambda i: -L[i]).index(it['answer']) + 1


