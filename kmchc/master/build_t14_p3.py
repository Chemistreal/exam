    # ⑯ ★경계를 넘는 부분열 주기★ — 앞 배치 꼬리 여덟 자리에 이어 붙여 다시 본다
    import json as _j
    import os as _o
    try:
        prev = [b['answer'] for b in _j.load(
            open(_o.path.join(_o.path.dirname(_o.path.abspath(__file__)),
                              'master_bank.json'), encoding='utf-8'))[-8:]]
    except Exception:
        prev = []
    ext = prev + [x['answer'] for x in items]
    off = len(prev)
    for per, need in ((2, 4), (3, 3), (4, 2)):
        L = per * need
        for i in range(len(ext) - L + 1):
            if i + L <= off:
                continue
            if all(ext[i + k] == ext[i + k % per] for k in range(L)):
                bad.append(f'경계 포함 {i+1-off} 번 자리부터 주기 {per} 로 {need} 번 되풀이됨')

    if bad:
        print('\n  ❌ 저작 점검 실패')
        for b in bad:
            print(f'     · {b}')
