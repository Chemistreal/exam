def main():
    d = json.load(open(BANK, encoding='utf-8'))
    items = d if isinstance(d, list) else d['items']
    x = {it['id']: it for it in items}
    n = 0

    for fid, st in STEM.items():
        assert x[fid]['stem'] != st, f'{fid}: stem 이 이미 같음'
        x[fid]['stem'] = st; n += 1
    for fid, pf in PROOF.items():
        assert x[fid]['answer_proof'] != pf, f'{fid}: proof 가 이미 같음'
        x[fid]['answer_proof'] = pf; n += 1

    for fid, ch in CH.items():
        it = x[fid]
        old = it['choices']
        assert old != ch, f'{fid}: choices 가 이미 같음'
        # 정답 '위치'는 어떤 경우에도 바뀌지 않는다. 문면 변경은 아래 셋만 의도된 것이다.
        if fid not in ('M01908', 'M01913', 'M01915', 'M01916'):
            assert old[it['answer']] == ch[it['answer']], \
                f'{fid}: 정답 문면이 뜻하지 않게 바뀌었다 -> {old[it["answer"]]}'
        it['choices'] = ch
        dset(it, WRONGS[fid])
        n += 1
        # 해설의 [정답] 줄과 오답 줄 머리를 함께 갈아 끼운다
        a = it['answer']
        if old[a] != ch[a]:
            head = f"[정답] {'①②③④'[a]} {old[a]} —"
            assert head in it['solution'], f'{fid}: 해설 [정답] 줄을 못 찾음'
            it['solution'] = it['solution'].replace(
                head, f"[정답] {'①②③④'[a]} {ch[a]} —")
        lines = it['solution'].split('\n')
        for k, c in enumerate(ch):
            if k == it['answer']:
                continue
            oc = old[k]
            if oc != c:
                mark = '①②③④'[k]
                hit = [i for i, L in enumerate(lines) if L.startswith(f'{mark} {oc}:')]
                assert len(hit) == 1, f'{fid}: 해설 {mark} 줄을 못 찾음'
                lines[hit[0]] = f'{mark} {c}:' + lines[hit[0]].split(':', 1)[1]
        it['solution'] = '\n'.join(lines)

    for fid, old, new in SUB:
        it = x[fid]
        assert old in it['solution'], f'{fid}: 대상 조각 없음 -> {old[:44]}'
        assert it['solution'].count(old) == 1, f'{fid}: 조각이 둘 이상'
        it['solution'] = it['solution'].replace(old, new)
        n += 1

    for fid, key, frag in STALE:
        assert frag not in x[fid][key], f'{fid}.{key}: 옛 문면 잔존 -> {frag}'

    # ── 자체 점검 ──────────────────────────────────────────────
    ids = [f'M0{i}' for i in range(1907, 1917)]
    for fid in ids:
        it = x[fid]
        for k, c in enumerate(it['choices']):
            if k != it['answer']:
                assert f"{'①②③④'[k]} {c}:" in it['solution'], f'{fid}: 해설 {k+1} 줄 어긋남'
        assert len(it['solution']) >= 300 and '★' not in it['solution']
