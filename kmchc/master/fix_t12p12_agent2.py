def main():
    bank = json.load(open(BJ, encoding='utf-8'))
    x = {i['id']: i for i in bank}
    ids = [f'M0{i}' for i in range(1917, 1927)]

    # ── 정답 문면 ────────────────────────────────────────────────
    set_answer(x['M01918'], '전자가 도는 길은 없고 자리를 확률로만 말한다는 뜻이다')

    # ── 오답 교체 ────────────────────────────────────────────────
    swap_choice(x['M01917'], 2, '알파 입자가 뚫어 놓은 길만 비어 있다',
                '빈 자리는 알파 입자가 낸 것이 아니라 처음부터 있었어. '
                '게다가 빈 곳이 그 길뿐이라면 대부분이 그대로 지나갈 수 없지.',
                '빈 공간을 알파 입자가 만든 것으로 뒤집고 그 범위도 지나간 길로 좁힘', 'causal')

    swap_choice(x['M01918'], 1, '전자가 핵에서 멀든 가깝든 있을 확률이 같다는 뜻이다',
                '구름의 짙기는 곳마다 달라. 짙기가 다르다는 것이 바로 확률이 다르다는 뜻이지 — '
                '안쪽이 짙고 바깥으로 갈수록 옅어져.',
                '구름을 짙기가 고른 안개로 읽음 — 짙기의 차이가 곧 확률의 차이다', 'surface')

    swap_choice(x['M01919'], 3, '원자 속이 대부분 빈 공간이라고 보았기 때문이다',
                '톰슨의 그림은 원자 속을 (+)전하로 꽉 채워 두었어. '
                '빈 공간은 러더퍼드가 산란 결과에서 새로 얻은 것이지.',
                '톰슨 모형과 러더퍼드 모형의 내용을 맞바꿔 읽음', 'surface')

    swap_choice(x['M01920'], 2, '전자 들뜸 → 진동 → 회전 → 핵 스핀',
                '차례를 통째로 거꾸로 놓았어. 발문이 물은 것은 에너지가 작은 것부터야.',
                '큰 것부터로 거꾸로 배열함', 'sign')

    swap_choice(x['M01921'], 2, '빛을 쬐는 시간을 두 배로 한다',
                '두 배로 오래 쬐면 튀어나오는 전자가 두 배가 될 뿐이야. 하나하나의 몫은 그대로지.',
                '시간은 전자의 총 개수만 늘림', 'proc')

    swap_choice(x['M01923'], 2, '그 선 하나만 출발 준위가 n = ∞ 인 전이이기 때문이다',
                '122 nm 는 2 에서 1 로 떨어질 때 나오는 빛이야. 출발이 n = ∞ 인 전이는 '
                '라이먼 한계인 91.1 nm 라 이 다섯 선에는 없어.',
                '출발 준위와 도착 준위를 뒤바꿔 읽음 — 122 nm 는 2→1 이다', 'surface')

    # ── M01926 전면 개작 ─────────────────────────────────────────
    m = x['M01926']
    assert m['answer'] == 1, 'M01926: 개작 전 정답 자리가 ②가 아니다'
    m['stem'] = P26_STEM
    m['choices'] = list(P26_CHOICES)
    m['answer'] = 2
    m['solution'] = P26_SOL
    m['answer_proof'] = P26_PROOF
    m['distractors'] = [dict(d) for d in P26_DIST]
    m['skill'] = '표 안에 숨은 불변량으로 어긋난 줄 잡아내기'
    m['device'] = '네 줄 가운데 잘못 옮긴 한 줄'
    m['calc_check'] = '(3/20)×486 = 72.9 ≠ 91.1'
    m['scenario'] = '불변량을 스스로 찾아 어긋난 줄을 가려내기'
    m['objective'] = ('자료 여러 줄에서 한결같이 성립하는 관계를 스스로 찾아 '
                      '그 관계를 벗어난 줄을 가려낼 수 있는지 확인')

    # ── 본문·근거 치환 ───────────────────────────────────────────
    miss = [(f, k, a[:28]) for f, k, a, _ in REPL if a not in x[f][k]]
    assert not miss, f'치환 대상 없음: {miss}'
    for f, k, a, b in REPL:
        x[f][k] = x[f][k].replace(a, b, 1)

    # ── 자기 검사 ────────────────────────────────────────────────
    for fid in ids:
        it = x[fid]
        sol = it['solution']
        for k, c in enumerate(it['choices']):
            if k == it['answer']:
                assert f'[정답] {MK[k]} {c} —' in sol, f'{fid}: [정답] 줄 어긋남'
            else:
                assert f'{MK[k]} {c}:' in sol, f'{fid}: {k + 1} 번 줄 어긋남'
        assert len(it['distractors']) == 3, f'{fid}: 오답 주석 3개가 아님'
        assert sorted(d['opt'] for d in it['distractors']) == \
            sorted(k for k in range(4) if k != it['answer']), f'{fid}: 오답 자리 어긋남'
        assert '★' not in it['stem'] and '★' not in sol, f'{fid}: 강조 기호 잔존'
        assert '**' not in sol, f'{fid}: 굵게 기호 잔존'
        assert len(sol) >= 300, f'{fid}: 해설이 300자 미만'

    # M01926 개작이 남긴 옛 문면이 없는가
    m = x['M01926']
    for gone in ('91.1 k·nm', '364.6 k·nm', '가장 가까운 것은'):
        assert gone not in m['stem'] and gone not in m['solution'], f'M01926: 옛 문면 잔존 {gone}'

    json.dump(bank, open(BJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('P12 2차 조치 완료 — M01926 개작 · 정답 문면 1 · 오답 교체 6 · 본문/근거 치환 7')
    for fid in ids:
        L = [len(c) for c in x[fid]['choices']]
        s = sorted(L)
        sp = (s[3] - s[0]) / ((s[1] + s[2]) / 2)
        r = sorted(range(4), key=lambda i: -L[i]).index(x[fid]['answer']) + 1
        print(f'  {fid} {L} 산포{sp:.2f} 순위{r}')


if __name__ == '__main__':
    main()
