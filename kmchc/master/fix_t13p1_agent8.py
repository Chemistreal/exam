# -*- coding: utf-8 -*-
"""T13 P1 (M01971~M01980) 층5 순회 — 8차 조치 (서술만 · 화학 주장·선지·발문 불변).

6차 순회에서 **세 검증자가 모두 도착해 동시에 0 건**이 되었다.

    solver      10/10 일치 · 전원 확신 '확실' · 자족성 전원 '충분'
                형태 단서 1건(M01978 최빈 조합)이나 스스로 "위험도 낮음 ·
                대안은 새 값을 지어내야 한다" 고 적었다 — 이번 회차의 멈춤
                규칙이 정확히 그 경우다.
    defender    ★F2 실패 후보 없음★ 오답 서른을 네 경로로 다 밀어 보았으나
                "독립 진술로 읽으면 참이면서 발문이 막지 못하는" 선지가 하나도
                없다. M01978·M01979 는 ★발문의 한정구가 F2 를 막고 있는 유일한
                장치★ 이므로 그 두 구절을 건드리지 말라고 못 박았다.
    factchecker ★사실 오류 없음★ 정원·양자수·홀전자·산술·번호 상보성 전부 통과.
                오답 반박의 산술이 실제로 그 선지 값을 낳는지까지 재확인되었다.

그러므로 이 회차는 **닫는 회차**이고, 손대는 것은 factchecker 가 남긴 △ 가운데
★화학 주장을 하나도 건드리지 않는 두 문장★ 뿐이다. 선지·발문·정답·오답 메타는
한 글자도 바뀌지 않는다.

────────────────────────────────────────────────────────────────
㉠ M01977 — 크기와 값이 한 문장에 섞였다
────────────────────────────────────────────────────────────────
"에너지의 크기 자체는 핵전하의 제곱에 비례해 수소보다 훨씬 낮다" — E = −13.6Z²/n²
이므로 **절댓값이 Z² 에 비례**하고 **값은 더 낮다.** 두 진술이 한 문장에 겹쳐
"에너지가 Z² 에 비례해 낮아진다" 로 읽힐 여지가 있다. 두 문장으로 가른다.

────────────────────────────────────────────────────────────────
㉡ M01972 — '적다(기재)' 와 '적다(少)' 가 다시 겹쳤다
────────────────────────────────────────────────────────────────
"전자를 정원보다 많이 적은 경우" — 4차에서 발문의 같은 표현을 고쳤는데,
7차의 전면 재구성에서 **해설 본문에 같은 어순이 되살아났다.** '많게 적어 놓은'
으로 되돌린다. ★한 번 고친 표현이 재구성 과정에서 되살아나는 것을 이 배치에서
두 번 겪었다 — 재구성할 때는 그 문항의 옛 지적 목록을 함께 펴 놓을 것.★

────────────────────────────────────────────────────────────────
남기는 것 (마감 부채 · WATCH 에 기록)
────────────────────────────────────────────────────────────────
· M01971 해설의 "전자가 하나뿐이면 같은 껍질의 s·p·d 가 서로 에너지가 같아" 가
  M01977 의 정답 논리와 겹친다(factchecker 3·5·6차 연속). 반증도 발문 누설도
  아니고 **같은 단원의 공통 원리**라 지울 수 없다. 두 문항을 같은 시험지에서
  이웃하게 두지 않는 **출제 배열 부채**로 남긴다.
· 죽은 선지 일곱(7차의 멈춤 규칙 참조) — 문항당 하나이고 실측 0.422 구간이다.
· (ㄴ) 우회로 다섯 — P1 은 (ㄴ)를 필수 게이트로 올리기 전에 저작한 배치다.
· M01978 최빈 조합 형태 단서 — solver 스스로 대안이 새 값을 지어내야 한다고
  적었다. 5차의 거리 서사가 바로 그렇게 만들어진 사실 오류였다.
"""
import json

BANK = 'master/master_bank.json'
MK = ['①', '②', '③', '④']

bank = json.load(open(BANK, encoding='utf-8'))
by = {x['id']: x for x in bank}
before = {i: (json.dumps(by[f'M0{i}']['choices'], ensure_ascii=False),
              by[f'M0{i}']['stem'], by[f'M0{i}']['answer'],
              json.dumps(by[f'M0{i}']['distractors'], ensure_ascii=False))
          for i in range(1971, 1981)}


def sub(it, old, new, n=1):
    assert it['solution'].count(old) == n, f"{it['id']}: '{old[:40]}' {it['solution'].count(old)}회"
    it['solution'] = it['solution'].replace(old, new)


# ── ㉠ M01977 : 절댓값과 값을 가른다 ─────────────────────────────────────
sub(by['M01977'],
    '다만 같은 것은 갈라짐이 없다는 점뿐이고, 에너지의 크기 자체는 핵전하의 제곱에 비례해 '
    '수소보다 훨씬 낮다는 것도 함께 챙겨 두자.',
    '다만 같은 것은 갈라짐이 없다는 점뿐이야. 핵전하가 클수록 전자가 더 세게 붙들리니 '
    '안정한 정도는 핵전하의 제곱에 비례해 커지고, 그래서 준위의 값 자체는 수소보다 훨씬 '
    '아래에 놓여. 꼴이 같다는 것과 값이 같다는 것은 다른 이야기지.')

# ── ㉡ M01972 : '적다' 의 두 뜻이 겹친 어순 ──────────────────────────────
sub(by['M01972'], '오비탈이 멀쩡히 있는데 전자를 정원보다 많이 적은 경우고',
    '오비탈이 멀쩡히 있는데 전자를 정원보다 많게 적어 놓은 경우고')

# ── 불변 검사 : 선지·발문·정답·오답 메타가 한 글자도 바뀌지 않았는가 ─────
for i in range(1971, 1981):
    it = by[f'M0{i}']
    now = (json.dumps(it['choices'], ensure_ascii=False), it['stem'], it['answer'],
           json.dumps(it['distractors'], ensure_ascii=False))
    assert now == before[i], f'M0{i}: 서술만 고치는 회차인데 구조가 바뀌었다'
    assert len(it['solution']) >= 300, (i, len(it['solution']))
    a = it['answer']
    head = it['solution'].split('\n\n')[1]
    assert (MK[a] + '가 옳아' in head) or (MK[a] + '이 옳아' in head), it['id']
    for k in range(4):
        assert (MK[k] + ' ' + it['choices'][k]) in it['solution'], it['id']
    assert '★' not in it['stem'], it['id']

json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('8차 조치 완료 — 서술 2건 (M01977 크기·값 분리 · M01972 어순). 구조 불변 확인.')
