STALE = [('M01873','미세 구조'), ('M01873','반발을 넣어 준다 해도'),
         ('M01876','전하 없는 무언가'), ('M01870','63 kJ'),
         ('M01874','자외선에서 가시광선, 적외선 차례로')]


def main():
    bank = json.load(open(BANK, encoding='utf-8'))
    items = bank if isinstance(bank, list) else bank['items']
    idx = {x['id']: x for x in items}
    n = 0
    for fid, ch in CH_SET.items():
        assert len(ch) == 4
        idx[fid]['choices'] = ch; n += 1
    for (fid, opt), err in DIST_SET.items():
        for dd in idx[fid]['distractors']:
            if dd['opt'] == opt:
                dd['error'] = err; n += 1
    for fid, (lead, cor, wmap, diag) in SOL.items():
        c, a = idx[fid]['choices'], idx[fid]['answer']
        idx[fid]['solution'] = (f"{lead}\n\n[정답] {CIR[a]} {c[a]} — {cor}\n\n"
                                + "\n".join(f"{CIR[i]} {c[i]}: {wmap[c[i]]}" for i in range(4) if i != a)
                                + f"\n\n자가진단: {diag}"); n += 1
    for fid, old, new in SOL_REPL:
        s = idx[fid]['solution']; assert old in s, f"{fid} | {old[:40]}"
        idx[fid]['solution'] = s.replace(old, new); n += 1
    for fid, add in WATCH.items():
        v = idx[fid].setdefault('verified', {})
        v['watch'] = (v.get('watch', '') + ' / ' + add).strip(' /'); n += 1
    for fid in ('M01873',):
        idx[fid]['solution'] = idx[fid]['solution'].replace('★', '')

    print(f"조치 {n}곳\n")
    bad, ranks = [], {}
    for fid, ph in STALE:
        if ph in idx[fid]['solution']:
            print(f"⛔ STALE {fid} '{ph}'"); bad.append('STALE')
    for i in range(1867, 1877):
        fid = f'M0{i}'; itx = idx[fid]
        L = [len(str(x)) for x in itx['choices']]; sl = sorted(L)
        r = sorted(range(4), key=lambda k: (-L[k], k)).index(itx['answer']) + 1
        sp = (sl[3]-sl[0])/((sl[1]+sl[2])/2); sol = itx['solution']
        ranks[r] = ranks.get(r, 0) + 1
        print(f"{fid} {itx['track']} 답{CIR[itx['answer']]} 길이{L} 순위{r} 산포{sp:.2f} 해설{len(sol)}자")
        if sp > 0.25 and sl[1] >= 8: print('  ⛔ G3b'); bad.append('G3b')
        if L[itx['answer']] == max(L) and L.count(max(L)) == 1: print('  ⛔ G3 최장'); bad.append('G3')
        if L[itx['answer']] == min(L) and L.count(min(L)) == 1: print('  ⛔ G3 최단'); bad.append('G3')
        if len(sol) < 300: print('  ⛔ G9'); bad.append('G9')
        if '**' in sol or '★' in sol: print('  ⛔ G10'); bad.append('G10')
        for dd in itx['distractors']:
            if CIR[dd['opt']] not in sol: print(f"  ⛔ G9 오답 {CIR[dd['opt']]} 미언급"); bad.append('G9')
    print('\n길이순위', dict(sorted(ranks.items())))
    for r, cnt in ranks.items():
        if cnt > 4: print(f'  ⛔ G3c {r} 가 {cnt}/10'); bad.append('G3c')
    if bad: print('\n⛔ ' + ', '.join(sorted(set(bad)))); sys.exit(1)
    print('✅ 규칙 위반 없음')
    if '--apply' in sys.argv:
        json.dump(bank, open(BANK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('✅ 반영 완료')


if __name__ == '__main__':
    main()
