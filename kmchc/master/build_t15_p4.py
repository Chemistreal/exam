_ANON = re.compile(r'원소 (?:가|나|다|A|B|C)(?=의|와|과|는|은|를|이|가|,|·|\s|$)')


def local_checks(items):
    """T15 지역 저작 점검 — P3 의 것을 그대로 잇는다(⑧ 겹침 · ⑨ 길이 포함)."""
    bad = []
    ALLOWED = {'proc', 'sign', 'surface', 'conserv', 'unit', 'scale', 'overgen', 'causal'}
    for x in items:
        ts = [w['type'] for w in x['distractors']]
        if len(set(ts)) < 3:
            bad.append(f"{x['id']} 오답 유형이 겹친다 — {ts}")
        for t in ts:
            if t not in ALLOWED:
                bad.append(f"{x['id']} 허용되지 않은 유형 {t}")
        # ★★이 검사는 P3 3차까지 한 번도 울 수 없었다★★ — sol() 이 해설 끝에 붙이는
        #   단평 블록이 오답 문면을 ★글자 그대로★ 되풀이하므로 `in x['solution']` 은 언제나
        #   참이었다. 해설 산문에서 인용이 흐트러져도 검사는 통과한다(defender 와
        #   factchecker 가 각각 두 자리를 손으로 잡아 냈다). ▸ ★산문 문단만 본다.★
        prose = x['solution'].split('\n\n')[1] if '\n\n' in x['solution'] else x['solution']
        #   ▸ 산문은 간접 인용이라 종결어미가 바뀐다('…때문이다' → '…때문이라고 했어').
        #     ★어미를 뗀 몸통★ 이 그대로 있는지만 본다 — 몸통이 어긋나면 인용이 흐트러진 것이다.
        for w in x['distractors']:
            core = re.sub(r'(이)?다$', '', x['choices'][w['opt']]).strip()
            if core not in prose:
                bad.append(f"{x['id']} {w['opt'] + 1}번 오답 인용이 해설 산문과 어긋난다")
        if not re.search(r'[①②③④](가|이)? 옳아', x['solution']):
            bad.append(f"{x['id']} 해설에 정답 확정 어구가 없다")
        J = ('를|을|은|의|으로|로|에서|에|과|보다|처럼|까지|부터|이고|이다|이야|이라|이지')
        for f in ('stem', 'solution', 'answer_proof'):
            for m in re.finditer(rf'(?<=[가-힣]) ({J})(?=[\s,.·)?!]|$)', x[f]):
                bad.append(f"{x['id']} {f} 조사 앞 빈칸 — {x[f][max(0, m.start() - 14):m.end()]!r}")
        tails = [c.strip()[-3:] for c in x['choices']]
        for t in set(tails):
            if tails.count(t) == 3 and tails[x['answer']] != t:
                bad.append(f"{x['id']} 어미 「{t}」 셋 대 정답 하나 — 꼴로 갈린다")

        def tk(s):
            return {w for w in re.findall(r'[가-힣]{2,}', s)}
        for i in range(4):
            for j in range(i + 1, 4):
                if x['answer'] in (i, j):
                    continue
                a, b = tk(x['choices'][i]), tk(x['choices'][j])
                if a and b and len(a & b) / len(a | b) >= 0.62:
                    bad.append(f"{x['id']} 오답 {i + 1}·{j + 1} 자카드 "
                               f"{len(a & b) / len(a | b):.2f}")
    for x in items:
        s = x['stem']
        if '톱니' in s and '세로축' not in s:
            bad.append(f"{x['id']} 톱니를 쓰면서 세로축을 적지 않았다")
        anon = _ANON.search(s)
        named = re.search(r'(리튬|베릴륨|붕소|탄소|질소|산소|플루오린|네온|나트륨|마그네슘|염소'
                          r'|칼륨|알루미늄|헬륨|수소|아르곤|브로민|Li|Be|B\b|C\b|N\b|O\b|F\b|Ne|Na)', s)
        if anon and named:
            bad.append(f"{x['id']} 익명 원소와 원소 이름을 함께 인쇄했다 — "
                       f"{anon.group(0)!r} · {named.group(0)!r}")
        if '크게 뛰' in s or '급증' in s:
            if not re.search(r'비\(뒤 ÷ 앞\)|비로 재|앞까지의 개수', s):
                bad.append(f"{x['id']} 급증의 셈법을 발문이 정하지 않았다")
    g = sum(1 for x in items if x['track'] == '일반')
    if g < 7:
        bad.append(f'일반 {g}제 — P4 는 일반 7 이상')
    e = sum(1 for x in items if x['difficulty'] == '쉬움')
    if e > 3:
        bad.append(f'쉬움 {e}제 — 상한 3')

    # ⑧ ★정답이 발문과의 어휘 겹침 유일 최다이면 실패★ (P1 이 값을 치른 자리)
    for x in items:
        st = set(re.findall(r'[0-9A-Za-z가-힣]{2,}', x['stem']))
        ov = [len(set(re.findall(r'[0-9A-Za-z가-힣]{2,}', c)) & st) for c in x['choices']]
        if ov[x['answer']] == max(ov) and ov.count(max(ov)) == 1:
            bad.append(f"{x['id']} 정답이 발문과의 어휘 겹침 최다(유일) — {ov}")

    # ⑨ ★선지 길이 — 정답이 유일 최장/최단이거나 산포가 0.25 를 넘으면 실패★ (P3 이 값을 치렀다)
    for x in items:
        L = [len(c) for c in x['choices']]
        a = L[x['answer']]
        if a == max(L) and L.count(a) == 1:
            bad.append(f"{x['id']} 정답이 유일 최장 — {L}")
        if a == min(L) and L.count(a) == 1:
            bad.append(f"{x['id']} 정답이 유일 최단 — {L}")
        sp = (max(L) - min(L)) / (sum(L) / len(L))
        if sp > 0.25:
            bad.append(f"{x['id']} 선지 길이 산포 {sp:.2f} > 0.25 — {L}")

    print(f"  ▸ 배치 요약 — 유형 {sorted({w['type'] for x in items for w in x['distractors']})}")
    if bad:
        print('\n  ❌ 저작 점검 실패')
        for b in bad:
            print('     ·', b)
        raise SystemExit(1)
    print('  ✅ 저작 점검 통과')


