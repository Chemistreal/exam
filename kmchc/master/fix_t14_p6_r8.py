# ── ★기계로 센다★ ─────────────────────────────────────────────────────────────
body = '\n'.join(l for l in src.split('\n') if not l.strip().startswith('#'))
body = body[body.index('def build('):]

BAN = ['요인이 맞설', '두 요인이 상쇄', '2·3주기라면', '가로축으로 삼고',
       '자료에 두 부등식만', ' 를 ', ' 을 ', ' 도 ']
for w in BAN:
    assert w not in body, f'옛 낱말이 남았다: {w!r}'


def seg(mid):
    i = body.index(f"T.mk('M{mid}'")
    j = body.find("T.mk('M02", i + 10)
    return re.sub(r"'\s*\n\s*'", '', body[i:j if j != -1 else len(body)])


